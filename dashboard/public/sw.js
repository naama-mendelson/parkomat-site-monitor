// sw.js — Service Worker להתראות תקלה. **push ו-notificationclick בלבד.**
//
// ============================================================
// ⚠️ אין כאן fetch handler, ואסור שיהיה
// ============================================================
// Service Worker שמיירט בקשות רשת הוא מה שמגיש למשתמש גרסה ישנה אחרי
// פריסה. בפרויקט הזה זה כבר קרה בלי SW בכלל: הבנדל שהוגש היה בן יומיים,
// לא הכיל אף אחת מהכתיבות הישירות, והכפתור פשוט לא עבד — בלי שום הודעת
// שגיאה. הוספת caching הייתה מוסיפה שכבה שלישית לאותו כשל, והפעם כזו
// ששורדת גם רענון.
//
// בלי fetch handler כל בקשה עוברת לרשת כרגיל, בדיוק כאילו ה-SW לא קיים.
// הוא נוכח אך ורק כדי לקבל push כשהאפליקציה סגורה — וזה הדבר היחיד
// שאי אפשר לעשות בלעדיו.

// ============================================================
// skipWaiting + clients.claim — אחרת עדכון לא מגיע לעולם
// ============================================================
// ⚠️ ברירת המחדל: SW חדש ממתין עד שכל הלשוניות של האתר ייסגרו. **באפליקציה
// מותקנת זה לא קורה** — היא נשארת פתוחה ברקע שבועות. הגרסה החדשה הייתה
// ממתינה בלי סוף, וכל תיקון כאן לא היה מגיע לאף מכשיר.
self.addEventListener("install", () => self.skipWaiting());
self.addEventListener("activate", (e) => e.waitUntil(self.clients.claim()));

// ============================================================
// קבלת ההתראה
// ============================================================
// ⚠️ המטענה נקראת בתוך try: הודעה פגומה (או push ריק, שדפדפנים שולחים
// לבדיקת חיים) הייתה מפילה את המטפל, ואז **לא מוצגת שום התראה** — כולל
// האמיתיות שאחריה. עדיף להציג כותרת גנרית מאשר לשתוק.
self.addEventListener("push", (event) => {
  let d = {};
  try { d = event.data ? event.data.json() : {}; } catch { d = {}; }

  const siteName = d.siteName || d.code || "אתר";
  const fault = d.faultText || "לא התקבל תיאור מהבקר";

  event.waitUntil(
    self.registration.showNotification(`תקלה · ${siteName}`, {
      body: fault,
      icon: "/icon-192.png",
      badge: "/icon-192.png",
      dir: "rtl",
      lang: "he",
      // ⚠️ tag לפי קוד האתר: התראה חדשה על אותו אתר **מחליפה** את הקודמת
      // במקום להצטבר. אתר שמהבהב היה מייצר ערימה שצריך לנקות ידנית.
      tag: d.code ? `fault-${d.code}` : "fault",
      // ⚠️ renotify עם tag: בלעדיו ההחלפה שקטה לגמרי — בלי צליל ובלי
      // רטט — ותקלה חדשה הייתה מתחלפת בלי שאיש ישים לב.
      renotify: true,
      // ⚠️ requireInteraction: ההתראה נשארת עד שנוגעים בה. תקלה בחניון
      // אינה הודעה שאפשר לפספס כי הסתכלת על המסך בשנייה הלא נכונה.
      requireInteraction: true,
      // הצליל הוא של מערכת ההפעלה — Web Push אינו יכול לשאת קובץ צליל.
      // silent: false מוודא שלא נשתיק אותו בטעות.
      silent: false,
      data: { url: d.code ? `/?site=${encodeURIComponent(d.code)}` : "/" },
    }),
  );
});

// ============================================================
// לחיצה — פותחת את כרטיס האתר
// ============================================================
// ⚠️ מחפש חלון פתוח לפני שפותח חדש. בלי זה כל לחיצה הייתה פותחת עוד
// לשונית, ואחרי יום עמוס נשארות עשר עותקים של אותו דשבורד.
//
// ⚠️ ו-navigate() על חלון קיים ולא רק focus(): החלון עשוי לעמוד על אתר
// אחר לגמרי, ולהתמקד בו בלי לנווט היה נראה כאילו ההתראה הובילה למקום
// השגוי.
self.addEventListener("notificationclick", (event) => {
  event.notification.close();
  const url = event.notification.data?.url || "/";

  event.waitUntil((async () => {
    const all = await self.clients.matchAll({ type: "window", includeUncontrolled: true });
    for (const c of all) {
      if (new URL(c.url).origin === self.location.origin) {
        await c.navigate(url).catch(() => {});
        return c.focus();
      }
    }
    return self.clients.openWindow(url);
  })());
});
