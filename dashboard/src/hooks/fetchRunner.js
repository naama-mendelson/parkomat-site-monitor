// hooks/fetchRunner.js — מריץ שליפה אחת בכל רגע, ומאחד את מה שהצטבר.
//
// ============================================================
// ⚠️ למה זה קובץ נפרד ולא נשאר בתוך ה-hook
// ============================================================
// הכשל שהוא מונע הוא **שקט**: שליפה שמגיעה בזמן שליפה אחרת יכולה
// להיעלם, והמסך ימשיך להציג נתון ישן בלי שום סימן. אין כאן DOM ואין
// מריץ בדיקות של React, ולכן לוגיקה שיושבת בתוך ה-hook פשוט אינה
// נבדקת — וקוד שאינו נבדק, שהכשל שלו שקט, הוא הצירוף הגרוע ביותר.
//
// כפונקציה טהורה היא נבדקת ב-node:test כמו כל דבר אחר.
//
// ============================================================
// מה זה פותר
// ============================================================
// נמדד בדפדפן על הייצור: **כל שליפה של מסך המנהל הכללי רצה פעמיים**.
// המסך נטען, ותוך שניות מגיעה הודעת SSE, `dataVersion` עולה, והשליפה
// מתחילה שוב **בזמן שהראשונה עדיין באוויר**. שנים-עשר בקשות מקבילות
// מאיטות זו את זו: site_stats נמדד 1.58s בדפדפן מול 0.5s לבד.

/**
 * @param fetcher    (key) => Promise — השליפה עצמה
 * @param getLatest  () => key — מה המפתח הנוכחי. ⚠️ פונקציה ולא ערך:
 *                   הוא משתנה בזמן שהשליפה באוויר, וזו כל הנקודה.
 * @param on         { data, error, loading } — קריאות חזרה
 */
export function createRunner({ fetcher, getLatest, on }) {
  let inFlight = false;
  let pending = null;

  async function run(key) {
    // ⚠️ כבר יש שליפה — לא פותחים שנייה. מסמנים, והיא תרוץ **פעם אחת**
    // כשהנוכחית תיגמר. בלי זה שני הגלים חופפים.
    if (inFlight) { pending = key; return; }

    inFlight = true;
    on.loading(true);
    on.error(null);

    try {
      const r = await fetcher(key);
      // ⚠️ ההשוואה היא למפתח **הנוכחי**, ולא לדגל של מי שהתחיל. גרסה
      // קודמת בדקה דגל `cancelled` של ה-effect שהתחיל — וכשהוא בוטל,
      // הריצה הממתינה נבדקה מולו ונזרקה. הרענון נעלם בשקט.
      if (key === getLatest()) on.data(r);
    } catch (e) {
      if (key === getLatest()) on.error(e.message || String(e));
    } finally {
      inFlight = false;
      if (key === getLatest()) on.loading(false);

      const next = pending;
      pending = null;
      // רק אם היא עדיין רלוונטית — אחרת נריץ שליפה כבדה עבור פילטר
      // שהמשתמשת כבר עזבה.
      if (next && next === getLatest()) run(next);
    }
  }

  return {
    run,
    // חשוף לבדיקות בלבד — לא לשימוש מהרכיבים.
    _state: () => ({ inFlight, pending }),
  };
}
