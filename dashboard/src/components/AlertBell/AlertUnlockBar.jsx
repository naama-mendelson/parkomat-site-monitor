// ⚠️ **וכל מגע במסך משחרר, לא רק הפס.** useAlertAudio מאזין ל-pointerdown
// ול-keydown ברמת החלון, ולכן הפס נעלם ברגע שנוגעים במשהו — הוא אינו
// "עוד כפתור שצריך למצוא" אלא תזכורת שמתפוגגת מעצמה.
