// הנוהל שמתאים לתקלה — קופץ על הכרטיס ברגע שהיא מופיעה.
//
// ============================================================
// ⚠️ מה מוצג, ומה **במכוון** לא
// ============================================================
// מוצג: שהנוהל קיים, שמו, ואזהרת הבטיחות שלו. ומשם כפתור אל הנוהל עצמו.
//
// ⚠️ **ולא מוצגים "הצעדים הראשונים", וזו מדידה ולא קמצנות.** שלושת הצעדים
// הפותחים זהים כמעט בכל נוהל — `פתח טים` מופיע ב-304 מתוך 319, `פתח מצלמות`
// ב-303 — כי כך נכתבו: פתח שליטה מרחוק, צלם מסכים, ואז טפל. שורה כזו על
// הכרטיס נקראת כהוראה, נכונה לכל תקלה, ואינה מלמדת דבר. ניסיתי גם "הצעד
// המבחין הראשון" (הראשון שאינו נפוץ) — והוא יצא `תפריט סגור`. גם boilerplate.
//
// ⚠️ **אזהרת הבטיחות היא ההפך הגמור.** היא קיימת ב-148 מתוך 319 והיא ספציפית
// ממש: *"חובה לוודא במצלמות שאין אנשים בחניון וציוד שהושאר בפיר ובקומות"*.
// זה הדבר היחיד שחייב להיקרא **לפני** שנוגעים במשהו, ולכן הוא זה שקופץ.
//
// ============================================================
// ⚠️ ולמה אין כאן שליפה מהשרת
// ============================================================
// הדשבורד מוגש מ-Cloudflare ב-https, ו-FixFlow רצה ב-http ברשת המשרד. הדפדפן
// חוסם `fetch` בין השניים. לכן הכותרות והאזהרות **נוסעות עם הבנייה** (87KB),
// וההתאמה נעשית בדפדפן. עצי הטיפול נשארו בחוץ — הם 3.7MB.
import React from "react";
import { fixflowSolutionFor, FIXFLOW_ENABLED } from "../../services/fixflow.js";
import { useSavedAssignment } from "./savedAssignment.js";
import "./FixFlowLink.css";

export default function FixFlowSolution({ site, faultText }) {
  // ⚠️ השיוך שנשמר זה עתה — אחרת אזהרת הבטיחות הייתה של הספרייה הקודמת.
  // ההוק לפני כל `return` מוקדם.
  const effective = useSavedAssignment(site);
  if (!FIXFLOW_ENABLED || !faultText) return null;

  const hit = fixflowSolutionFor(effective, faultText);
  // ⚠️ אין התאמה — אין פאנל, ובשקט. הכפתור הרגיל "תקלות ופתרונות" נשאר,
  // והמוקדן מגיע לרשימה. פאנל שאומר "לא נמצא נוהל" היה רעש קבוע על 53%
  // מהתקלות, ומי שרואה אותו פעמיים מפסיק לקרוא גם את זה שכן נמצא.
  if (!hit) return null;

  return (
    <div className={`ffs${hit.warning ? " ffs-warn" : ""}`}>
      <div className="ffs-head">
        <span className="ffs-icon" aria-hidden="true">📖</span>
        <span className="ffs-title">{hit.title}</span>
      </div>

      {/* ⚠️ האזהרה לפני הכפתור, ולא אחריו. מי שילחץ ויעבור ל-FixFlow יקרא
          אותה שם ממילא; מי שלא ילחץ — וזה הרוב באירוע לחוץ — צריך לראות
          אותה **כאן**, לפני שהוא ניגש למתקן. */}
      {hit.warning && (
        <p className="ffs-warning">
          <span aria-hidden="true">⚠️</span> {hit.warning}
        </p>
      )}

      {/* ⚠️ **אין כאן קישור, ובמכוון.** הכפתור "הנוהל לתקלה הזו" שמתחת
          מוביל בדיוק לאותו מקום, ושני קישורים צמודים לאותו יעד הם בחירה
          מיותרת בדיוק ברגע שאין בו זמן לבחור. הפאנל הוא ההקשר; הכפתור הוא
          הפעולה. */}
    </div>
  );
}
