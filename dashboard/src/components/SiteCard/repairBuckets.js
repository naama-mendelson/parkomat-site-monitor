//
// ============================================================
// ⚠️ מה שנשאר מהפס, ולמה
// ============================================================
// כאן ישב `RepairStrip` — פס יחסי שחילק את התקלות לשלוש דרגות ברוחב.
// הוא הוחלף ב-`RepairChart`, שבו כל תקלה היא מקל וגובהו הוא המשך: הפס
// ענה על "כמה מכל דרגה", והגרף עונה על "כמה חמור", וזו השאלה כאן —
// 10% התקלות הארוכות מהוות 68% מזמן התקלה.
//
// ⚠️ הסיווג עצמו נשאר, כי הוא מה שקובע את **צבע** כל מקל ואת הפס בקצה
// כל שורה בפאנל. הגבולות זהים ל-`site_stats`; שכפולם היה נפרד ביום
// שאחד ישתנה, והתסמין הוא מקל שצבוע אחרת מהשורה שלו.

/** אותם גבולות כמו ב-site_stats (בדקות). */
export const QUICK_MAX = 15;
export const LONG_MIN = 60;

export const BUCKETS = [
  { key: "quick",  label: "עד ¼ שעה" },
  { key: "medium", label: "עד שעה" },
  { key: "long",   label: "מעל שעה" },
];

/** דקות → דרגה. */
export function bucketOf(min) {
  if (min > LONG_MIN) return BUCKETS[2];
  if (min > QUICK_MAX) return BUCKETS[1];
  return BUCKETS[0];
}
