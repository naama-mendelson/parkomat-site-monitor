// services/pageAll.js — שליפת כל השורות מ-PostgREST, בעמודים.
//
// ============================================================
// ⚠️ Supabase חוסם כל בקשה ב-1,000 שורות. קשיח.
// ============================================================
// זה **לא** מה שנראה מהקוד. הכתיבה הטבעית היא `.limit(20000)`, והיא נראית
// כאילו היא עובדת — אין שגיאה, אין אזהרה, וחוזרות שורות. נמדד מול הפרויקט
// החי:
//
//     בלי limit        -> 1000 שורות   content-range: 0-999/*
//     limit=20000      -> 1000 שורות   content-range: 0-999/*
//     Range: 0-4999    -> 1000 שורות   content-range: 0-999/*
//     Range: 1000-1999 -> 1000 שורות   content-range: 1000-1999/*
//
// כלומר `limit` פשוט מתעלמים ממנו, ו**רק Range מזיז את החלון**.
//
// ============================================================
// למה זה היה מסוכן במיוחד כאן
// ============================================================
// המסלולים הישירים נבנו עם FETCH_CAP = 20000 וגלאי חריגה `length >= CAP`.
// מכיוון שהתשובה תמיד 1,000, הגלאי **לעולם לא היה נורה** — הדשבורד היה מציג
// שבוע חלקי, עם "סה\"כ" שנראה סמכותי, בלי שום סימן שמשהו חסר.
//
// נתפס רק כי tools/parity-insights.js הופנה ל-PostgREST **האמיתי** במקום
// לסימולציה: 2,085 שורות בשרת מול 1,000 ב-PostgREST. סימולציה לא הייתה
// תופסת את זה לעולם, כי הקאפ אינו בקוד שלנו.

/** גודל עמוד. 1,000 הוא התקרה של Supabase — בקשה גדולה יותר לא תעזור. */
const PAGE = 1000;

/**
 * מריץ את הבורר שוב ושוב עם חלונות Range עד שנגמרות השורות.
 *
 * @param build (from, to) => PostgrestFilterBuilder — חייב להחזיר בורר **חדש**
 *              בכל קריאה; בורר של supabase-js אינו ניתן לשימוש חוזר.
 * @param cap   תקרת ביטחון. הגעה אליה מסומנת ב-capped ואינה מושתקת.
 * @returns {{ rows, capped }}
 */
export async function pageAll(build, cap = 20000) {
  const rows = [];

  for (let offset = 0; offset < cap; offset += PAGE) {
    const { data, error } = await build(offset, offset + PAGE - 1);
    if (error) {
      throw new Error(
        error.code === "42501" ? "אין הרשאת קריאה — נדרשת התחברות" : error.message
      );
    }

    rows.push(...(data || []));

    // עמוד קצר מהמלא = הגענו לסוף. זה הסימן היחיד האמין — Supabase אינו
    // מחזיר את הסך הכולל אלא אם מבקשים count, וזו שאילתה נוספת בכל עמוד.
    if (!data || data.length < PAGE) return { rows, capped: false };
  }

  // ⚠️ נגמרה התקרה ועדיין יש שורות. מחזירים capped כדי שה-UI יאמר "חלקי"
  // במקום להציג "סה\"כ" שקטן מהאמת — בדיוק הכשל שהקובץ הזה קיים בשבילו.
  return { rows, capped: true };
}
