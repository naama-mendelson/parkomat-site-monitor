import { supabase, isSupabaseConfigured } from "./supabase";

/**
 * מחזיר `{ alive, ageSeconds, lastBeatAt, unknown }`.
 *
 * ⚠️ `unknown` נבדל מ-`alive:false` בכוונה. אין אף שורה ב-`alive` פירושו
 * שאף אתר עוד לא חובר ישירות — להכריז על זה "מת" היה מציג אזהרה אדומה על
 * מצב התחלתי תקין, כלומר בדיוק סוג ההתראה שגורם לאנשים להפסיק להאמין למסך.
 */
export async function fetchServerHealthDirect(staleAfterSeconds = 300) {
  if (!isSupabaseConfigured) throw new Error("Supabase אינו מוגדר בדשבורד");

  const { data, error } = await supabase
    .from("alive")
    .select("seen_at")
    .order("seen_at", { ascending: false })
    .limit(1);
  if (error) throw new Error(error.message || "בדיקת הפעימות נכשלה");

  const newest = data?.[0]?.seen_at;
  if (!newest) return { alive: null, ageSeconds: null, lastBeatAt: null, unknown: true };

  const beat = new Date(newest).getTime();
  if (Number.isNaN(beat)) {
    return { alive: null, ageSeconds: null, lastBeatAt: null, unknown: true };
  }

  // ⚠️ שעון הדפדפן מול שעון השרת: פער קטן וחיובי הוא נורמלי ואינו מעניין,
  // אבל שעון מקומי שמקדים היה מייצר גיל שלילי ואז "חי" לנצח. Math.max
  // מקבע את הרצפה באפס.
  const ageSeconds = Math.max(0, Math.round((Date.now() - beat) / 1000));
  return {
    alive: ageSeconds < staleAfterSeconds,
    ageSeconds,
    lastBeatAt: newest,
    unknown: false,
  };
}
