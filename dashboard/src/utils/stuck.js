// utils/stuck.js — זיהוי אתר שקפא במצב פעיל. **תצוגה בלבד.**
//
// ============================================================
// מה זה בא לתפוס
// ============================================================
// שער לא יכול להיות "בפעולה" במשך שעות. אתר 1348 הציג "בפעולה" 13 שעות ו-40
// דקות (רגיסטר MODE תקוע על 2), ו-1399/3513 תשע עד שתים-עשרה שעות — ובכרטיס
// הם נראו תקינים לגמרי, בצבע ירוק-כחול של מצב עובד.
//
// גרוע מזה: מצב 'בפעולה' נספר כזמן תקין בחישוב הזמינות, ולכן אתר תקוע מקבל
// **100% זמינות**. המדד שנועד לתפוס תקלות דירג את התקלה כמושלמת.
//
// ============================================================
// מה זה *לא* בא לתפוס — וזו ההבחנה החשובה
// ============================================================
// אתר שקט במצב 'מוכן' הוא אתר בריא. חניון ריק בשבת, בחג, או פשוט בלילה יכול
// לא לדווח דבר במשך ימים, וזו התנהגות נכונה: הסוכן משדר **רק על שינוי**, ואין
// בו סימן חיים תקופתי (זיהוי הנתק הוא תפקידם של שני שכבות ה-LWT). לכן שתיקה
// לבדה אינה תקלה, ואינה מסומנת — במפורש, לפי החלטה.
//
// גם פעולה חיה אינה מסומנת: מחזור חניה אמיתי נמשך שניות עד דקות בודדות.
//
// לכן שני התנאים חייבים להתקיים **יחד**:
//   1. האתר במצב *פעיל* — כזה שאמור להחזיק דקות, לא שעות.
//   2. לא נשמע ממנו דבר יותר מהסף.
//
// ============================================================
// אפס נגיעה בחשבון
// ============================================================
// המודול הזה אינו משתתף בשום חישוב: לא בזמינות, לא באחוז הכשל ולא במונה
// הפעולות. הוא קורא שדות קיימים ומחזיר טקסט לתצוגה. המדדים אומתו כנכונים
// מול הנתונים הגולמיים, ואין סיבה לגעת בהם.

/**
 * מצבים "פעילים": כאלה שמתארים משהו שקורה *עכשיו*, ולכן אמורים להחזיק זמן
 * קצר. 'מוכן' אינו כאן בכוונה (מנוחה היא מצב יציב וחוקי), וגם לא 'בתחזוקה'
 * (היא ארוכה מהגדרתה) ולא 'אין תקשורת' (הוא *כבר* מדווח על הבעיה בעצמו).
 */
export const ACTIVE_STATES = new Set(["operating", "error"]);

/**
 * מעל כמה דקות בלי שום דיווח מצב פעיל נחשב חשוד.
 *
 * 30 דקות: ארוך מכל מחזור חניה אמיתי בסדר גודל (מחזור נמדד בשניות עד דקות
 * בודדות, ולכן אין סיכוי שהוא יגרור סימון), וקצר בהרבה מקיפאון של שעות —
 * שהוא מה שנצפה בשטח. **כוונן אחרי שיהיו זמני מחזור אמיתיים מהשדה.**
 */
export const STUCK_AFTER_MINUTES = 30;

const MINUTE_MS = 60 * 1000;

/** משך בדקות → טקסט קצר בעברית. */
function humanDuration(minutes) {
  if (minutes < 60) return `${minutes} דקות`;
  const hours = Math.floor(minutes / 60);
  if (hours < 24) {
    const rest = minutes % 60;
    return rest ? `${hours} שע' ${rest} דק'` : `${hours} שעות`;
  }
  const days = Math.floor(hours / 24);
  return days === 1 ? "יום" : `${days} ימים`;
}

/**
 * האם האתר נראה תקוע, וכמה זמן.
 *
 * @param site אובייקט האתר כפי שה-API מחזיר (status, last_seen, statusSince)
 * @param nowMs "עכשיו" — מוזרק כדי שהבדיקות לא יהיו תלויות בשעון האמיתי
 * @returns null אם אינו תקוע; אחרת { silentMinutes, stateMinutes, label, text }
 */
export function stuckInfo(site, nowMs = Date.now()) {
  if (!site || !ACTIVE_STATES.has(site.status)) return null;

  // הטריגר הוא **השתיקה**: last_seen מתקדם רק על דיווח אמיתי מהאתר (ולעולם
  // לא על no_comm — נתק אינו צפייה). מצב פעיל שלא מגיע ממנו עדכון הוא
  // בדיוק החתימה של MODE שקפא.
  const lastSeen = Date.parse(site.last_seen);
  if (!Number.isFinite(lastSeen)) return null;

  const silentMinutes = Math.floor((nowMs - lastSeen) / MINUTE_MS);
  if (silentMinutes < STUCK_AFTER_MINUTES) return null;

  // המשך שמוצג הוא של **המצב** (מאז statusSince) ולא של השתיקה: זה מה שמעניין
  // את המפעיל — "בפעולה 11 שעות" — והוא גם הגדול מהשניים, כי כל שינוי מצב
  // מקדם גם את last_seen.
  const stateStart = Date.parse(site.statusSince);
  const stateMinutes = Number.isFinite(stateStart)
    ? Math.floor((nowMs - stateStart) / MINUTE_MS)
    : silentMinutes;

  // 'מושבת' הוא התווית של error; "מושבת 5 שעות" נקרא נכון בעברית כמו
  // "בפעולה 5 שעות", ולכן אין צורך בהטיה מיוחדת.
  const label = site.status === "operating" ? "בפעולה" : "מושבת";

  return {
    silentMinutes,
    stateMinutes,
    label,
    /** הטקסט לתג. */
    text: `${label} ${humanDuration(stateMinutes)} — ייתכן תקוע`,
    // ==========================================================
    // הניסוח תפעולי ולא טכני — בלי רגיסטרים ובלי MODE
    // ==========================================================
    // הנוסח הקודם הפנה את הקוראת "לבדוק את רגיסטר ה-MODE בבקר". זה מידע נכון
    // אבל לא שלה: מי שקוראת את הפאנל רוצה לדעת **מה קורה באתר**, לא איפה
    // לחפש בבקר. השם הפנימי של הרגיסטר גם אינו אומר דבר למי שאינה מתחזקת את
    // הסוכן, והוא הופך הודעה תפעולית לשורת דיבאג.
    //
    // מה שכן נשאר: כמה זמן, מתי נשמע לאחרונה, ושהמדדים אינם מושפעים.
    // ⚠️ הניסוח נגזר מהמצב ואינו קבוע. הגרסה הקודמת אמרה "הפעולה נמשכת"
    // תמיד — כלומר אתר **מושבת** 5 שעות קיבל הודעה על "פעולה שנמשכת", וזה
    // פשוט לא נכון. הסימון חל על כל מצב פעיל (ראה ACTIVE_STATES).
    noun: site.status === "operating" ? "הפעולה" : "ההשבתה",

    /** הסבר מלא ל-title, כולל *למה* זה סומן. */
    title:
      `${site.status === "operating" ? "הפעולה" : "ההשבתה"} נמשכת ` +
      `${humanDuration(stateMinutes)} — הרבה מעבר לצפוי. ` +
      `לא התקבל מהאתר שום עדכון ${humanDuration(silentMinutes)}. ` +
      `(הסימון מופיע אחרי ${STUCK_AFTER_MINUTES} דקות שתיקה במצב פעיל; ` +
      `אתר שקט במצב 'מוכן' אינו מסומן — מנוחה היא מצב תקין.)`,
  };
}
