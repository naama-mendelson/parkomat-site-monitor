// utils/tier.js — איזו דרגה מוצגת לאתר, ומתי הוא "לא חובר".
//
// ============================================================
// ⚠️ רמת השירות מגיעה מהרמזור, לא משדה נפרד על האתר
// ============================================================
// ל-`sites` יש שדה `tier` משלו, והתג בכרטיס הוצג ממנו. אבל **ההסכם בלוח
// הוא מה שקובע מתי הזמינות בכלל נמדדת** — כלומר שני מקורות לאותה אמת,
// ואחד מהם משפיע על מספר והשני רק על תווית. תג שאומר "בסיסי" בזמן שהשורה
// אומרת VIP הוא בדיוק סוג הסתירה שאיש לא מבחין בה עד שמישהו משווה.
//
// ⚠️ ואוצר המילים שונה: הלוח כותב `ext`, השדה הישן `extended`. התרגום כאן
// ולא בכרטיס — אחרת כל צרכן של `tier` (הכרטיס, שורת הטבלה, המיון, הסינון)
// היה צריך לזכור אותו בעצמו.
import { TIER_UNLINKED, TIER_BOARD_STATES } from "./constants.js";

const TIER_FROM_AGREEMENT = { vip: "vip", ext: "extended", basic: "basic" };

const norm = (v) => {
  const s = v == null ? "" : String(v).trim().toLowerCase();
  return s || null;
};

/**
 * הדרגה שמוצגת לאתר.
 *
 * ⚠️ **אתר בלי שורה ברמזור הוא "לא חובר", לא "בסיסי".** `sites.tier` הוא
 * `'basic'` כברירת מחדל במסד, ולכן אתר שאיש לא חיבר הוצג "בסיסי" — בזמן
 * שהזמינות שלו מחושבת על 24/7, כלומר **הפוך** ממה שהתג אמר. נמדד 05/10/2026:
 * אתר אחד מתוך 56 (1370, הקונגרס 29).
 *
 * ⚠️ **ואותה סתירה בשני מקרים נוספים, שאפשר להגיע אליהם בבחירה אחת ברמזור:**
 *   • "להתייחס כ" = לא בשירות / תחזוקה בלבד — ערכים שקיימים בתפריט של
 *     העמודה. התג הציג "בסיסי" מברירת המחדל במסד. עכשיו הוא מציג את מה שכתוב
 *     ברמזור.
 *   • "להתייחס כ" ריק ו"במקור" מלא — הזמינות נמדדת לפי המסלול, ולכן התג
 *     מציג את המסלול ולא את ברירת המחדל.
 * נמדד 05/10/2026: אף אתר מנוטר אינו באחד מהם היום — אבל אין שום דבר
 * שמונע זאת מחר.
 *
 * ⚠️ **ו"לא חובר" רק כשהקריאה הצליחה.** כשל ב-`site_uptime_service` אינו
 * מפיל את הרשימה, ומשאיר אותה בלי שורה לאף אתר — ו"אין שורה" היה צובע את
 * כל 56 האתרים "לא חובר" בגלל תקלת רשת. במקרה כזה הדרגה מהמסד, כמו קודם.
 *
 * @param {object|null} svc        השורה של האתר מ-`site_uptime_service` (agreement, plan), או null
 * @param {boolean}     svcFailed  הקריאה ל-`site_uptime_service` נכשלה
 * @param {string}      manualTier `sites.tier`
 * @returns {string} vip / extended / basic / unlinked / no_service / maintenance_only / none
 */
export function effectiveTier(svc, svcFailed, manualTier) {
  // השירות קודם ("איך מתייחסים"), והמסלול רק כשהשירות ריק — אותו סדר נפילה
  // כמו ב-`site_uptime_service`, רק הפוך: שם המסלול קודם כי הוא **מודד**,
  // כאן השירות קודם כי התג אומר **איך לטפל**.
  // ערך שאינו מוכר (טקסט חופשי) מדולג, ולא עוצר את הנפילה למסלול.
  for (const v of [norm(svc?.agreement), norm(svc?.plan)]) {
    if (v && TIER_FROM_AGREEMENT[v]) return TIER_FROM_AGREEMENT[v];
    if (v && TIER_BOARD_STATES.includes(v)) return v;
  }
  // ‏`site_uptime_service` מחזירה שורה לכל אתר שיש לו מסלול **או** שירות
  // בלוח, ולכן "אין שורה" = אין לאתר שורה ברמזור, או ששני התאים בה ריקים.
  if (!svcFailed && !svc) return TIER_UNLINKED;
  return manualTier;
}
