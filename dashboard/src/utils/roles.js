// מה שהמסך מראה: בקר לא רואה כפתורי עריכה (או רואה אותם נעולים עם הסבר), כדי שלא ילחץ ויקבל שגיאה. כפתור שנשאר בטעות
// גלוי לבקר נכשל במסד עם "בקר יכול רק לצפות".
// קובץ טהור — הבדיקות מריצות אותו ב-node.

export const ROLES = ["manager", "editor", "operator"];
export const ROLE_LABELS = { manager: "מנהל", editor: "עורך", operator: "בקר" };
/** מה כל תפקיד רשאי — לבורר במסך המשתמשים */
export const ROLE_HINTS = {
  manager: "הכול, כולל מחיקת אתר וניהול משתמשים",
  editor: "עריכה של הכול, חוץ ממחיקת אתר וניהול משתמשים",
  operator: "צפייה בלבד",
};

export const roleLabel = (role) => ROLE_LABELS[role] ?? "—";
/** מנהל או עורך — כל פעולה שכותבת (app.can_edit במסד) */
export const canEdit = (role) => role === "manager" || role === "editor";
/** מנהל בלבד: מחיקת אתר, ניהול משתמשים, קוד הניהול, תיבת הדיווחים */
export const isManagerRole = (role) => role === "manager";

/** המשפט שבקר רואה ליד כפתור נעול — אותה הודעה שהמסד מחזיר */
export const READ_ONLY_MSG = "בקר יכול רק לצפות — לעריכה צריך תפקיד עורך או מנהל";
