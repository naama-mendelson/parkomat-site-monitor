// check-agent-identity-ui — הנפקת סיסמה חדשה אפשרית מהמסך.
//
// ============================================================
// ⚠️ למה השער הזה קיים: שלושה אתרים שנתקעו בלי דרך חזרה
// ============================================================
// 1326, 1414 ו-3510 קיבלו זהות ב-06/09/2026 דרך הדשבורד. הסיסמה מוצגת
// **פעם אחת** (Supabase שומר גיבוב בלבד), ואיש לא העתיק אותה. מאותו רגע
// הכפתור החזיר `409 — כבר קיימת`, והוצג כשגיאה.
//
// כלומר: אתר שהזהות שלו הונפקה ואבדה **לא היה ניתן לחיבור מהמסך בכלל**.
// הדרך היחידה הייתה `provision-agent-user.js <קוד> --rotate` על מחשב עם
// `.env` — בדיוק סוג הפקודה שהפרויקט הזה קיים כדי לחסל, ולא במקרה:
// פקודה שצריך לזכור מייצרת אתר שנראה מותקן ואינו מדווח.
//
// ⚠️ **ה-Edge Function תמכה ב-`rotate` מהיום הראשון.** לא היה חסר שום
// דבר בצד השרת — רק המסך לא ידע לבקש.
//
//   node scripts/check-agent-identity-ui.mjs

import { readFileSync } from "node:fs";

let failures = 0;
const check = (label, ok, detail) => {
  console.log((ok ? "✅ " : "❌ ") + label + (detail ? `   ${detail}` : ""));
  if (!ok) failures++;
};

// ⚠️ שורות הערה מוסרות לפני כל בדיקה. השער הזה מחפש קריאות בקוד, והערה
// שמסבירה את המנגנון הייתה צובעת אותו ירוק בלי שהמנגנון קיים — טעות
// שנעשתה כבר שלוש פעמים בשערים אחרים בפרויקט הזה.
const code = (p) =>
  readFileSync(new URL(`../${p}`, import.meta.url), "utf8")
    .split("\n").filter((l) => !/^\s*(\/\/|\*|\/\*)/.test(l.trim())).join("\n");

const panel = code("src/components/AdminPanel/AdminPanel.jsx");
const writes = code("src/services/sitesWriteDirect.js");

// ------------------------------------------------------------
// 1. השגיאה נושאת את הסיבה
// ------------------------------------------------------------
// ⚠️ בלי זה המסך מקבל מחרוזת בלבד ואינו יכול להבחין בין "כבר קיימת"
// לבין כישלון אמיתי — וזה מה שהפך 409 למסך סופי.
check("שגיאת 409 שומרת את alreadyExists", /err\.alreadyExists\s*=/.test(writes));
check("...וגם כשהגוף אינו מכיל את השדה", /res\.status === 409/.test(writes));

// ------------------------------------------------------------
// 2. המסך מבקש אישור במקום להציג שגיאה
// ------------------------------------------------------------
// ⚠️ שתי טענות ולא אחת: ש**רק** שגיאה שאינה 409 מוצגת כשגיאה, ושיש
// מסלול המשך. בדיקה אחת מהן לבדה עוברת גם על קוד ששולח הכול ל-setErr.
check("רק שגיאה שאינה 409 מוצגת כשגיאה",
  /if \(!e\.alreadyExists \|\| rotate\)\s*\{\s*setErr\(e\.message\);\s*return;/.test(panel));
check("ול-409 יש המשך", /setConfirmRotate\(site\.code\);/.test(panel));

// ------------------------------------------------------------
// 3. הסיבוב נשלח בפועל
// ------------------------------------------------------------
// ⚠️ **הטענה היא שהדגל מגיע ליעד.** בלעדיו הכפתור קיים, נלחץ, ומחזיר
// שוב 409 — כלומר מסך שמציע פעולה שאינו יודע לבצע.
check("provisionAgent נקרא עם rotate", /provisionAgent\(site\.code,\s*\{\s*rotate\s*\}\)/.test(panel));
check("הכפתור מבקש סיבוב מפורש", /issueAgent\(s,\s*true\)/.test(panel));
check("והדגל נשלח ל-Edge Function", /rotate\s*\}\)/.test(writes) || /rotate,?\s*\}/.test(writes));

// ------------------------------------------------------------
// 4. לחיצה אחת כשבטוח — אישור כשלא
// ------------------------------------------------------------
// ⚠️ אתר שמעולם לא פעם: הסיסמה אינה בשימוש, ואישור על
// פעולה ללא סיכון הוא מה שהשאיר שלושה אתרים תקועים שבוע.
check("אתר שלא פעם מסתובב בלחיצה אחת",
  /beat === false\)\s*\{\s*await issueAgent\(site, true\)/.test(panel));

// ⚠️ **וכשל בבירור חייב להוביל לאישור, לא לסיבוב.** `false` במקום
// `null` היה מסובב אתר חי בלחיצה אחת בגלל תקלת רשת רגעית.
check("⚠️ כשל בבירור נכשל-סגור", /if \(error\) return null;/.test(writes));

// ------------------------------------------------------------
// 5. ⚠️ ולא בלחיצה אחת כשהאתר חי
// ------------------------------------------------------------
// סיבוב מבטל את הסיסמה הקודמת מיד. אתר שכבר משתמש בה מפסיק לדווח, ובלי
// MQTT אין נפילה-לאחור. אותו כלל כמו במחיקת אתר ובהחלפת בקר: הטקסט אומר
// מה **יקרה**, ולא "האם את בטוחה".
check("⚠️ יש שלב אישור נפרד", /confirmRotate === s\.code/.test(panel));
check("⚠️ והאזהרה אומרת מה יקרה", /יפסיק לדווח/.test(panel));

// ------------------------------------------------------------
// 6. המודל מבדיל בין הנפקה ראשונה לסיבוב
// ------------------------------------------------------------
// ⚠️ אחרת מנהלת שסובבה סיסמה קוראת "נוצרה זהות" ומסיקה שלא היה קיים
// כלום — ואז אינה מבינה למה האתר הפסיק לדווח.
check("המודל אומר שזו סיסמה חדשה", /agentIssued\.rotated/.test(panel));

console.log(failures ? `\n❌ ${failures} כשלים` : "\n✅ הכל עבר");
process.exit(failures ? 1 : 0);
