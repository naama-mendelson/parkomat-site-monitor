using System.Linq;

namespace Parkomat.Agent.Service.Modbus;

/// <summary>
/// תוצאת פענוח: הטקסט, ומה שנצפה בדרך.
///
/// ⚠️ החזרת הדגל כערך ולא כמאפיין סטטי היא **תיקון לתכנון קודם**: מאפיין
/// סטטי הוא מצב גלובלי שקריאה אחת דורסת לשנייה, ואינו בטוח בריבוי תהליכונים.
/// </summary>
public readonly record struct FaultText(string Text, int UnknownChars, string RawHex = "")
{
    public static readonly FaultText Empty = new("", 0, "");

    /// <summary>האם הפענוח נתקל בערכים שלא ידע לפרש (הוחלפו ב-'?').</summary>
    public bool HadUnknown => UnknownChars > 0;
}

/// <summary>
/// פענוח טקסט התקלה מ-registers גולמיים.
///
/// ============================================================
/// למה זה מחלקה נפרדת ולא שורות בתוך PlcReader
/// ============================================================
/// PlcReader דורש PLC אמיתי ברשת. הפענוח הוא הלוגיקה שאפשר לטעות בה —
/// פרשנות הבתים, איפה המחרוזת נגמרת, מה עושים עם תו לא חוקי — והוא
/// **טהור לחלוטין**: מערך פנימה, מחרוזת החוצה.
///
/// הפרדה כזו היא ההבדל בין "נבדק" לבין "נראה בסדר באתר".
///
/// ============================================================
/// הפורמט — **נמדד מול בקר אמיתי**, לא משוער
/// ============================================================
///   • **תו אחד לכל register**, מתחיל בכתובת 2, מסתיים באפס (כמו C).
///   • **הערך הוא נקודת קוד יוניקוד ישירה**, לא בית.
///
/// ⚠️ הסעיף האחרון הוא תיקון להנחה קודמת שהייתה שגויה, וכך היא התגלתה —
/// מטבלת המיפוי של הבקר בז'בוטינסקי 91 (`Takalolek_ErrorString`):
///
///     1502 1504 1492 1500  32  1495 1504 1497 1493 1503  32  45 ...
///      מ    נ    ה    ל   רווח  ח    נ    י    ו    ן   רווח  -
///
/// כלומר **"מנהל חניון - דלתות חניון פתוחות"** — בדיוק מה שמסך הבקר הציג
/// באותו רגע. 32 ו-45 הם ASCII רגיל, אבל העברית היא 1488..1514, שהוא
/// טווח היוניקוד של א..ת (U+05D0..U+05EA).
///
/// ⚠️ **וכך זה נראה כשטועים:** הגרסה הקודמת לקחה את הבית הנמוך ותרגמה לפי
/// Windows-1255. עבור 1504 (0x05E0) הבית הנמוך הוא 0xE0 — שהוא **א** תקין
/// ב-1255 — ועבור 1502 (0x05DE) הוא 0xDE, שאינו אות. התוצאה בשטח הייתה
/// `?א?? ?א???`: **קריא למחצה, לא ג'יבריש**, ולכן היא נראית כמו תקלה
/// בבקר ולא כמו טעות פענוח.
/// </summary>
public static class FaultTextDecoder
{
    /// <summary>
    /// ממיר registers גולמיים למחרוזת.
    /// מחזיר Empty כשאין טקסט — ולא null, כדי שהקורא לא יצטרך להבדיל בין
    /// "אין תקלה" לבין "לא נקרא".
    /// </summary>
    public static FaultText Decode(ushort[]? registers)
    {
        if (registers is null || registers.Length == 0) return FaultText.Empty;

        int unknown = 0;
        var chars = new List<char>(registers.Length);

        foreach (ushort r in registers)
        {
            // סיום המחרוזת. **עוצרים כאן ולא ממשיכים לסרוק** — הבקר אינו
            // מבטיח שהחוצץ נוקה, ומה שאחרי הסיום עלול להיות זנב של הודעה
            // קודמת. סריקה עד הסוף הייתה מדביקה אותו לטקסט.
            if (r == 0) break;

            char c = ToChar(r);
            if (c == '?' && r != '?') unknown++;
            chars.Add(c);
        }

        // רווחי ריפוד בקצוות נחתכים — בקרים מרפדים שדות ברווחים, וזה רעש.
        // ⚠️ הגולמי נשמר **רק כשיש תו לא מזוהה** — אחרת זו מחרוזת
        // מיותרת בכל קריאה, על נתון שאיש לא יסתכל בו.
        string rawHex = unknown > 0
            ? string.Join(" ", registers.TakeWhile(x => x != 0).Select(x => x.ToString("X4")))
            : "";
        return new FaultText(new string(chars.ToArray()).Trim(), unknown, rawHex);
    }

    // ============================================================
    // בית בודד → תו. כולל עברית.
    // ============================================================
    // ⚠️ הגרסה הראשונה סיננה **כל** בית מעל 126 ל-'?'. אילו הבקר שולח
    // עברית — והוא בקר ישראלי — כל הודעה הייתה מגיעה כשורת סימני שאלה,
    // ומי שרואה את זה מסיק שהקוד שבור ולא שהקידוד שונה.
    //
    // Windows-1255 (הקידוד העברי של Windows, ומה ש-PLC ישראלי ישלח)
    // ממפה 0xE0..0xFA ל-א..ת ברצף. זו הזזה פשוטה, ולכן אין צורך בחבילת
    // System.Text.Encoding.CodePages — תלות שלמה בשביל טבלה אחת.
    //
    // ⚠️ ואם הבקר בעצם שולח אנגלית בלבד, השינוי הזה אינו משנה דבר:
    // 32..126 עוברים כמות שהם בשני המקרים.
    private static char ToChar(ushort r)
    {
        // ============================================================
        // מעל בית בודד = נקודת קוד יוניקוד ישירה
        // ============================================================
        // כך הבקר בז'בוטינסקי 91 שולח עברית: 1488=א ... 1514=ת. אין כאן
        // המרה בכלל — הערך **הוא** התו.
        //
        // ⚠️ והכלל הזה חייב לבוא **ראשון**. אילו הבדיקה של 0xE0..0xFA
        // הייתה רצה על הבית הנמוך לפניו, 1504 היה נקרא כ-א (0xE0) במקום
        // כ-נ — וזו בדיוק הטעות שייצרה `?א?? ?א???` בשטח.
        // ⚠️ **ורק בטווח העברי.** הגרסה הקודמת החזירה כל ערך מעל 0xFF
        // כתו, בלי לבדוק דבר. נמדד בייצור באתר 1376: רגיסטר בערך
        // 0x73FC הפך ל-`珼`, והתקלה — "מעלית לא בקומה בכניסה לאוטומט" —
        // הוצגה כתו סיני יחיד.
        //
        // ⚠️ והנזק כפול: לא רק שהטקסט שגוי, אלא ש-`珼` **אינו נספר
        // כתו לא מזוהה**, ולכן האזהרה שאמורה לצעוק על קידוד לא ירתה.
        // שגיאה שקטה שנראית כמו נתון.
        //
        // הבלוק 0x0590..0x05FF הוא כל העברית, כולל סופיות וניקוד.
        // מה שמחוצה לו אינו טקסט שבקר ישראלי שולח.
        if (r > 0xFF)
        {
            if (r >= 0x0590 && r <= 0x05FF) return (char)r;
            return '?';
        }

        // ASCII להדפסה — הרוב המכריע, ועובר כמות שהוא (32=רווח, 45=מקף).
        if (r >= 32 && r <= 126) return (char)r;

        // ============================================================
        // עברית כבית בודד ב-Windows-1255: 0xE0 = א ... 0xFA = ת
        // ============================================================
        // ⚠️ **נשאר בכוונה, למרות שהבקר שנמדד אינו משתמש בו.** נמדד בקר
        // אחד; יש 12 אתרים ובקרים מדגמים שונים. מסלול זה עולה שתי שורות,
        // ואם בקר אחר כן שולח בתים — הוא יעבוד ביום הראשון במקום להגיע
        // כשורת סימני שאלה שמישהו יצטרך לחקור מאפס.
        if (r >= 0xE0 && r <= 0xFA) return (char)(r - 0xE0 + 0x05D0);

        // ⚠️ כל השאר — תווי בקרה ובתים לא ממופים — הופכים ל-'?'.
        // הם שוברים JSON ולוגים, ו-\0 באמצע חותך מחרוזת בשקט לאורך המסלול
        // (MQTT → שרת → DB → מסך).
        //
        // מוחלף ולא נזרק: האורך נשמר, ומי שרואה "ERR?12" יודע שהיה שם
        // משהו — במקום להסיק שהבקר שלח "ERR12".
        return '?';
    }
}
