namespace Parkomat.Agent.Core.Protocol;

/// <summary>
/// מאחד את מצביהן של <b>שתי מערכות באתר אחד</b> למצב אחד של האתר.
///
/// <para>נבנה עבור אתר פלורנטין: שני <c>ParkManager</c> באותו בקר, כל אחד
/// עם מצב ורכב משלו (רגיסטרים 290/291 ו-293/294), ומונה מחזורים אחד
/// משותף (292).</para>
///
/// <para><b>הכלל, כפי שנקבע על ידי בעלת המוצר:</b> האתר נחשב בתקלה רק אם
/// <b>שתי</b> המערכות בתקלה, ובתחזוקה רק אם <b>שתיהן</b> בתחזוקה. בכל
/// מקרה אחר — <b>הטוב מביניהן</b>. הנימוק: אתר שאחת ממערכותיו עובדת עדיין
/// משרת רכבים.</para>
///
/// <para>⚠️ <b>וזו החלטה עם מחיר ידוע.</b> אתר שמערכת אחת בו מתה חודש
/// מציג 100% זמינות, והמיון לפי אחוז כשל לעולם לא יעלה אותו. הפיצוי הוא
/// <b>תצוגתי</b> — שני שבבים ותג "מערכת מושבתת" על הכרטיס — ובמכוון אינו
/// נוגע במדד: המדד הוא הגדרה, והתצוגה היא מה שמושך את העין.</para>
///
/// <para>⚠️ <b>והאיחוד קורה כאן ולא ב-SQL, בכוונה.</b> ‏<c>ingest_state</c>
/// מקבלת מצב אחד לאתר וממשיכה לעשות בדיוק את מה שעשתה — סגירת מקטעים,
/// זמינות, אחוז כשל. כלומר <b>קוד הקליטה, זה שכותב נתוני לקוחות, אינו
/// משתנה בכלל</b> בשביל התכונה הזו. מה שכן נוסף הוא פירוט המערכות לצד
/// המצב, לתצוגה בלבד.</para>
/// </summary>
public static class SiteStateAggregator
{
    // ⚠️ הדירוג הוא **הגדרת הכלל**, ולא נוחות מימוש: "הטוב מביניהן"
    // חייב סדר, וזה הסדר. תקלה היא הגרועה; תחזוקה מעליה מפני שהיא מצב
    // מכוון ולא כשל; המתנה ופעולה שתיהן "המערכת עובדת".
    private static int Rank(SiteState? s) => s switch
    {
        SiteState.Error => 0,
        SiteState.Maintenance => 1,
        SiteState.Ready => 2,
        SiteState.Operating => 3,
        // ⚠️ **מינוס אחת, ולא אפס.** מצב לא ידוע (MODE 4 = init, או ערך
        // לא צפוי) חייב להיות **מתחת** לתקלה, ולא שווה לה: אחרת מערכת
        // שעוברת דרך init בעליית הבקר הייתה מורידה את האתר לתקלה בכל
        // אתחול — ומקטע שנפתח ונסגר הוא נתון שנשמר לתמיד.
        //
        // ⚠️ וזה גם מה שהופך משמרות מפורשות ל-null למיותרות. הייתה כאן
        // בדיקה נפרדת לכל צד; מוטציה שמחקה אותה עברה **ירוקה**, כי כלל
        // המקסימום כבר מטפל בזה. קוד מת שההערה שלו טוענת שהוא מגן —
        // גרוע מהיעדרו, כי הוא מייצר ביטחון שווא.
        _ => -1,
    };

    /// <summary>
    /// מחזיר את מצב האתר משתי מערכות. ‏<c>null</c> באחד הצדדים פירושו
    /// "לא ידוע" — ואז המצב הידוע קובע לבדו.
    /// </summary>
    public static SiteState? Combine(SiteState? first, SiteState? second)
    {
        // שוויון מחזיר את המערכת הראשונה — שרירותי, אבל **דטרמיניסטי**:
        // שתי מערכות באותו מצב חייבות להניב את אותה תשובה בכל קריאה,
        // אחרת מקטעים היו נפתחים ונסגרים על לא כלום.
        return Rank(first) >= Rank(second) ? first : second;
    }
}
