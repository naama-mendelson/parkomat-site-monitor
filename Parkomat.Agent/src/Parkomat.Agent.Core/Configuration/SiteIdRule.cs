namespace Parkomat.Agent.Core.Configuration;

/// <summary>תוצאת בדיקת מזהה אתר: תקין/לא, והסבר בעברית לטכנאי.</summary>
public readonly record struct SiteIdCheck(bool IsValid, string Message);

/// <summary>
/// מה נחשב מזהה אתר תקין.
///
/// ============================================================
/// למה זה ב-Core ולא בטופס או בשירות
/// ============================================================
/// לכלל הזה יש **שלושה** צרכנים: חלון "בדוק חיבור" ב-Tray, טופס ההגדרות,
/// והשירות עצמו בעלייה. עד עכשיו כל אחד הגדיר "תקין" בעצמו — הטופס בדק
/// ריקנות, השירות בדק ריקנות, והבדיקה בדקה גם תווי MQTT.
///
/// ⚠️ שלוש הגדרות של אותו כלל הן שלוש הזדמנויות לסחף, והסחף כאן שקט
/// במיוחד: מזהה שהטופס מקבל והשירות דוחה יוצר אתר שנראה מוגדר ואינו
/// משדר — בדיוק הכשל שהכלל הזה נועד למנוע.
///
/// ============================================================
/// מה הכלל מגן עליו
/// ============================================================
/// המזהה נכנס ישירות לנושא ה-MQTT: `sites/{id}/state`. מזהה ריק יוצר
/// `sites//state`, ומזהה עם תו מבני יוצר נושא אחר לגמרי. שניהם **תקינים
/// לפי הפרוטוקול** ושניהם אינם הנושא שהשרת מנוי אליו — כלומר שידור
/// שמצליח במלואו ואיש אינו שומע.
/// </summary>
public static class SiteIdRule
{
    /// <summary>
    /// ⚠️ '/' מפצל את הנושא לרמות; '+' ו-'#' הם תווי-כלליות של מנוי.
    /// אלה אינם תווים אסורים ב-MQTT — הם תווים בעלי **משמעות מבנית**,
    /// ולכן מזהה שמכיל אותם לא נכשל אלא מייצר נושא שגוי בשקט.
    /// רווח וטאב אינם תואמים את קוד האתר הרשום אצלנו.
    /// </summary>
    private static readonly char[] Forbidden = { '/', '+', '#', ' ', '\t' };

    /// <summary>הצורה המנוקה של המזהה — מה שייכנס לנושא בפועל.</summary>
    public static string Normalize(string? siteId) => (siteId ?? "").Trim();

    public static SiteIdCheck Check(string? siteId)
    {
        string id = Normalize(siteId);

        if (id.Length == 0)
            return new SiteIdCheck(false,
                "מזהה האתר ריק. הסוכן ישדר, הבקר והענן ייראו תקינים — אבל האתר " +
                "לא יופיע בדשבורד כלל. יש להזין את מספר האתר בהגדרות (למשל 1399) ולשמור.");

        int at = id.IndexOfAny(Forbidden);
        if (at >= 0)
            return new SiteIdCheck(false,
                $"מזהה האתר '{id}' מכיל תו שאינו חוקי ('{id[at]}'). " +
                "מזהה תקין הוא מספר האתר בלבד, בלי רווחים ובלי סימנים.");

        return new SiteIdCheck(true, $"מזהה האתר: {id}");
    }
}
