export const OP_PAIR_TOLERANCE_SECONDS = 5;

// ============================================================
// הגדרת המסננים — **בשרת, לא בדפדפן**
// ============================================================
// עד עכשיו הסינון היה שכפול: הדשבורד החזיק עותק משלו (categoryOf + הכלל של
// "הכל"), והשרת החזיק את המונים שאמורים להתאים לו. שני עותקים של אותו כלל
// נפרדים ביום שבו מישהו יתקן אחד מהם, והתסמין הוא הגרוע ביותר במסך הזה:
// **מספר על הצ'יפ שאינו שווה למספר השורות שנפתחות.**
//
// מרגע שהחיתוך חייב לרוץ אחרי הסינון (ראה למטה), הסינון ממילא חייב להיות
// כאן. אז יש מקור אמת אחד.
//
// ⚠️ הקטגוריות **אינן** זרות זו לזו, וזה מכוון: מעבר ל'בתחזוקה' מהבקר נספר
// גם ב-"שינויי מצב" וגם ב-"תחזוקה", ופעולה שנקטעה בתקלה נספרת גם ב-"פעולות"
// וגם ב-"תקלות". אלה עדשות על אותו אירוע, לא ספירה כפולה בטעות.
export const LOG_FILTERS = {
  // ==========================================================
  // "הכל" — 'בפעולה' לא מופיע כאן. נקודה.
  // ==========================================================
  // כל כניסת רכב מייצרת גם מעבר מצב ל'בפעולה' וגם הודעת פעולה, באותה שנייה.
  // בציר המאוחד זה הופיע פעמיים ברצף — "המצב השתנה ל: בפעולה" ומיד "כניסת
  // רכב" — וזה רעש שמטשטש את מה שבאמת קרה.
  //
  // 'מוכן' **כן** מופיע, למרות שגם הוא נולד יחד עם סיום פעולה: הוא נושא את
  // משך ההמתנה עד הפעולה הבאה, ואין שורה אחרת שמספרת אותה. הסתרתו השאירה
  // פעולות צמודות כאילו האתר לא עמד ריק ביניהן.
  all: (e) => !e.explainedByOp && !(e.kind === "status" && e.status === "operating"),

  // ==========================================================
  // מעבר רכב אחד = שורה אחת בצ'יפ, ולא שתיים
  // ==========================================================
  // ⚠️ נתפס על המסך, וזו סתירה של **פי שניים** בין שני כרטיסים באותו מסך:
  //
  //     לוג:    כניסות 56 · יציאות 49 · פעולות 105
  //     דונאט:  כניסות 28 · יציאות 25 · סה"כ    62
  //
  // כל מעבר פיזי נרשם כשתי שורות — "התחילה" ו"הושלמה" — והמסנן ספר שורות
  // בעוד computeInsights סופר מעברים. שני המספרים היו נכונים כל אחד ביחידה
  // שלו, ולכן אף בדיקה לא נפלה; מי שקוראת אותם זה לצד זה רואה סתירה.
  //
  // הכרעה: **הצ'יפ סופר רכבים.** "כניסות 56" נקרא כ-56 רכבים שנכנסו, וזו
  // פשוט טענה שגויה — בלי קשר לשאלה מה נוח לספור.
  //
  // ⚠️ ולכן המסנן עצמו מצומצם ל-'end' ולא רק המונה. הכלל שאסור לשבור כאן
  // הוא **המספר על הצ'יפ שווה למספר השורות שנפתחות**; מונה שסופר 28 ורשימה
  // שפותחת 56 היא בדיוק סוג הסתירה שהתיקון הזה בא לסלק.
  //
  // 'התחילה' לא נעלמה — היא מוצגת ב"הכל", יחד עם סימון "ללא סיום" כשהסיום
  // מעולם לא הגיע.
  //
  // ⚠️ אנומליות: הציר כולל אותן, computeInsights מחריג. בייצור יש 0 כאלה
  // כרגע, ולכן אין פער — אם יופיעו, זה המקום שבו שני המספרים ייפרדו שוב.
  operation: (e) => e.kind === "operation" && e.startEnd === "end",

  // כל שינויי המצב — **כולל** 'בפעולה'. היסטוריית מצבים שחסר בה המצב הנפוץ
  // ביותר אינה היסטוריית מצבים; כאן זה התוכן ולא הרעש.
  status: (e) => e.kind === "status",

  // ==========================================================
  // תחזוקה ותפעול תקלה — שני מסננים, ובלי חפיפה
  // ==========================================================
  // ⚠️ **הם זרים זה לזה בכוונה, ו-repair + maintenance = כל התחזוקה.**
  // שני מסננים שחופפים היו יוצרים סתירה על המסך: המונים היו מסתכמים ליותר
  // מסך התחזוקה, ואותה שורה הייתה נפתחת בשניהם. מי שמנסה לענות "כמה פעמים
  // טיפלו בתקלה" צריך שהמספר יהיה תשובה, לא חיתוך שצריך לחשב.
  //
  // הכלל זהה לזה שבזמינות ובתובנות (afterError ב-buildTimeline): מקטע
  // תחזוקה שמתחיל בדיוק בשנייה שבה נגמרה תקלה.
  repair: (e) => e.kind === "status" && e.status === "maintenance" && e.afterError === true,

  // תחזוקה משני מקורות: חלון ידני (kind='maintenance') *וגם* מצב תחזוקה
  // שדווח מהבקר. בלי השני, המסנן מפספס בדיוק את התחזוקה שהמתקן עצמו הכריז.
  //
  // ⚠️ **החלון הידני הוא תמיד תחזוקה ולעולם לא טיפול** — מישהו לחץ על
  // כפתור, וזו החלטה לפי הגדרה. אותו כלל בדיוק חל בחישוב הזמינות
  // (executive.mjs), ופיצול שהיה סוטה ממנו כאן היה נותן שני מספרים שונים
  // לאותה שאלה בשני מסכים.
  maintenance: (e) =>
    e.kind === "maintenance" ||
    (e.kind === "status" && e.status === "maintenance" && e.afterError !== true),

  // ==========================================================
  // "תקלות" — גם מקטע התקלה וגם הפעולה שנקטעה בגללו
  // ==========================================================
  // נמדד: 71% מהתקלות קורות תוך כדי פעולה. מסנן שמציג רק את מקטע התקלה מראה
  // חצי סיפור — שהמתקן נפל, בלי מי היה בתוכו. שתי השורות יחד הן האירוע.
  error: (e) =>
    (e.kind === "status" && e.status === "error") ||
    (e.kind === "operation" && e.interruptedBy === "error"),

  // ==========================================================
  // ⚠️ תקלות בזמן תחזוקה — מסנן משלהן, ולא חלק מ"תקלות"
  // ==========================================================
  // הן אינן נספרות בשום מדד, ולכן הכללתן במונה ה"תקלות" הייתה מציגה
  // מספר שסותר את אחוז הכשל שלידו. ומצד שני הן אינן אירוע תחזוקה —
  // איש לא **עשה** כלום — ולכן גם המסננים ההם אינם מקום להן.
  //
  // מי ששואל "מה קרה בזמן שהמתקן היה בתחזוקה" שואל שאלה שלישית, ומגיע לכאן.
  suppressed: (e) => e.kind === "suppressedFault",

  // ניתוקים — אירוע תפעולי בפני עצמו, ובלוג המצרף הוא נבלע בין אלפי פעולות.
  no_comm: (e) => e.kind === "status" && e.status === "no_comm",

  // אותו כלל בדיוק כמו operation — רכבים, לא שורות.
  entry: (e) => e.kind === "operation" && e.startEnd === "end" && e.entryExit === "entry",
  exit:  (e) => e.kind === "operation" && e.startEnd === "end" && e.entryExit === "exit",
};

// בונה את ציר הזמן המאוחד מהשורות שנשלפו (טהור) — משרת אתר בודד ומצרף כלל-אתרי.
//
// **מחזיר את הציר המלא: בלי סינון, בלי חיתוך.** ההפרדה בין "לבנות" לבין
// "לסנן ולחתוך" אינה קוסמטית — הבנייה היא מקום שבו שגיאה שקטה (הצמדה שלא
// תופסת, דירוג הפוך, חותם שלא אומץ) נראית זהה לנתון חסר. הבדיקות אוחזות
// בציר הגולמי ובודקות אותו ישירות, כי מסנן שרץ ביניהן היה מסתיר בדיוק את
// השורות שהן באות לאמת.
export function buildTimeline({ ops, states, maint, suppressed = [] }) {
  const secondsBetween = (a, b) =>
    a && b ? Math.max(0, Math.round((Date.parse(b) - Date.parse(a)) / 1000)) : null;

  // ============================================================
  // דירוג לשבירת שוויון כשכמה אירועים נושאים את *אותו* חותם זמן
  // ============================================================
  // סיום פעולה וחזרה ל-"מוכן" הם מעבר MODE אחד (2→1), ולכן הסוכן מייצר את
  // שניהם באותו סבב דגימה ועם אותה שנייה בדיוק. אין ביניהם סדר אמיתי בנתונים,
  // רק שאלה של קריאוּת.
  //
  // הכלל: **הפעולה נסגרת, ורק אז האתר מוכן.** הרשימה היא מהחדש לישן, ולכן
  // "מאוחר יותר" = גבוה יותר: "המצב השתנה ל: מוכן" מופיע *מעל* "יציאת רכב
  // הושלמה", וקריאה מלמטה למעלה היא הכרונולוגיה האמיתית.
  //
  // ⚠️ אל תהפכו את זה. ניסיון קודם הציב את הסיום מעל המוכן, מתוך מחשבה על
  // קריאה מלמעלה למטה — אבל ברשימה יורדת זה אומר שהמוכן קדם לסיום, כלומר
  // שהאתר חזר להיות מוכן בזמן שהפעולה עוד פתוחה. סדר שלא יכול לקרות.
  //
  // הדירוג *עולה* עם המאוחרוּת הלוגית, והמיון מציב את הגבוה למעלה:
  //   0 בפעולה  ‹  1 התחלה  ‹  2 סיום  ‹  3 מוכן/מושבת  ‹  4 תחזוקה
  //
  // ובכל זאת, זה רק מפל אחרון: ב"הכל" שורת המצב שיש לה פעולה תואמת מוסתרת
  // ממילא (ActivityLog.jsx), כי מעבר MODE אחד אינו שני אירועים. הדירוג כאן
  // נשאר נכון עבור מה שכן מוצג יחד — למשל מקטע 'בפעולה' יתום.
  const phaseRank = (e) => {
    if (e.kind === "status") return e.status === "operating" ? 0 : 3;
    if (e.kind === "operation") return e.startEnd === "start" ? 1 : 2;
    return 4;   // תחזוקה — תמיד למעלה, היא עוטפת את השאר
  };

  // "תחזוקה גוברת" — תקלה שקרתה בזמן/בגבול תחזוקה לא מוצגת בלוג ולא נספרת.
  // החפיפה נבדקת *לפי אתר* (site_id): מקטעי PLC (בתוך states) + חלונות ידניים
  // (maint). באתר בודד site_id === undefined לכל השורות → דלי יחיד, זהה
  // להתנהגות הקודמת; במצרף כל אתר נבדק מול התחזוקה שלו בלבד.
  const maintBySite = new Map();
  const pushMaint = (siteId, start, end) => {
    if (!maintBySite.has(siteId)) maintBySite.set(siteId, []);
    maintBySite.get(siteId).push({ start, end });
  };
  for (const s of states) if (s.status === "maintenance") pushMaint(s.site_id, s.started_at, s.ended_at);
  for (const w of maint) pushMaint(w.site_id, w.started_at, w.cancelled_at || w.expires_at);
  const inMaintenance = (ts, siteId) =>
    (maintBySite.get(siteId) || []).some((m) => m.start <= ts && (m.end === null || m.end >= ts));

  const isMaintError = (s) => s.status === "error" && inMaintenance(s.started_at, s.site_id);
  const visibleStates = states.filter((s) => !isMaintError(s));

  // ============================================================
  // איזה שינוי מצב "מוסבר" על ידי פעולה — ולכן מיותר בציר המאוחד
  // ============================================================
  // מעבר MODE 1→2/3 מייצר גם state=operating וגם operation/start, באותה שנייה.
  // שורת ה-'בפעולה' אינה מוסיפה דבר על "כניסת רכב התחילה" — אותו רגע, פחות
  // מידע — ולכן היא מסומנת כמוסברת והדשבורד מסתיר אותה ב"הכל".
  //
  // 'מוכן' **אינו** ברשימה, למרות שגם הוא נוצר יחד עם operation/end. הוא נושא
  // את משך ההמתנה עד הפעולה הבאה, וזו התקופה שבין הפעולות — מידע שאין לו שום
  // מקור אחר בציר הזמן. הסתרתו השאירה פעולות צמודות כאילו האתר לא עמד ריק.
  //
  // תקלה, תחזוקה ונתק לעולם אינם נובעים ממעבר פעולה, ולכן לעולם אינם מוסברים.
  //
  // ============================================================
  // ההצמדה משמשת לשני דברים שונים — אל תמזגו אותם
  // ============================================================
  // PAIRED_OP = איזו הודעת פעולה נושאת את **אותו רגע פיזי** כמו שינוי המצב.
  //   כאן שני הכיוונים: MODE 1→2/3 מייצר operating + start, ו-MODE 2/3→1
  //   מייצר end + ready. זה משמש ל**אימוץ חותם הזמן** (ראה למטה).
  //
  // REDUNDANT = ומאלה, מי גם **מיותר** בציר המאוחד. רק 'בפעולה': הוא אינו
  //   מוסיף כלום מעל "כניסת רכב התחילה". 'מוכן' כן מוסיף — משך ההמתנה עד
  //   הפעולה הבאה — ולכן הוא מוצג תמיד.
  const PAIRED_OP = { operating: "start", ready: "end" };
  const REDUNDANT = new Set(["operating"]);

  // הצמדה לפי אתר: במצרף כלל-אתרי שתי רשומות מאתרים שונים באותה שנייה אינן
  // מסבירות זו את זו. באתר בודד site_id === undefined לכל השורות → דלי יחיד.
  const opsBySite = new Map();
  for (const o of ops) {
    if (!opsBySite.has(o.site_id)) opsBySite.set(o.site_id, []);
    opsBySite.get(o.site_id).push(o);
  }

  /** הפעולה שנושאת את אותו רגע פיזי כמו שינוי המצב, או null. */
  const pairedOpFor = (s) => {
    const wants = PAIRED_OP[s.status];
    if (!wants) return null;
    const t = Date.parse(s.started_at);
    return (opsBySite.get(s.site_id) || []).find(
      (o) => o.start_end === wants &&
             Math.abs(Date.parse(o.occurred_at) - t) <= OP_PAIR_TOLERANCE_SECONDS * 1000
    ) || null;
  };

  // ==========================================================
  // פעולה שנקטעה בתקלה אינה פעולה שהושלמה
  // ==========================================================
  // ה-detector בסוכן סוגר פעולה בכל מעבר MODE, כולל מעבר לתקלה (2/3 → 5).
  // מבחינת הנתונים זה `end` רגיל לגמרי, ולכן הלוג הציג "יציאת רכב הושלמה"
  // בדיוק ברגע שהרכב **נתקע**. זו לא אי-דיוק בניסוח אלא היפוך משמעות: מי
  // שקורא את הלוג רואה הצלחה במקום כשל.
  //
  // הזיהוי חד-משמעי ואינו הערכה: כשהמעבר הוא מפעולה לתקלה, הסוכן מייצר את
  // שתי ההודעות באותו סבב דגימה ועם אותו חותם. לכן —
  //
  //     end.occurred_at === error_segment.started_at   ⟺   הפעולה נקטעה
  //
  // נמדד על נתוני אמת: מתוך 49 מקטעי תקלה, **35 (71%)** קרו תוך כדי פעולה.
  // כלומר זה לא מקרה קצה — זה הרוב.
  //
  // ⚠️ ההשוואה על המחרוזת ולא על Date.parse: שני החותמים נולדו מאותו מקור
  // ונשמרו באותו פורמט, וסובלנות זמן כאן הייתה מסמנת בטעות גם תקלה שהתחילה
  // סמוך לסיום תקין.
  //
  // ==========================================================
  // לא רק תקלה — כל מצב שאינו 'מוכן' קוטע
  // ==========================================================
  // הכלל הרחב: הפעולה מסתיימת כשה-MODE יוצא ממצב פעולה, ו**התוצאה נקבעת
  // לפי המצב שאליו עבר**. נמדד על כל 1,018 הסגירות:
  //
  //     -> מוכן        945   92.8%   הושלמה
  //     -> תקלה         35    3.4%   נקטעה
  //     -> תחזוקה        7    0.7%   נקטעה
  //     אין מקטע תואם   31    3.0%   ברירת מחדל: הושלמה
  //
  // התחזוקה קוטעת פחות, אבל היא קוטעת — ורכב שנתקע כי מישהו העביר את
  // המחסום לתחזוקה אינו "פעולה שהושלמה" יותר משרכב שנתקע בתקלה.
  //
  // 31 ללא מקטע תואם נשארות "הושלמה": המצב לא עבר לתקלה ולא לתחזוקה, ולכן
  // ברירת המחדל תואמת את ה-92.8%. סימונן כ"לא ידוע" היה מוסיף רעש בלי
  // להוסיף מידע.
  const interruptedBy = new Map();   // "site|timestamp" -> 'error' | 'maintenance'
  for (const s of states) {
    if (s.status === "error" || s.status === "maintenance") {
      interruptedBy.set(`${s.site_id}|${s.started_at}`, s.status);
    }
  }

  // ==========================================================
  // "נקטעה" ⟶ "הושלמה בתחזוקה"
  // ==========================================================
  // רכב שנתקע בתקלה אינו נשאר תקוע: מעבירים ללא-אוטומט ומכניסים אותו ידנית.
  // כלומר כשאחרי מקטע התקלה בא **תחזוקה**, ההנחה היא שהמעבר הושלם — רק לא
  // בדרך הרגילה. "נקטעה" לבדה מספרת חצי סיפור, ובדיוק את החצי המדאיג.
  //
  // ⚠️ זו נגזרת של קריאה ולא נתון שנכתב לטבלה, וזה מכוון: זו **הנחה** ולא
  // תצפית — איננו רואים את הרכב עובר. כלל שנשמר לעמודה קופא ברגע שמתקנים
  // אותו, וההיסטוריה נשארת עם הפרשנות הישנה בלי סימן.
  //
  // המפתח הוא ended_at של מקטע התקלה: המקטע שמתחיל בדיוק כשהתקלה נגמרה הוא
  // המצב שבא אחריה.
  const startsAt = new Map();        // "site|timestamp" -> status
  for (const s of states) startsAt.set(`${s.site_id}|${s.started_at}`, s.status);

  const errorEndedAt = new Map();    // "site|error.started_at" -> error.ended_at
  for (const s of states) {
    if (s.status === "error" && s.ended_at) {
      errorEndedAt.set(`${s.site_id}|${s.started_at}`, s.ended_at);
    }
  }

  // ============================================================
  // תחזוקה אחרי תקלה היא **תפעול תקלה**, לא תחזוקה מתוכננת
  // ============================================================
  // שתיהן נראות זהות בטבלה — מקטע `maintenance` — אבל הן שני דברים הפוכים:
  //
  //   **מתוכננת** — מישהו בחר להוריד את האתר. זו החלטה, וזה סימן טוב.
  //   **תפעול תקלה** — האתר נפל, ומישהו בא. זו תוצאה, ומבחינת מי שרצה
  //     לחנות זה המשך של אותה השבתה.
  //
  // ערבובן מייפה את התמונה: אתר שנופל שלוש פעמים בשבוע ומטופל בכל פעם נראה
  // כמו אתר שעובר תחזוקה שוטפת מסודרת. נמדד: **18 מתוך 141 (13%)** ממקטעי
  // התחזוקה מתחילים בדיוק כשתקלה נגמרת.
  //
  // ⚠️ הזיהוי חד-משמעי ואינו הערכה: `error.ended_at === maintenance.started_at`.
  // הסוכן סוגר מקטע ופותח את הבא באותו סבב דגימה, ולכן החותם משותף בדיוק.
  // תחזוקה שבאה אחרי 'מוכן' או אחרי 'בפעולה' לעולם לא תתאים לחותם כזה.
  //
  // ⚠️ **"טיפול" ולא "תיקון"**: ברוב המקרים הטכנאי מאתחל את המכונה ולא מתקן
  // דבר. "תיקון" טוען טענה על מה שנעשה; "טיפול" מתאר את מה שידוע.
  //
  // ⚠️ אותו כלל בדיוק קיים ב-shared/insights.mjs. שני עותקים של הכלל היו
  // נפרדים ביום שמישהו יתקן אחד מהם, ואז אותו מקטע היה "תפעול תקלה" במסך
  // אחד ו"תחזוקה" באחר.
  const errorEndSet = new Set(
    states.filter((s) => s.status === "error" && s.ended_at)
          .map((s) => `${s.site_id}|${s.ended_at}`)
  );

  /** האם התפעול תקלה שקטעה את הפעולה עבר לתחזוקה. */
  const handledInMaintenance = (siteId, at) => {
    const errEnd = errorEndedAt.get(`${siteId}|${at}`);
    return Boolean(errEnd) && startsAt.get(`${siteId}|${errEnd}`) === "maintenance";
  };

  // ==========================================================
  // האיחוד מסתיר **שתי** שורות, לא אחת
  // ==========================================================
  // ⚠️ זה היה באג, ונמדד: 43 מתוך 49 ההתחלות היתומות בכל הנתונים נוצרו כאן.
  //
  // `supersedeInterruptedAttempt` / `supersedeFlicker` מסמנות רק את שורת ה-end
  // שנקטעה — `superseded_by = id של הפתיחה החדשה`. אבל **הפתיחה החדשה עצמה
  // אינה מסומנת**, כי היא זו שמצביעים עליה. התוצאה בציר הייתה:
  //
  //     התחלה A · [סיום A מוסתר] · התחלה B · סיום B     ⟹  שתי התחלות, סיום אחד
  //
  // והקוראת רואה בדיוק את מה שהמשתמשת ראתה: רכב שהתחיל לצאת ולא סיים.
  //
  // המעבר הפיזי האחד הוא **התחלה A → סיום B**, ולכן שתי השורות האמצעיות
  // יורדות. הזיהוי אינו הערכה: כל ערך ב-superseded_by *הוא* ה-id של הפתיחה
  // המאחדת, ולכן הקבוצה מדויקת ונגזרת מהנתונים עצמם.
  //
  // ⚠️ ונגזרת בקריאה ולא עמודה חדשה — מאותו טעם שמתועד למטה ב"נקטעה":
  // כלל שנשמר לעמודה קופא, וההיסטוריה נשארת עם הפרשנות הישנה בלי סימן.
  //
  // ⚠️ מקרה קצה מקובל: אם הסגירה שאוחדה נפלה מחוץ לטווח הנטען והפתיחה בתוכו,
  // אין ממה לגזור. חלון האיחוד הוא 30 דקות לכל היותר, כך שזה רק גבול הטווח.
  const mergedStartIds = new Set(ops.map((o) => o.superseded_by).filter(Boolean));
  const visibleOps = ops.filter((o) => !o.superseded_by && !mergedStartIds.has(o.id));

  // ==========================================================
  // פעולה שנפתחה ולא נסגרה — סימון, לא השמטה
  // ==========================================================
  // אחרי שהאיחוד תוקן נשארו 6 מקרים אמיתיים בכל הנתונים. הסוכן מזהה לפי
  // **שינוי** ב-MODE, ולכן כשהרגיסטר נתקע במצב הפעולה לא נשלחת שום הודעת
  // סיום — לא מאוחר, פשוט לעולם לא. נמדד באתר 2438: 21 שעות ו-26 דקות
  // ב-'בפעולה' רצוף, ואז 'מוכן'.
  //
  // השורה נשארת בציר — היא קרתה — אבל בלי סימון היא נראית כמו **נתון חסר**
  // ולא כמו מכונה תקועה, וזה בדיוק ההפך מהמסקנה הנכונה.
  //
  // ⚠️ שתי מסקנות שונות, ואסור למזג אותן:
  //   unfinished — יש אירועים אחרי, והסיום מעולם לא הגיע. עובדה.
  //   pending    — זו הפעולה האחרונה בטווח. ייתכן שהיא רצה כרגע וייתכן
  //                שנקטעה בגבול הטווח, ואיננו יכולים לדעת. אי-ידיעה.
  //
  // ⚠️ הקבוצות מחזיקות את **האובייקטים** ולא id-ים. שורה בלי id (בדיקות, וכל
  // שולף עתידי ששכח אותה) הייתה נופלת ל-`undefined` אחד משותף וכל ההתחלות היו
  // מסומנות יחד. זהות אובייקט אינה יכולה להתנגש.
  const openState = new Map();       // "site|direction" -> שורת ה-start הפתוחה
  const unfinished = new Set();
  const chronological = [...visibleOps].sort((a, b) =>
    a.occurred_at < b.occurred_at ? -1 : a.occurred_at > b.occurred_at ? 1 : 0);
  for (const o of chronological) {
    const key = `${o.site_id}|${o.entry_exit}`;
    if (o.start_end === "start") {
      // פתיחה חדשה בזמן שקודמת פתוחה ⟹ הקודמת לא תיסגר לעולם.
      if (openState.has(key)) unfinished.add(openState.get(key));
      openState.set(key, o);
    } else {
      openState.delete(key);
    }
  }
  const pending = new Set(openState.values());

  return [
    ...visibleOps.map((o) => ({
      kind: "operation",
      // ⚠️ המזהה ושדות הניסוי — בלעדיהם אי אפשר לסמן שורה מהלוג הראשי,
      // וזה הלוג שממנו באמת עובדים. השם מוצג בשורה עצמה, ולכן הוא נשלף
      // כאן ולא בשאילתה נוספת לכל שורה.
      id: o.id ?? null,
      excludedAt: o.excluded_at ?? null,
      excludedBy: o.excluded_by ?? null,
      at: o.occurred_at,
      startEnd: o.start_end,
      entryExit: o.entry_exit,
      card: o.card_number || null,
      isAnomaly: !!o.is_anomaly,
      unfinished: unfinished.has(o),
      pending: pending.has(o),
      // רק על end: פתיחה לעולם אינה "נקטעת". null = הושלמה כרגיל.
      interruptedBy: o.start_end === "end"
        ? (interruptedBy.get(`${o.site_id}|${o.occurred_at}`) || null)
        : null,
      // הפעולה נקטעה בתקלה, והטיפול עבר לתחזוקה ⟹ המעבר הושלם ידנית.
      resolvedInMaintenance:
        o.start_end === "end" &&
        interruptedBy.get(`${o.site_id}|${o.occurred_at}`) === "error" &&
        handledInMaintenance(o.site_id, o.occurred_at),
      state: o.state,
      siteName: o.site_name ?? null,   // מוצג רק במצב "כל האתרים"
    })),
    ...visibleStates.map((s) => {
      const paired = pairedOpFor(s);
      return {
        kind: "status",
        id: s.id ?? null,
        excludedAt: s.excluded_at ?? null,
        excludedBy: s.excluded_by ?? null,
        // ============================================================
        // אימוץ חותם הפעולה — התיקון שמנקה גם את ההיסטוריה
        // ============================================================
        // מעבר MODE אחד נרשם בשתי טבלאות, ובמשך תקופה הוא נרשם עם **שני
        // חותמים שונים**: היישור בשרת חישב כל הודעה מול "עכשיו" שלה, והשתיים
        // עובדו בזו אחר זו. התוצאה בשטח (19 זוגות): המצב 'מוכן' נרשם שנייה
        // *לפני* "הפעולה הסתיימה" — כלומר האתר חזר להיות מוכן בזמן שהפעולה
        // עוד פתוחה. סדר שלא יכול לקרות.
        //
        // הקליטה תוקנה (clamp-memo.js + FUTURE_CLAMP_MIN_SECONDS), אבל השורות
        // שנכתבו כבר נשארות עם הפער. לכן שורת המצב מאמצת כאן את חותם הפעולה
        // שהיא חולקת איתה רגע: אירוע אחד, זמן אחד. זה מיישר את כל ההיסטוריה
        // מיד, בתצוגה, **בלי לשנות שורה אחת ב-DB** — הרישום הגולמי נשאר כפי
        // שהוא, וההצגה מפסיקה להציג ממנו סדר בלתי אפשרי.
        //
        // durationSeconds מחושב מהמקטע הגולמי במכוון: הפער הוא שנייה-שתיים,
        // זניח למשך, ואין סיבה להזיז גם אותו.
        at: paired ? paired.occurred_at : s.started_at,
        status: s.status,
        // תיאור התקלה מהבקר. ⚠️ null = **לא נקרא** (תקלה היסטורית, סוכן
        // ישן, בקר בלי התכונה), '' = נקרא והיה ריק. המסך מציג אותם
        // אחרת, ולכן אסור למזג אותם ל-"" אחד.
        faultText: s.fault_text ?? null,
        // תחזוקה שהתחילה בדיוק כשתקלה נגמרה — ראה errorEndSet למעלה.
        afterError: s.status === "maintenance"
          && errorEndSet.has(`${s.site_id}|${s.started_at}`),
        endedAt: s.ended_at,
        durationSeconds: secondsBetween(s.started_at, s.ended_at),
        siteName: s.site_name ?? null,
        // האם הפעולה גם הופכת את שורת המצב למיותרת (רק 'בפעולה'). מחושב **כאן
        // ולא בדשבורד** בכוונה: זו הצטלבות בין שתי רשימות עם סבילות זמן, וכל
        // צד שיחשב אותה בעצמו יסטה מהשני. הדשבורד רק קורא את הדגל, והמונה
        // בצ'יפ נספר לפי אותה סבילות (ראה למטה).
        explainedByOp: !!paired && REDUNDANT.has(s.status),
      };
    }),
    // ============================================================
    // ⚠️ תקלות שהושמטו בזמן תחזוקה — נראות, ולא נספרות
    // ============================================================
    // הן אינן ב-status_history בכוונה: שורת error שם הייתה סוגרת את מקטע
    // התחזוקה ומשנה את הזמינות. הן מגיעות מטבלה נפרדת שאף מדד אינו קורא
    // ממנה, ולכן **אחוז הכשל אינו יכול להשתנות מהן**.
    //
    // ⚠️ ו-kind נפרד ולא status:"error": מסנן ה"תקלות" סופר אירועים,
    // והכללתן שם הייתה מציגה מספר שסותר את אחוז הכשל שלידו — בדיוק
    // הסתירה שהפרדת הטבלאות נועדה למנוע.
    ...suppressed.map((f) => ({
      kind: "suppressedFault",
      at: f.occurred_at,
      faultText: f.fault_text ?? null,
      // 'window' = מישהו לחץ על הכפתור · 'plc' = הבקר לא באוטומט.
      // שתי מסקנות שונות, ולכן הלוג אומר איזו מהן.
      reason: f.reason,
      siteName: f.site_name ?? null,
    })),
    ...maint.map((m) => ({
      kind: "maintenance",
      // ⚠️ מזהה ושדות ניסוי — חלון תחזוקה ניתן לסימון בדיוק כמו כל שורה אחרת.
      id: m.id ?? null,
      excludedAt: m.excluded_at ?? null,
      excludedBy: m.excluded_by ?? null,
      at: m.started_at,
      setBy: m.set_by_name,
      role: m.set_by_role,
      reason: m.reason,
      durationHours: m.duration_hours,
      expiresAt: m.expires_at,
      cancelledAt: m.cancelled_at,
      siteName: m.site_name ?? null,
    })),
  ].sort((a, b) => {
    if (a.at !== b.at) return a.at < b.at ? 1 : -1;   // מהחדש לישן
    return phaseRank(b) - phaseRank(a);               // באותו רגע: המאוחר לוגית קודם
  });
}

/**
 * הציר המלא → עמוד מסונן + מונים. זו השכבה שה-API מחזיר.
 */
export function buildActivityLog({
  ops, states, maint, suppressed = [], limit,
  offset = 0, filter = "all", card = null, capped = false,
}) {
  const all = buildTimeline({ ops, states, maint, suppressed });

  // ============================================================
  // הסינון עבר לכאן — והחיתוך חייב לבוא *אחריו*
  // ============================================================
  // קודם הסינון רץ בדפדפן, על מה שכבר נחתך ל-limit. זה היה שגוי בשני מובנים,
  // והשני חמור מהראשון:
  //
  //   1. **"שבוע" לא הראה שבוע.** נמדד: 3,124 שורות ב-7 הימים האחרונים מול
  //      תקרה של 300 — כלומר המשתמש קיבל בערך את היממה האחרונה תחת הכותרת
  //      "7 הימים האחרונים". בחודש הפער גדול פי ארבעה.
  //
  //   2. **הסינון סינן את החיתוך, לא את התקופה.** לחיצה על "תחזוקה" הציגה רק
  //      אירועי תחזוקה שבמקרה נכנסו ל-300 החדשים ביותר. אתר שהיה בתחזוקה
  //      לפני חמישה ימים פשוט לא הופיע — והמסך לא רמז שמשהו חסר.
  //
  // עכשיו: בונים את הציר המלא, מסננים, ורק אז חותכים לעמוד. total הוא גודל
  // הקבוצה **המסוננת**, ולכן "טען עוד" יודע מתי לעצור.
  // ==========================================================
  // חיפוש הכרטיס מצמצם גם את המונים — לא רק את הרשימה
  // ==========================================================
  // קודם הוא צמצם רק את השורות: בחיפוש כרטיס 7 הצ'יפ "פעולות" הראה 1,529
  // בזמן ש-99 שורות נפתחו. זו בדיוק ההבטחה שהמונים נועדו לקיים, ושבירתה כאן
  // הייתה גרועה מהמצב הקודם — כי המספר נראה סמכותי ואינו קשור למה שמוצג.
  //
  // לכן הצמצום קורה **לפני** הכול, ומכאן ואילך `scope` הוא כל מה שקיים.
  const needle = (card || "").trim();
  const scope = needle
    ? all.filter((e) => e.kind === "operation" && e.card === needle)
    : all;

  const wanted = LOG_FILTERS[filter] || LOG_FILTERS.all;
  const filtered = scope.filter(wanted);

  const start = Math.max(0, offset | 0);
  const entries = filtered.slice(start, start + limit);

  return {
    entries,
    offset: start,
    total: filtered.length,
    // truncated = יש עוד מעבר לעמוד הזה. הדשבורד מציג לפיו "טען עוד".
    truncated: start + entries.length < filtered.length,
    // הגענו לתקרת השליפה — הציר עצמו חלקי, לא רק העמוד. נדיר, אבל אם קורה
    // עדיף לומר זאת מאשר להציג "סה\"כ" שקטן מהאמת.
    capped: Boolean(capped),
    // ============================================================
    // המונים נספרים מאותו ציר שנפתח — לא בשאילתה נפרדת
    // ============================================================
    // קודם כל מונה היה COUNT(*) משלו ב-SQL, כי הציר היה חתוך ל-300 ולא יכול
    // היה לספר על התקופה כולה. זה עבד, אבל דרש שכל כלל יתקיים פעמיים — פעם
    // ב-SQL ופעם ב-JS — וההערות סביבו מלאות בתיקונים למקומות שבהם השניים
    // סטו (הוצאת 'בפעולה', תקלות שהוסתרו בתחזוקה, 'בפעולה' יתום).
    //
    // מרגע שהציר המלא נבנה כאן ממילא, המונה הוא **אורך הקבוצה המסוננת**.
    // הצ'יפ שווה למספר השורות שנפתחות בהגדרה, לא במקרה. תקלות שהוסתרו בזמן
    // תחזוקה כבר אינן ב-`all` (visibleStates), ולכן הן יורדות מעצמן ואין צורך
    // בחיסור מתקן.
    //
    // ⚠️ המחיר: אם נגמלה תקרת השליפה, המונים חלקיים כמו הציר. לכן `capped`
    // מוחזר — עדיף לומר "חלקי" מאשר להציג מספר שנראה מלא ואינו.
    counts: Object.fromEntries(
      Object.entries(LOG_FILTERS).map(([key, fn]) => [key, scope.filter(fn).length])
    ),
  };
}

