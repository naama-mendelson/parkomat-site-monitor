// 17/09/2026: "יתכן וגרוזנברג והזורע יהיו אותו סוג, לדוגמא XY, אך הם מסוג אחר
// ולכן הם צריכים לקבל סוג טיפול תקלה שונה". בכונן `איתור תקלות` יש `xy לולק`
// ו-`ביטנקם xy`, `דולי` ו-`דולי ביטנקם`, `שאטל מסילה` ו-`שאטל מסילה ביטנקם` —
// אותו סוג, ספרייה אחרת לגמרי.
//
// ⚠️ **הערכים הם השמות עצמם, ולא מפתחות באנגלית.** זה בדיוק מה שכתוב בעמודה
// "סוג מערכת הפעלה" בטבלת האתרים, ובדיוק שמות המערכות ב-FixFlow. מפתח מתורגם
// היה עוד טבלת המרה — ועוד מקום לסטות בו.
//
// ⚠️ **ארבעה, ולא שניים.** הטבלה מכילה גם סוטפין (14 אתרים) וסוטפין-לולק (אחד
// העם 13). אין להם ספריית תקלות היום, אבל אתר כזה צריך להיות ניתן לתיאור נכון
// — אחרת הוא יסומן לולק "כי זו האפשרות הקרובה", ויקבל נהלים של מכונה אחרת.
//
// ⚠️ **המסד אוכף את אותה רשימה** (`app.check_control_system`), ובדיקה ב-
// tests/fixflow-profiles.test.js משווה בין השתיים.
export const CONTROL_SYSTEMS = [
  { key: "לולק", label: "לולק" },
  { key: "ביטנקם", label: "ביטנקם" },
  { key: "סוטפין", label: "סוטפין" },
  { key: "סוטפין-לולק", label: "סוטפין-לולק" },
];

export const CONTROL_SYSTEM_KEYS = CONTROL_SYSTEMS.map((s) => s.key);

/** ערך מנורמל, או null כשאין / ריק. ערך שאינו ברשימה מוחזר כמות שהוא — הקורא מחליט. */
export function normalizeControlSystem(v) {
  const t = String(v ?? "").trim();
  return t ? t : null;
}

/** התווית להצגה. "לא הוגדר" ולא ריק — שדה ריק על המסך נראה כמו תקלה בטעינה. */
export function controlSystemLabel(v) {
  return normalizeControlSystem(v) ?? "לא הוגדר";
}
