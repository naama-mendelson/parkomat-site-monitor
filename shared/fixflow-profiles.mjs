/**
 * הפרופיל של אתר, לפי סוג המכונה שלו.
 *
 * @param {string|null} plcType  הערך מ-`sites.plc_type`
 * @param {string|null} system   "לולק" / "ביטנקם" — נדרש רק כשהסוג עמום
 * @returns {{status:string, system?:string, profile?:string, reason?:string}}
 *   status: 'ok' | 'no-type' | 'needs-system' | 'unmapped'
 */
export function resolveProfile(plcType, system = null) {
  if (!plcType) return { status: "no-type", reason: "לא הוגדר סוג מכונה לאתר" };

  const entry = PROFILE_BY_TYPE[plcType];
  if (!entry) {
    const why = UNRESOLVED_TYPES[plcType];
    if (why) return { status: "unmapped", reason: why };
    // ⚠️ סוג תקין שאינו במפה ואינו ברשימת הלא-מוכרעים הוא **סוג חדש שנוסף
    // ואיש לא מיפה**. הוא חייב להיראות אחרת מ"לא ידוע", אחרת התוספת הבאה
    // ל-site-types.mjs תיצור אתרים ריקים בלי שאיש ישים לב.
    return {
      status: "unmapped",
      reason: SITE_TYPE_KEYS.includes(plcType)
        ? `הסוג "${plcType}" קיים במערכת אך לא מופה לתיקייה בכונן`
        : `סוג לא מוכר: "${plcType}"`,
    };
  }

  if (entry.bySystem) {
    if (!system) {
      return {
        status: "needs-system",
        reason: `הסוג "${plcType}" קיים בשתי המערכות (${Object.keys(entry.bySystem).join(" / ")}) — צריך לדעת באיזו`,
      };
    }
    const hit = entry.bySystem[system];
    if (!hit) return { status: "unmapped", reason: `המערכת "${system}" אינה מוכרת עבור הסוג "${plcType}"` };
    return { status: "ok", ...hit };
  }

  return { status: "ok", ...entry };
}

/**
 * ההחלטה המלאה: לאן אתר מגיע ב-FixFlow, לפי מפת האתרים ואז לפי סוג המכונה.
 *
 * ============================================================
 * ⚠️ מימוש אחד, שני קוראים
 * ============================================================
 * הדשבורד (`services/fixflow.js`) והשער (`tools/check-fixflow-mapping.js`)
 * שואלים את אותה שאלה, ולכן הם חייבים לקבל את אותה תשובה. כשהם החזיקו כל אחד
 * את הלוגיקה שלו, השער דיווח "14 מחוברים" בזמן שהמסך חיבר 25 — כי הוא הכיר רק
 * את המיפוי לפי סוג. שער שמודד משהו אחר ממה שנשלח הוא לא שער.
 *
 * סדר ההחלטה:
 *   0. **בחירה שנשמרה על האתר** (`fixflow_profile`) — מפורשת, וגוברת על הכול.
 *   1. התאמת שם מדויקת → קישור **ברמת האתר**, כלומר עם חריגות האתר.
 *   2. ⚠️ אלא אם הספרייה שהשם מוביל אליה ריקה והסוג מוביל לאחת עם תוכן —
 *      גולדברג 5 מתאים בשם לפרופיל `שאטל מצבט y` שיש בו 0 מסמכים לנצח, בזמן
 *      ש-`שאטל מצבט y שמסובבת בשאטל` מחזיק 38. רשימה ריקה אינה מציגה שגיאה;
 *      היא נראית בדיוק כמו "אין תקלות ידועות".
 *   3. אחרת לפי סוג המכונה.
 *   4. אחרת סירוב **עם סיבה**, ולא כפתור שמנחש.
 *
 * @param {{code?: string|number, plc_type?: string|null, fixflow_profile?: string|null}} site
 * @param {{sites?: Record<string, any>, profiles?: Record<string, any>}} map  נוצרת ב-build-fixflow-map.js
 */
export function resolveLink(site, map) {
  // ============================================================
  // ⚠️ 0. הבחירה שנשמרה על האתר — גוברת על הכול
  // ============================================================
  // שלוש שיטות ניסו לגזור את הספרייה מהנתונים, וכולן שחזרו עובדה שאדם יודע
  // בשנייה: התאמת שם (נכשלת באתר שאינו ברשימת 117 של FixFlow — כלומר בכל
  // אתר חדש), גזירה מסוג המכונה (`xy` קיים בשתי המערכות), וניתוח נוסח
  // התקלות (אומת — ומסרב כשהראיה דקה, וזה רוב הזמן).
  //
  // ⚠️ **והחמור מכול: גזירה אינה יכולה לעבוד בעיקרון.** ללולק לבדה שישה
  // פרופילי מצבט, ו-FixFlow מתייקת 5 אתרים ל-`שאטל מצבט x` שיש בו 0
  // מסמכים בזמן ש-25 המסמכים יושבים ב-`שאטל מצבט שמסובבת במעלית` שיש בו
  // אתר אחד. סבך כזה במקור אינו ניתן להתרה בכלל — רק להכרעה.
  //
  // ⚠️ **ולמה זה חייב להישמר במסד ולא בקובץ.** המפה נבנית בכלי על מחשב
  // הפיתוח ונכתבת ל-JSON בריפו. כלומר: את אינך יכולה לשנות קישור, ואתר
  // שנרשם מחר נשאר בלי קישור עד שמישהו יריץ כלי וידחוף קוד. בחירה שנשמרת
  // על האתר עצמה תופסת מיד, כמו כל שאר עריכת האתר.
  const chosen = String(site?.fixflow_profile ?? "").trim();
  if (chosen) {
    // ============================================================
    // ⚠️ שתי רמות קישור, ולא אחת — וההבדל הוא 22 חריגות
    // ============================================================
    // `site:<id>`        → קישור ל**אתר** ב-FixFlow: התקלות של סוג המכונה
    //                      **בתוספת חריגות האתר**, כלומר דרך טיפול שנכתבה
    //                      למתקן הזה בלבד.
    // `מערכת|פרופיל`     → קישור ל**ספרייה**: סוג המכונה בלבד.
    //
    // ⚠️ הגרסה הראשונה של הבורר הציעה ספריות בלבד, וזו הייתה רגרסיה שקטה:
    // גרוזנברג 7 מחזיק **15 מתוך 22** חריגות האתר הקיימות, ובחירה ידנית של
    // ספרייה שם הייתה מוחקת אותן מהמסך בלי שום סימן.
    if (chosen.startsWith("site:")) {
      const id = chosen.slice(5).trim();
      if (!id) return { status: "bad-choice", reason: `הקישור לאתר אינו תקין: "${chosen}"` };
      const hit = map?.ffSites?.[id];
      return {
        status: "ok",
        by: "chosen-site",
        siteId: id,
        // ⚠️ `scope` הוא מה שה-title בכרטיס מציג. כשהמפה אינה מכירה את המזהה
        // (פרופיל שנוסף ב-FixFlow אחרי בניית המפה) עדיף המזהה על פני ריק —
        // כותרת ריקה נראית כמו באג ולא כמו מידע חסר.
        scope: hit?.name ?? id,
        system: hit?.system,
        profile: hit?.profile,
        docs: hit?.docs,
        overrides: hit?.overrides,
      };
    }

    const [system, ...rest] = chosen.split("|");
    const profile = rest.join("|").trim();
    // ⚠️ ערך פגום אינו נבלע בשקט. שדה חופשי שנשמר שגוי היה מחזיר את האתר
    // לגזירה — כלומר לכפתור שעובד, שמוביל למקום אחר ממה שנבחר.
    if (!system?.trim() || !profile)
      return { status: "bad-choice", reason: `הספרייה שנבחרה אינה תקינה: "${chosen}"` };
    return {
      status: "ok",
      by: "chosen",
      scope: profile,
      system: system.trim(),
      profile,
      docs: map?.profiles?.[chosen]?.docs,
    };
  }

  const entry = map?.sites?.[String(site?.code)];
  if (entry?.by === "name") {
    return {
      status: "ok",
      by: "name",
      scope: entry.siteName,
      siteId: entry.siteId,
      system: entry.system,
      profile: entry.profile,
      docs: entry.docs,
    };
  }
  if (entry?.by === "type") {
    return { status: "ok", by: "type", scope: entry.profile, system: entry.system, profile: entry.profile, docs: entry.docs };
  }
  // ⚠️ נפילה ל-resolveProfile ולא הסתמכות על המפה בלבד: המפה היא תמונת מצב
  // שנוצרה בפקודה, ואתר שנרשם אחריה אינו בה. סוג מכונה שכבר הוגדר לו יביא
  // אותו לספרייה הנכונה בלי שאיש יריץ שום דבר מחדש.
  const t = resolveProfile(site?.plc_type ?? null, null);
  if (t.status !== "ok") return { status: t.status, reason: t.reason };
  return { status: "ok", by: "type", scope: t.profile, system: t.system, profile: t.profile, docs: undefined };
}
