// shared/site-systems.mjs — אתר שבבקר שלו שתי מערכות: מה מציגים, ומתי בכלל.
//
// ============================================================
// ⚠️ מימוש אחד, שני קוראים — ולא במקרה
// ============================================================
// הכלל הזה נדרש גם ב-`sitesDirect` (רשימת האתרים) וגם ב-`supervisorShape`
// (מסך המפקח). כשכתבתי אותו פעמיים, שני העותקים היו זהים **באותו רגע** —
// וזו בדיוק הנקודה שבה עותק מתחיל לסטות: מי שיתקן במקום אחד לא ידע שיש שני.
// הפרויקט כבר שילם על זה (שלוש העתקות של `site-{code}@parkomat.co.il`).

// ⚠️ הדירוג הוא **ההפך** מזה של `SiteStateAggregator` בסוכן, ובכוונה:
// שם מחפשים את הטוב (מה עדיין עובד, כלומר מה שנמדד כזמינות), כאן את הגרוע
// (מה דורש טיפול עכשיו). שתי הפונקציות מתארות את אותו אתר ואינן סותרות —
// הן עונות על שתי שאלות שונות.
export const WORST_RANK = { error: 0, no_comm: 1, maintenance: 2, operating: 3, ready: 4 };

/**
 * פירוט המערכות, או null כשאין מה לומר עליו.
 *
 * ============================================================
 * ⚠️ אין תקשורת — הפירוט אינו "מידע ישן", הוא טענה שגויה
 * ============================================================
 * `systems` מגיע מהפעימה האחרונה של הסוכן. כשהסוכן מפסיק לפעום השורה נשארת
 * כפי שהייתה, ולכן היא מתארת את מה שהיה **לפני הנתק** — בזמן שהמסך מציג אותה
 * כמצב הנוכחי.
 *
 * ⚠️ **וזה לא רק הצגה.** `displayStatus` נגזר מכאן, ולכן אתר דו-מערכתי שאיבד
 * תקשורת היה מוצג לפי המצב הישן של המערכות — כלומר "מוכן", ירוק — במקום
 * "מנותק". אתר מנותק שנראה תקין הוא בדיוק הכשל שכל מנגנון זיהוי הנתק קיים
 * כדי למנוע.
 */
export const SYSTEMS_STALE_MS = 3 * 60 * 1000;

export function liveSystems(status, systems, seenAt = null, now = Date.now()) {
  if (status === "no_comm") return null;
  if (!Array.isArray(systems) || systems.length === 0) return null;

  // ============================================================
  // ⚠️ הפירוט בן כמה דקות, או בן עשר שעות — וזה לא נראה על המסך
  // ============================================================
  // נמדד בפלורנטין ב-15/09: הכרטיס הציג `בפעולה` לצד `1 המתנה · 2 תחזוקה`.
  // שני הנתונים היו נכונים ואף אחד מהם לא סתר את השני — הם פשוט תיארו שני
  // רגעים שונים. המצב הגיע ב-MQTT ב-09:28, והפירוט היה מהפעימה של **אתמול
  // ב-22:58**. על המסך הם נראו כמו תיאור אחד של עכשיו.
  //
  // ⚠️ הסף הוא 3 דקות — **אותו סף בדיוק** ש-`app.mark_silent_agents` משתמשת
  // בו (שלוש פעימות שהוחמצו). סף אחר כאן היה יוצר מצב שבו הפירוט נחשב טרי
  // בזמן שהשרת כבר מחשיב את הסוכן שותק, ולהפך.
  //
  // ⚠️ וחסרון חותמת אינו "טרי". אתר שלא החזיר `systems_seen_at` הוא אתר
  // שאיננו יודעים מתי נקרא, וזה בדיוק המצב שבו אסור להציג.
  //
  // ⚠️ **ובדיקה אחת ולא שתיים.** היה כאן `if (!seenAt) return null` לפני
  // השורה הזו. הוא נראה כמו ההגנה על חותמת חסרה, והיה **קוד מת**:
  // `Date.parse(null)` מחזיר NaN, ו-`Number.isFinite` כבר תופס אותו. מוטציה
  // שמחקה אותו עברה בירוק — כלומר הוא לא הגן על דבר, ורק הסתיר מי כן מגן.
  const t = Date.parse(seenAt);
  if (!Number.isFinite(t) || now - t > SYSTEMS_STALE_MS) return null;

  return systems;
}

/**
 * המצב הגרוע מבין המערכות, או null כשאין אף מצב מוכר.
 *
 * ⚠️ `unknown` מדולג ואינו נחשב גרוע: MODE 4 (אתחול) או ערך שלא מופה אינם
 * "תקלה". ספירתם כגרוע הייתה צובעת אתר באדום על בסיס ערך שאיננו מבינים.
 */
export function worstOfSystems(systems) {
  if (!Array.isArray(systems) || systems.length === 0) return null;
  let worst = null;
  for (const u of systems) {
    const st = String(u?.state ?? "").trim();
    if (!(st in WORST_RANK)) continue;
    if (worst === null || WORST_RANK[st] < WORST_RANK[worst]) worst = st;
  }
  return worst;
}

/**
 * המצב להצגה: הגרוע מבין המערכות כשיש מה להסתמך עליו, אחרת מצב האתר עצמו.
 *
 * ⚠️ `status` עצמו **אינו** נוגע. הוא מה שנכתב ל-`status_history`, וממנו
 * מחושבות הזמינות ואחוז הכשל — שינוי שלו היה מעביר גם אותם לגרוע, כלומר
 * בדיוק ההפך מהכלל שנקבע ("הצגה לפי הגרוע, מדידה לפי הטוב").
 */
export function displayStatusFor(status, systems, seenAt = null, now = Date.now()) {
  // ============================================================
  // ⚠️ הגרוע מבין **מצב האתר והמערכות יחד** — ולא המערכות במקומו
  // ============================================================
  // שתי גרסאות קודמות היו שגויות, וכל אחת בכיוון אחר:
  //
  //   1. הגיל פסל פירוט ישן ⇒ פלורנטין, שמערכת שלמה בה אינה באוטומט,
  //      הוצגה "מוכן".
  //   2. המערכות **החליפו** את מצב האתר ⇒ פירוט ישן שאמר `[המתנה, תחזוקה]`
  //      הסתיר תקלה עכשווית, כי `תחזוקה` טובה מ`תקלה` בדירוג. נצפה בפלורנטין
  //      ב-15/09: הבקר דיווח `מנהל דולים - דלתות חניון פתוחות` והצ'יפ היה
  //      אמור להיקרא "בתחזוקה".
  //
  // ⚠️ **הכלל השני גרוע מהראשון**: הראשון הציג ירוק במקום כתום, השני היה
  // מסתיר תקלה. מדד תצוגה לא יכול להפוך אתר לתקין יותר ממה שהוא מדווח.
  //
  // לכן `status` משתתף בדירוג ואינו מוחלף. התוצאה עונה על שני הכללים:
  //   `status=ready`  + `[מוכן, תחזוקה]` → תחזוקה   (מספיק שאחת בתחזוקה)
  //   `status=error`  + `[מוכן, תחזוקה]` → תקלה     (תקלה אינה נעלמת)
  //
  // ⚠️ ו-`status` עצמו **אינו** משתנה. הוא מה שנכתב ל-`status_history`, וממנו
  // מחושבות הזמינות ואחוז הכשל — הן ממשיכות להימדד לפי הטוב, כפי שנקבע.
  const states = [status, ...(Array.isArray(systems) ? systems.map((u) => u?.state) : [])];
  let worst = null;
  for (const st of states) {
    const k = String(st ?? "").trim();
    if (!(k in WORST_RANK)) continue;
    if (worst === null || WORST_RANK[k] < WORST_RANK[worst]) worst = k;
  }
  return worst ?? status;
}


/**
 * גיל הפירוט בדקות, או null כשאין חותמת.
 *
 * ============================================================
 * ⚠️ להציג את הגיל, לא להסתיר את הנתון
 * ============================================================
 * הגרסה הראשונה של התיקון **הסתירה** פירוט ישן והחליפה אותו ב"אינו עדכני".
 * זו הייתה החמרה, ונמדדה בשטח: בפלורנטין הפירוט אמר `2 תחזוקה` מלפני עשר
 * שעות — **וזה היה נכון**. הלובי השמאלי באמת לא באוטומט, וההסתרה מחקה בדיוק
 * את המידע שבגללו מסתכלים על הכרטיס.
 *
 * נתון ישן אינו נתון שגוי. מה שהיה שגוי הוא להציג אותו **בלי לומר שהוא ישן**,
 * לצד מצב עדכני, כאילו שניהם מתארים את אותו רגע.
 */
export function systemsAgeMinutes(seenAt, now = Date.now()) {
  const t = Date.parse(seenAt ?? "");
  if (!Number.isFinite(t)) return null;
  return Math.max(0, Math.round((now - t) / 60000));
}
