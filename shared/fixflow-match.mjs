//
// ============================================================
// ⚠️ למה זה עובד בכלל: שני הצדדים נכתבו מול אותו בקר
// ============================================================
// הבקר כותב `מנהל חניון - דלתות חניון פתוחות:`, והמסמך בכונן נקרא
// `מנהל חניון -דלתות חניון פתוחות`. זו אינה התאמה סמנטית אלא **אותו משפט**
// עם הבדלי פיסוק — כי מי שכתב את הנוהל העתיק את הכיתוב מהמסך.
//
// נמדד על 90 צמדי (אתר, נוסח תקלה) אמיתיים מההיסטוריה: **47% נמצא להם נוהל**
// בציון ≥ 0.55, ורובם ב-0.88–1.00. השאר אינם "התאמה חלשה" אלא תקלות שאין
// עליהן מסמך בכונן — וזה מצב שצריך לומר, לא לגשר עליו.
//
// ============================================================
// ⚠️ ומשקל לפי נדירות, לא ספירת מילים
// ============================================================
// `מסובבת`, `שאטל`, `מגש`, `זמן` מופיעים כמעט בכל כותרת ואינם מבחינים בכלום;
// `אוברלואד`, `אנקודר`, `דקלוק` מופיעים בכותרת אחת או שתיים. בלי משקל, שתי
// תקלות שונות לגמרי באותה משפחה מקבלות ציון גבוה — וזו בדיוק ההתאמה השגויה
// שהמנגנון הזה מסוכן בלעדיה: נוהל של תקלה אחרת נראה למוקדן בדיוק כמו הנוהל
// הנכון, וכל הצעדים בו סבירים.

const BIDI = /[‎‏‪-‮⁦-⁩]/g;

/**
 * ⚠️ **ספרות אינן הופכות למונח, וזה נובע מהמפריד ולא משורת מחיקה.**
 * המחלקה `[^֐-׿A-Za-z]` רואה ספרה כמפריד, ולכן `מיטה 13` נותן
 * `['מיטה']` ו-`שאטל 1,2` נותן `['שאטל']`. זה בדיוק מה שצריך: הבקר כותב
 * `שאטל 1` והמסמך נקרא `שאטל 1,2` — אותה תקלה.
 *
 * ⚠️ היה כאן `.replace(/[0-9]+/g, " ")` לפני הפיצול, והוא היה **קוד מת**.
 * מוטציה שמחקה אותו עברה בירוק, ומדידה הראתה למה: המפריד כבר עושה את
 * העבודה. קוד שנראה כמו הגנה ואינו מגן מסתיר מי כן מגן — אותו לקח בדיוק
 * כמו `if (!seenAt)` ב-site-systems.
 *
 * ו-`מספר` נמחקת כי היא ה-placeholder בכותרות (`מיטה (מספר)`).
 *
 * ⚠️ **ו-`length >= 2` נמדד ואינו משנה דבר.** מוטציה שהרפתה אותו ל-1 עברה
 * בירוק, ומדידה על **92 הצמדים האמיתיים** נתנה 40 התאמות בשני המקרים, עם
 * 0 הבדלים בתוצאה. הוא נשאר כהיגיינה של טוקניזציה, ו**אף בדיקה אינה טוענת
 * שהיא מגנה עליו** — טענה כזו הייתה יוצרת ביטחון שאין מאחוריו מדידה.
 */
export function tokens(s) {
  return new Set(
    String(s ?? "")
      .replace(BIDI, "")
      .split(/[^֐-׿A-Za-z]+/)
      .map((w) => w.trim())
      .filter((w) => w.length >= 2 && w !== "מספר")
  );
}

/**
 * טבלת משקלים מתוך אוסף הכותרות. מונח נדיר מקבל משקל גבוה.
 *
 * ⚠️ נבנית **פעם אחת** לכל האוסף ולא לכל השוואה. בניה חוזרת בתוך לולאה על 319
 * כותרות הייתה הופכת התאמה אחת לעבודה של רבע מיליון פעולות, בכל רינדור של
 * כרטיס — כלומר תכונה שמאיטה את המסך בדיוק כשיש תקלה.
 */
export function buildWeights(faults) {
  const df = new Map();
  const cache = new Map();
  for (const f of faults) {
    const tk = tokens(f.title);
    cache.set(f, tk);
    for (const w of tk) df.set(w, (df.get(w) ?? 0) + 1);
  }
  const n = faults.length || 1;
  return { weight: (w) => Math.log(1 + n / (1 + (df.get(w) ?? 0))), tokensOf: (f) => cache.get(f) ?? tokens(f.title) };
}

/**
 * דמיון בין שתי קבוצות מונחים: F1 של שתי הכיסויות, ממושקל.
 *
 * ⚠️ **F1 ולא כיסוי בכיוון אחד.** כיסוי הכותרת לבדו נותן ציון מלא לכותרת קצרה
 * שנבלעת בכל תקלה ארוכה; כיסוי התקלה לבדו נותן ציון מלא לכותרת ארוכה שמכילה
 * הכול. שתי הטעויות נמדדו בגרסה מוקדמת של המסווג.
 */
export function similarity(a, b, weight) {
  let inter = 0, at = 0, bt = 0;
  for (const w of a) { const x = weight(w); at += x; if (b.has(w)) inter += x; }
  for (const w of b) bt += weight(w);
  if (inter === 0 || at === 0 || bt === 0) return 0;
  const pa = inter / at, pb = inter / bt;
  return (2 * pa * pb) / (pa + pb);
}

/** הסף שנמדד. מתחתיו — אומרים "אין נוהל", ולא מציגים את הקרוב ביותר. */
export const MIN_SCORE = 0.55;

/**
 * ⚠️ שתי כותרות **שונות** באותו ציון הן עמימות, לא הצלחה.
 * נמדד: `מסובבת שאטל 1 - זמן מקסימלי לתנועה` קיבל 0.58 מול 0.54 לשנייה —
 * הפרש שאין להסתמך עליו כשהכותרות מתארות מתקנים שונים.
 */
export const MIN_MARGIN = 0.03;

/**
 * מוצא את הנוהל שמתאים לנוסח התקלה, או null.
 *
 * @param {string} faultText  הטקסט שהבקר כתב
 * @param {Array<{id,title,warning}>} faults  הנהלים של **הספרייה של האתר בלבד**
 * @returns {{fault, score, runnerUp}|null}
 */
export function matchFault(faultText, faults, model = null, { rank = null } = {}) {
  if (!faultText || !Array.isArray(faults) || faults.length === 0) return null;
  const m = model ?? buildWeights(faults);
  const q = tokens(faultText);
  if (q.size === 0) return null;

  let best = null, bestScore = 0, second = 0, secondTitle = null;
  for (const f of faults) {
    const s = similarity(q, m.tokensOf(f), m.weight);
    if (s > bestScore) {
      second = bestScore; secondTitle = best?.title ?? null;
      bestScore = s; best = f;
    } else if (s > second) { second = s; secondTitle = f.title; }
  }

  if (!best || bestScore < MIN_SCORE) return null;

  // ⚠️ כותרת **זהה** שחוזרת פעמיים אינה עמימות — זו אותה תקלה שמתויקת פעמיים,
  // ובחירת הראשונה נכונה. עמימות היא שתי כותרות **שונות** באותו ציון.
  if (secondTitle && secondTitle !== best.title && bestScore - second < MIN_MARGIN) {
    // ============================================================
    // ⚠️ שקולים — הכרעה לפי **מקור** המסמך, ורק אם היא חד-משמעית
    // ============================================================
    // נמדד (24/09/2026): 6 זוגות בספריות הם אותה כותרת בפיסוק אחר, ובכל
    // אחד **התוכן שונה** — מסמך כללי מול "הדגש לאתר" אחר, או שני אתרים.
    // לכן הסירוב נכון כשאין דרך להבחין. אבל כשאחד המועמדים נכתב **לאתר
    // הזה**, או שהוא הכללי מול הדגשים של אתרים אחרים — יש.
    // `rank` נמוך = עדיף. שני אתרים זרים באותה דרגה — ממשיכים לסרב.
    if (!rank) return null;
    const contenders = faults.filter((f) => {
      const s = similarity(q, m.tokensOf(f), m.weight);
      return s >= MIN_SCORE && s > bestScore - MIN_MARGIN;
    });
    // ⚠️ **רק כשכולם אותה כותרת** (אותן מילים — פיסוק וספרות אינם מילים).
    // מקור המסמך מכריע בין שתי **גרסאות** של אותה תקלה; הוא אינו אומר דבר על
    // איזו מבין שתי תקלות **שונות** נכונה. נמדד: בלי ההגבלה "מסובבת שאטל 1 -
    // זמן מקסימלי לתנועה" הוצמד ל"מסובבת - זמן מקסימלי **להפסקת** מסובבת"
    // רק משום שהוא כללי והשני הדגש של אתר אחר.
    const sig = (f) => [...m.tokensOf(f)].sort().join(" ");
    if (new Set(contenders.map(sig)).size !== 1) return null;
    const top = Math.min(...contenders.map(rank));
    const winners = contenders.filter((f) => rank(f) === top);
    if (new Set(winners.map((f) => f.title)).size !== 1) return null;
    const w = winners.reduce((a, b) =>
      similarity(q, m.tokensOf(b), m.weight) > similarity(q, m.tokensOf(a), m.weight) ? b : a);
    return { fault: w, score: similarity(q, m.tokensOf(w), m.weight), runnerUp: second, byRank: true };
  }

  return { fault: best, score: bestScore, runnerUp: second };
}
