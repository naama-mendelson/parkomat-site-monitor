// ⚠️ **והסיבה לא הייתה גודל הפונט אלא חלוקת הרוחב.** מתוך 203px בכותרת,
// תג הסוג (64–89px) ותג הדרגה (47px) לקחו 111–136px ולשם נשארו 43 —
