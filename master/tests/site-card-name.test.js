// המדידה **כן** נעשתה בדפדפן, והיא זו שמצאה את הבאג. הבדיקה הזו נועדה
// למשהו אחר: לשרוד אחרי שהרתמה ההיא נעלמת. היא רצה בכל הרצה של החבילה,
// בלי רשת ובלי דפדפן, ומקבעת את שלוש ההחלטות שאפשר לבטל בטעות בשורה
// אחת — בדיוק הדפוס של `alert-audio.test.js` ו-`client-ip.test.js`.
const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");

const CSS = fs.readFileSync(
  path.join(__dirname, "..", "..", "dashboard", "src",
            "components", "SiteCard", "SiteCard.css"), "utf8");

/** גוף כלל CSS לפי הסלקטור שלו, בלי הערות. */
function rule(selector) {
  const clean = CSS.replace(/\/\*[\s\S]*?\*\//g, "");
  const at = clean.indexOf(selector + " {");
  assert.ok(at >= 0, `כלל חסר ב-SiteCard.css: ${selector}`);
  const open = clean.indexOf("{", at);
  const close = clean.indexOf("}", open);
  return clean.slice(open + 1, close);
}

test("לשם יש רצפת רוחב", () => {
  assert.match(rule(".card-name-text"), /min-width:/,
    "בלי רצפה, השם מתכווץ עד שהוא נחתך — כי הוא היחיד שיכול להתכווץ");
});

test("הרצפה אינה נמדדת בפונט של השם עצמו", () => {
  // ⚠️ זה היה הניסיון הראשון, והוא נמדד ככושל: `10ch` נגזר מהפונט של
  // האלמנט — בדיוק זה ש-`useFitName` מקטין. כל הקטנה מקטינה גם את
  // הרצפה, הרוחב הזמין מתכווץ איתה, והטקסט רודף אחרי מטרה שבורחת.
  // נמדד: 4 שמות נשארו חתוכים אף שהפונט הוקטן.
  const m = /min-width:\s*([^;]+);/.exec(rule(".card-name-text"));
  assert.ok(m, "min-width לא נמצא");
  // ⚠️ `\bch\b` **אינו** תופס את `10ch` — בין הספרה ל-c אין גבול מילה,
  // וזו בדיוק הצורה שתיכתב. הניסוח הראשון כאן היה ירוק על `10ch`,
  // והמוטציה שרדה. מספר ואחריו `ch` הוא מה שצריך לחפש.
  assert.doesNotMatch(m[1], /[\d.]\s*ch\b/,
    `הרצפה היא "${m[1].trim()}" — יחידה שתלויה בפונט של האלמנט, ולכן רודפת אחרי ההקטנה`);
});

test("תג הסוג הוא זה שמוותר, לא השם", () => {
  // ⚠️ `flex-shrink: 0` כאן פירושו ששם האתר הוא היחיד שמתכווץ — ודווקא
  // לטובת תג שמוסתר ב-`opacity: 0` עד ריחוף.
  assert.doesNotMatch(rule(".type-badge"), /flex-shrink:\s*0\b/,
    "תג הסוג חזר להיות בלתי-מתכווץ, והשם ישוב להיחתך");
});

test("קוד האתר נשאר גלוי תמיד", () => {
  // הכיוון ההפוך: הקוד קצר, הוא הזיהוי היציב, והוא **כן** חייב להישאר
  // שלם. תיקון שמרפה גם אותו היה פותר בעיה אחת ויוצר אחרת.
  assert.match(rule(".card-code"), /flex-shrink:\s*0\b/,
    "קוד האתר הפך למתכווץ — הוא אמור להישאר שלם בכל רוחב");
});
