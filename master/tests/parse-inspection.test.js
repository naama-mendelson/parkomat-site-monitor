test("L: שורת 'הערה:' בתוך הרשימה היא תוכן — הליקוי שאחריה לא נעלם; '10. הערות' ממוספרת כן סוגרת", () => {
  const l = parse([{ items: [
    ...HEAD(),
    R(".9 תיאור הליקוים שהתגלו בבדיקה", 560, 400),
    R("1. להחליף כבל פלדה שחוק", 560, 386),
    R("הערה: יש לתקן את מעקה הבטיחות בקומה 2", 560, 373),
    R("3. להתקין שלט עומס מרבי", 560, 360),
    R(".10 הערות", 560, 300),
    R("1. שורה שאחרי הסוף ואינה ליקוי", 560, 286),
  ] }]);
  // ⚠️ קודם "הערה:" חתכה כאן, ו"להתקין שלט עומס מרבי" פשוט לא הופיע
  assert.equal(l.defects.length, 2);
  assert.match(l.defects[0], /מעקה הבטיחות/);
  assert.equal(l.defects[1], "להתקין שלט עומס מרבי");
  assert.equal(l.defects.some((d) => d.includes("אינה ליקוי")), false);
  assert.equal(codes(l).includes("section_unterminated"), false);
  assert.equal(codes(l).includes("soft_section_end"), false);
  assert.equal(l.confidence, "high");
});

test("L2: 'הערה' / 'הערות:' / 'הערות אחרות' לבדן בשורה הן כותרת (סוף קשה); 'הערות הבודק: …' עם תוכן — לא", () => {
  for (const heading of ["הערה", "הערות:", "הערות אחרות"]) {
    const r = parse([{ items: [
      ...HEAD(),
      R(".9 תיאור הליקוים שהתגלו בבדיקה", 560, 400),
      R("- לגרז את המסילות", 560, 386),
      R(heading, 560, 300),
      R("- שורה שאחרי הכותרת", 560, 286),
    ] }]);
    assert.deepEqual(r.defects, ["לגרז את המסילות"], heading);
    assert.equal(codes(r).includes("soft_section_end"), false, heading);
  }
  const c = parse([{ items: [
    ...HEAD(),
    R(".9 תיאור הליקוים שהתגלו בבדיקה", 560, 400),
    R("- לגרז את המסילות", 560, 386),
    R("הערות הבודק: יש להחליף את הבולם", 560, 373),
    R(".10 הערות", 560, 300),
  ] }]);
  assert.equal(c.defects.length, 1);
  assert.match(c.defects[0], /להחליף את הבולם/);
});

