// פריט כפי ש-pdfjs היה מחזיר: עברית בסדר לוגי, x = קצה שמאלי
const R = (str, xRight, y, fs = 10) => {
  const w = str.length * fs * 0.45;
  return { str, dir: HEB.test(str) ? "rtl" : "ltr", transform: [fs, 0, 0, fs, xRight - w, y], width: w, height: fs, hasEOL: false };
};
const L = (str, xLeft, y, fs = 10, w = str.length * fs * 0.5) =>
  ({ str, dir: "ltr", transform: [fs, 0, 0, fs, xLeft, y], width: w, height: fs, hasEOL: false });

