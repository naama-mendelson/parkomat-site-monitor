// tests/transient-codes.test.js — אילו כשלים ראויים לניסיון חוזר.
//
// ============================================================
// ⚠️ הבדיקה הזו נולדה מאובדן תקלה אמיתית
// ============================================================
// ב-23.08 שודרה תקלה מאתר 1284. HiveMQ אישר אותה ב-`PUBACK RC:0`, והשרת
// לא כתב אותה. הפער בין השידור לרישום היה **7.13 שניות** — בדיוק המסלול
// שבו כל ניסיון נכשל **מיד**, בלי חמשת הניסיונות של שכבת המסד.
//
// הסיבה: `40P01` (deadlock) לא היה ברשימת החולפים. באותו יום נמדדו
// deadlock-ים בין `ALTER TABLE` שרץ ב-db.init() לבין הקליטה שכתבה באותו
// רגע — ACCESS EXCLUSIVE על status_history מול INSERT חי.
//
// ⚠️ **וההבחנה היא בין "אבד" ל"התעכב".** כשל שמסווג כחולף מקבל חמישה
// ניסיונות ומצליח ברבע שנייה. כשל שאינו מסווג כך נופל ל-5 ניסיונות מהירים
// של ה-dispatcher, שמסתיימים ב-`return` — כלומר PUBACK, וההודעה נמחקת
// מ-HiveMQ **לתמיד**.
const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");

const SRC = fs.readFileSync(path.join(__dirname, "..", "db", "db.js"), "utf8");
// ⚠️ ההערות מוסרות **לפני** החילוץ. הן בעברית, והכתיב `סה״כ` מכיל גרשיים
// כפולים — פרסר נאיבי חשב שזה מחרוזת קוד ואסף חצי הערה כ"קוד שגיאה".
const CODE_ONLY = SRC
  .replace(/\/\*[\s\S]*?\*\//g, "")
  .replace(/^\s*\/\/.*$/gm, "");
const CODES = (() => {
  const m = CODE_ONLY.match(/const TRANSIENT_CODES = new Set\(\[([\s\S]*?)\]\)/);
  assert.ok(m, "TRANSIENT_CODES לא נמצא");
  return new Set([...m[1].matchAll(/"([^"]+)"/g)].map((x) => x[1]));
})();

test("⚠️ התנגשות טרנזקציות ראויה לניסיון חוזר", () => {
  // Postgres ממליץ על כך במפורש: הטרנזקציה מתגלגלת במלואה, ולכן ניסיון
  // חוזר הוא התגובה הנכונה — לא ויתור.
  assert.ok(CODES.has("40P01"), "40P01 (deadlock) אינו חולף — הודעה תאבד במקום להתעכב");
  assert.ok(CODES.has("40001"), "40001 (serialization_failure) אינו חולף");
});

test("כשלי חיבור ונעילה נשארים חולפים", () => {
  for (const c of ["ECONNRESET", "ETIMEDOUT", "08006", "57P01", "57014", "55P03"]) {
    assert.ok(CODES.has(c), `${c} הוסר מרשימת החולפים`);
  }
});

test("⚠️ שגיאה אמיתית **אינה** חולפת", () => {
  // ניסיון חוזר על שגיאה קבועה הוא לולאה מיותרת שמעכבת את התור של האתר.
  // 23505 = הפרת ייחודיות (dedup עשה את שלו), 42P01 = טבלה חסרה,
  // 23514 = הפרת CHECK. אלה לא ישתנו בניסיון הבא.
  for (const c of ["23505", "42P01", "23514", "42703"]) {
    assert.ok(!CODES.has(c), `${c} סווג כחולף — ייווצרו ניסיונות מיותרים`);
  }
});

test("⚠️ הניסיון החוזר מפוזר ואינו מיידי", () => {
  // שתי טרנזקציות שהתנגשו וינוסו מיד שוב יתנגשו שוב. ה-backoff המעריכי
  // הוא מה שמונע את זה.
  assert.match(SRC, /backoffMs = Math\.min\(250 \* 2 \*\* \(attempt - 1\)/,
    "אין backoff מעריכי — ניסיון חוזר על deadlock יתנגש שוב מיד");
});
