// אומדן היסט השעון ב-check-message-loss — אחוזון נמוך, לא חציון.
//
// ============================================================
// ⚠️ למה זה קיים: השער הפליל שלושה אתרים תמימים
// ============================================================
// ההפרש שהשער מודד הוא **היסט שעון + השהיית מסירה**, ושתיהן חיוביות.
// חציון על אתר שקט — 16 אירועים ב-48 שעות — נגרר בקלות על ידי שש
// הודעות שהמתינו בתור.
//
// ⚠️ **נמדד ב-07/09/2026:** השער דיווח שאתר 1416 סוטה ב-7,072 שניות,
// ו-1275 ו-1415 בסדרי גודל דומים. הבדיקה בפועל: כל ההודעות האיטיות
// בשלושת האתרים נקלטו **באותו חלון של ארבע דקות** (06/09, 06:44–06:48),
// וכל שאר ההודעות שלהם היו 3 שניות. זה השרת שחזר אחרי 6.6 שעות השבתה
// וריקן את התור של HiveMQ — לא שעונים.
//
// ⚠️ ועל סמך הדיווח הזה כמעט נשלח מישהו לשלושה חניונים תקינים.
//
// שעון סוחף מזיז **כל** הודעה בעקביות; תור נראה כקבוצה צפופה בחלון
// קליטה אחד ואפס בשאר הזמן. לכן האומדן הוא המינימום המעשי (אחוזון 10):
// השהיית רשת ותור היא תמיד תוספת חיובית, ולכן ההודעה שהתעכבה הכי פחות
// היא הקירוב הטוב ביותר להיסט — אותה שיטה שבה NTP מסנן מדידות.
const test = require("node:test");
const assert = require("node:assert");
const fs = require("node:fs");
const path = require("node:path");

const SRC = fs.readFileSync(
  path.join(__dirname, "..", "tools", "check-message-loss.js"), "utf8");

test("⚠️ אומדן ההיסט הוא אחוזון נמוך ולא חציון", () => {
  assert.match(SRC, /const pLow = \(arr\) =>/, "אין אומדן אחוזון נמוך");
  assert.match(SRC, /perSite\s*=[\s\S]{0,200}?m: pLow\(v\)/,
    "ההיסט לכל אתר עדיין נמדד בחציון — תור יגרור אותו");
});

test("⚠️ מסירה מאוחרת מדווחת בנפרד ובשמה", () => {
  // איחוד השניים הוא מה ששלח לחפש שעון בחניון תקין. מסירה איטית אמיתית
  // וראויה לדיווח — אבל היא תכונה של הרשת ושל השרת, לא של האתר.
  assert.match(SRC, /late: v\.filter\(\(x\) => x > 300\)\.length/,
    "אין ספירה נפרדת של הודעות מאוחרות");
  assert.match(SRC, /מסירה מאוחרת/, "אין דיווח נפרד על מסירה מאוחרת");
});

test("⚠️ ריבוי אתרים באותו חלון נאמר כשרת ולא כשעונים", () => {
  // ⚠️ הענף הזה **אינו מופעל על ידי הנתונים החיים היום**, כי events מוגבל
  // ל-800 שורות אחרונות ואין בהן הודעות מאוחרות. הבדיקה המבנית היא כל
  // הכיסוי שיש לו, וזה נאמר במפורש: ענף שאינו נבדק ואינו רץ הוא ענף
  // שיישבר בשקט בפעם הבאה שיהיה בו צורך — כלומר בנפילה הבאה.
  assert.match(SRC, /backlog\.length >= 3/,
    "אין הבחנה בין תקלה מקומית לתור כלל-מערכתי");
  assert.match(SRC, /חתימה של תור אחרי נפילת שרת/);
});

test("הבסיס נמדד ולא מונח", () => {
  // הבסיס כולל רשת, תור וכתיבה, ולכן חריגה נמדדת מולו ולא מול אפס.
  assert.match(SRC, /const base = median\(perSite\.map\(\(x\) => x\.m\)\)/);
});
