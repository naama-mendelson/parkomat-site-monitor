// tests/traffic-light-datehint.test.js — בורר התאריך בלוח הרמזור.
//
// ============================================================
// מה שדווח מהמסך
// ============================================================
// צילום מסך של השדה "איש קשר נוסף", ובו "מוטי 054-5565552", עם סמל
// ▦ ("הזנת תאריך") צמוד אליו. הבקשה: *"שים את זה רק ב-INPUT שהוא
// וודאי תאריך"*.
//
// הבורר עצמו נכון והוא נולד מסיבה טובה — עמודת "אחריות" מחזיקה 50
// תאריכים מול 70 ערכים אחרים ("#x", "השער באחריותנו"), ולכן אי אפשר
// להגדיר אותה `kind: "date"`: ‏`input[type=date]` אינו מקבל טקסט חופשי,
// ו-70 תאים היו הופכים לבלתי ניתנים לעריכה. הכשל היה **בהכללה**: הוא
// נתלה על כל עמודת טקסט, כולל כאלה שלעולם לא יחזיקו תאריך.
//
// ============================================================
// ⚠️ למה בדיקת מקור ולא בדיקת התנהגות
// ============================================================
// ההתנהגות **כן** נבדקה בדפדפן אמיתי (Playwright מול הרכיב עצמו, 13
// בדיקות, 5 מוטציות שכולן נתפסו). הבדיקה הזו נועדה למשהו אחר: לשרוד
// אחרי שסביבת העבודה ההיא נעלמת. היא סטטית, בלי רשת ובלי `.env`,
// ולכן היא רצה בכל הרצה של החבילה — וזו הסיבה היחידה שהיא קיימת.
//
// ⚠️ **ובדיקת מקור נכשלת בשקט כשהקוד משתנה בצורתו.** לכן כל עוגן כאן
// דורש שהביטוי יימצא, ו"לא נמצא" הוא **כישלון** ולא דילוג — בדיוק
// הלקח מ-`check-agent-email`: עותק שמדלגים עליו הוא העותק שיסחף בלי
// שאיש ישים לב.
const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");

const SRC = path.join(__dirname, "..", "..", "dashboard", "src",
  "components", "TrafficLight", "TrafficLight.jsx");
const code = fs.readFileSync(SRC, "utf8");

test("הכפתור בטבלה מותנה ב-dateHint", () => {
  assert.match(code, /column\.kind === "text" && dateHint && \(/,
    'התנאי בטבלה אינו `column.kind === "text" && dateHint`');
});

test("הכפתור במגירה מותנה ב-dateHint", () => {
  // שני מופעים של `tl-cal` הם כפתורי "הזנת תאריך"; השלישי הוא ה-✕
  // שחוזר מהבורר לטקסט חופשי, והוא נמצא ממילא רק בתוך מצב התאריך.
  const opens = code.match(/className="tl-cal"/g) || [];
  assert.equal(opens.length, 2, `ציפינו לשני כפתורי פתיחה, נמצאו ${opens.length}`);
  assert.match(code, /\{dateHint && \(\s*\n\s*<button/,
    "הכפתור במגירה אינו מותנה ב-dateHint");
});

test("ברירת המחדל של dateHint היא false", () => {
  // ⚠️ מי ששוכח להעביר את ה-prop צריך לקבל שדה טקסט. ברירת מחדל `true`
  // הייתה מחזירה את הבאג בכל מקום קריאה חדש, ובשקט.
  assert.match(code, /dateHint = false/,
    "dateHint חייב להיות false כברירת מחדל");
});

test("הכלל חל רק על עמודות טקסט", () => {
  assert.match(code, /if \(c\.kind !== "text"\) continue;/,
    "dateBearingKeys אינו מסנן לעמודות טקסט בלבד");
});

test("נדרש יותר מתאריך בודד", () => {
  const m = /const MIN_DATE_CELLS = (\d+);/.exec(code);
  assert.ok(m, "MIN_DATE_CELLS לא נמצא");
  assert.ok(Number(m[1]) >= 2,
    `סף של ${m[1]} — ערך בודד בצורת תאריך יזמן את הכפתור לעמודה שלמה`);
});

test("זיהוי התאריך עוגן לשני קצות התא", () => {
  const m = /const DATE_CELL = (\/.*\/);/.exec(code);
  assert.ok(m, "DATE_CELL לא נמצא");
  // בלי עוגן, "נמסר לדיירים בתאריך ה- 19.8.25" בעמודת "הערות" נספר
  // כתא תאריך — ושלוש הערות כאלה מספיקות כדי להצמיח את הכפתור שם.
  assert.ok(m[1].startsWith("/^") && m[1].endsWith("$/"),
    `הביטוי אינו עוגן: ${m[1]}`);
});

test("הכלל נגזר מכל השורות ולא מהמסוננות", () => {
  // ⚠️ חיפוש שמצמצם לשורה אחת היה מעלים את הבורר מ"אחריות", והכפתור
  // היה מופיע ונעלם לפי מה שהוקלד בתיבת החיפוש.
  //
  // ⚠️ **והעוגן הראשון כאן היה שגוי בדיוק כמו ב-`check-agent-email`:**
  // ‏`doesNotMatch(/dateBearingKeys\(columns, rows\)/)` נכשל על **הגדרת**
  // הפונקציה — `function dateBearingKeys(columns, rows)` — ולא על קריאה.
  // שער אדום על קוד תקין, מאותה סיבה בדיוק: הביטוי תפס אזכור ולא שימוש.
  // לכן נספרות כאן **הקריאות בלבד**.
  const calls = [...code.matchAll(/(?<!function )dateBearingKeys\(([^)]*)\)/g)]
    .map((m) => m[1].trim());
  assert.equal(calls.length, 1, `ציפינו לקריאה אחת, נמצאו ${calls.length}: ${calls.join(" | ")}`);
  assert.equal(calls[0], "columns, allRows",
    `הכלל נגזר מ-"${calls[0]}" ולא מכל השורות`);
});

test("שני מקומות הקריאה מעבירים את ה-prop", () => {
  const passes = code.match(/dateHint=\{/g) || [];
  assert.equal(passes.length, 2,
    `ציפינו ששני מופעי <Cell> יעבירו dateHint, נמצאו ${passes.length}`);
  assert.match(code, /dateCols=\{dateCols\}/,
    "המגירה אינה מקבלת את dateCols");
});
