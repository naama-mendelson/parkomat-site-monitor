// tests/insights-tabs.test.js — אילו שוניות מוצגות במבט המצרף.
//
// ============================================================
// ⚠️ "משתמשים" אינו במבט של מנהל כללי — החלטת מוצר
// ============================================================
// המבט המצרף מסכם **מערכת**, ולא אנשים. פילוח של מחזיקי כרטיסים בודדים
// הוא פרט תפעולי בגובה הלא נכון שם.
//
// ⚠️ ובאתר בודד הוא **נשאר**: "מי הכי פעיל" ו"מי נתקל בתקלות" הן שאלות
// תפעוליות אמיתיות, וכל השורות מאותו אתר. הסרה גורפת הייתה מוחקת מידע
// שימושי כדי לתקן מקום אחד.
//
// ⚠️ ולכן זה נבדק כ**הבחנה** ולא כהיעדר: בדיקה שרק מוודאת שהמילה נעלמה
// הייתה עוברת גם אם הסרתי אותה משני המבטים.
const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");

const MODAL = fs.readFileSync(
  path.join(__dirname, "..", "..", "dashboard", "src", "components",
            "InsightsModal", "InsightsModal.jsx"), "utf8");

const code = MODAL.replace(/\/\*[\s\S]*?\*\//g, "").replace(/^\s*\/\/.*$/gm, "");

test("⚠️ שונית המשתמשים מותנית ב-allSites", () => {
  // הצורה: ...(allSites ? [] : [{ key: "cards", ... }])
  assert.match(code, /allSites \? \[\] : \[\{ key: "cards"/,
    "השונית חייבת להיעלם במצרפת ולהישאר באתר בודד");
});

test("⚠️ וגם כרטיס המדד ב'סקירה' מותנה", () => {
  // ⚠️ ה-hint שלו אומר "פעלו **באתר**" — טקסט שגוי בתצוגה שאינה של אתר,
  // ולא רק מיותר.
  const kpi = code.slice(code.indexOf('section === "overview"'));
  assert.match(kpi.slice(0, 1200), /\{!allSites && \([\s\S]{0,200}label="משתמשים"/,
    "הכרטיס בסקירה חייב להיות מותנה גם הוא");
});

test("⚠️ שונית שאינה קיימת נופלת ל'סקירה'", () => {
  // הפרופ initialSection מאפשר לפתוח ישר על "משתמשים". אף קורא אינו עושה
  // זאת היום, אבל במצרפת השונית אינה קיימת — ואז הפאנל היה מוצג בלי שום
  // שונית מסומנת שתוציא ממנו.
  assert.match(code, /sections\.some\(\(s\) => s\.key === requested\)/,
    "חייבת נפילה לשונית קיימת");
});

test("⚠️ ובאתר בודד השונית עדיין שם", () => {
  // ההבחנה עצמה. בלי זה, הסרה גורפת הייתה עוברת את כל הבדיקות למעלה.
  assert.match(code, /key: "cards", label: "משתמשים"/,
    "השונית חייבת להמשיך להתקיים — רק מותנית");
  assert.match(code, /h3>סיכום המשתמשים/,
    "והתוכן שלה לא נמחק");
});
