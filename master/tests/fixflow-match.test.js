// tests/fixflow-match.test.js — מנוסח הבקר אל הנוהל, וכשאין — לומר שאין.
//
// ============================================================
// ⚠️ למה דווקא כאן טעות יקרה
// ============================================================
// הפאנל על הכרטיס מציג נוהל **ואזהרת בטיחות**. התאמה שגויה אינה מציגה שגיאה:
// היא מציגה נוהל של מתקן אחר, שכל הצעדים בו סבירים — ואזהרה שאינה שייכת.
// מוקדן באמצע אירוע אין לו שום דרך להבחין.
//
// לכן הבדיקות כאן מתעקשות על שלושה סירובים, לא רק על הצלחות: ציון נמוך,
// עמימות בין שתי כותרות שונות, וקלט ריק.
import { test } from "node:test";
import assert from "node:assert/strict";
import { matchFault, similarity, tokens, buildWeights, MIN_SCORE } from "../../shared/fixflow-match.mjs";

// נלקחו מההיסטוריה האמיתית — נוסח הבקר משמאל, כותרת המסמך בכונן מימין.
const FAULTS = [
  { id: "f1", title: "מנהל חניון -דלתות חניון פתוחות", warning: "חובה לוודא במצלמות שאין אנשים" },
  { id: "f2", title: "שאטל 1,2- מגש לא ממוקם" },
  { id: "f3", title: "מסובבת- שאטל לא באיזור סיבוב ." },
  { id: "f4", title: "דקלוק - אוברלואד" },
  { id: "f5", title: "אנקודר יצא מטווח" },
];

test("נוסח הבקר מוצא את הנוהל, למרות הבדלי פיסוק", () => {
  const r = matchFault("מנהל חניון - דלתות חניון פתוחות:", FAULTS);
  assert.equal(r.fault.id, "f1");
  assert.ok(r.score > 0.9, `ציון ${r.score}`);
});

// ⚠️ הבקר כותב `שאטל 1`, המסמך נקרא `שאטל 1,2` — אותה תקלה. וב-`מיטה (מספר)`
// המסמך מחזיק placeholder במקום המספר.
//
// ⚠️ **והבדיקה טוענת על הטוקנים ולא רק על התוצאה**, כי מוטציה שמחקה את
// טיפול הספרות עברה בירוק: המפריד מטפל בהן ממילא, והשורה ההיא הייתה קוד מת.
// טענה על התוצאה בלבד אינה מבחינה בין "עובד" ל"עובד ממקום אחר".
test("ספרות אינן הופכות למונח, ולכן אינן מפרידות בין אותה תקלה לעצמה", () => {
  assert.deepEqual([...tokens("מיטה 13")], ["מיטה"]);
  assert.deepEqual([...tokens("שאטל 1,2")], ["שאטל"]);
  assert.equal(matchFault("שאטל 1 - מגש לא ממוקם:", FAULTS).fault.id, "f2");
});

test("האזהרה מוחזרת יחד עם הנוהל", () => {
  const r = matchFault("מנהל חניון - דלתות חניון פתוחות:", FAULTS);
  assert.match(r.fault.warning, /במצלמות/);
});

// ⚠️ **הסירוב החשוב ביותר.** תקלה שאין עליה מסמך חייבת להחזיר null, ולא את
// הכותרת הקרובה ביותר. "הכי קרוב" הוא בדיוק איך שנוהל של מתקן אחר מגיע למסך.
test("תקלה שאין עליה מסמך מחזירה null, ולא את הקרוב ביותר", () => {
  assert.equal(matchFault("טמפרטורת שמן גבוהה בהידראוליקה:", FAULTS), null);
  assert.equal(matchFault("banana split", FAULTS), null);
});

// ============================================================
// ⚠️ הבדיקה שהייתה חסרה, ומוטציה הוכיחה זאת
// ============================================================
// שתי הטענות שמעל עוברות גם **בלי הסף כלל**, כי הציון שלהן הוא 0 — אין ולו
// מונח משותף. כלומר הן מדדו את "אין חפיפה", לא את הסף. מוטציה שמחקה את
// `bestScore < MIN_SCORE` עברה בירוק.
//
// המקרה האמיתי נמדד: `דלתות מעלית פתוחות` מקבל **0.540** מול
// `מנהל חניון -דלתות חניון פתוחות` — מתחת לסף בקושי, ושגוי לגמרי. דלתות
// מעלית אינן דלתות חניון, והנוהל לחלוטין אחר.
test("⚠️ ציון גבוה שאינו מספיק — נדחה. זו הבדיקה שנוגעת בסף עצמו", () => {
  const near = matchFault("דלתות מעלית פתוחות:", FAULTS);
  assert.equal(near, null, "0.54 הוא מתחת לסף ולכן אינו התאמה");

  // ולראיה שהציון באמת קרוב ולא אפס — אחרת הבדיקה חוזרת למדוד "אין חפיפה".
  const m = buildWeights(FAULTS);
  const s = similarity(tokens("דלתות מעלית פתוחות:"), tokens(FAULTS[0].title), m.weight);
  assert.ok(s > 0.45 && s < MIN_SCORE, `הציון ${s} חייב להיות קרוב לסף ומתחתיו`);
});

test("קלט ריק או רשימה ריקה — null, בלי לזרוק", () => {
  assert.equal(matchFault("", FAULTS), null);
  assert.equal(matchFault(null, FAULTS), null);
  assert.equal(matchFault("מגש לא ממוקם", []), null);
  assert.equal(matchFault("מגש לא ממוקם", null), null);
});

// ⚠️ שתי כותרות **שונות** באותו ציון הן עמימות. נמדד בשטח: `מסובבת שאטל 1 -
// זמן מקסימלי לתנועה` קיבל 0.58 מול 0.54 — הפרש שאין להסתמך עליו כששתי
// הכותרות מתארות מתקנים שונים.
test("שתי כותרות שונות בציון זהה — מסרב", () => {
  const twins = [
    { id: "a", title: "מעלית - שער לא סגור" },
    { id: "b", title: "מעלית - שער לא סגור נעילה" },
    { id: "c", title: "מעלית שער לא סגור" },
  ];
  const r = matchFault("מעלית - שער לא סגור:", twins);
  assert.equal(r, null);
});

// ⚠️ אבל כותרת **זהה** שחוזרת פעמיים אינה עמימות — זו אותה תקלה שמתויקת
// פעמיים, ובחירת הראשונה נכונה. בלי ההבחנה הזו כל מסמך כפול היה נעלם מהמסך.
test("כותרת זהה שחוזרת פעמיים אינה עמימות", () => {
  const dup = [
    { id: "a", title: "דלתות חניון פתוחות", warning: "אזהרה" },
    { id: "b", title: "דלתות חניון פתוחות" },
  ];
  const r = matchFault("דלתות חניון פתוחות:", dup);
  assert.ok(r, "היה אמור להתאים");
  assert.equal(r.fault.id, "a");
});

// ⚠️ המשקל הוא מה שמונע מ`שאטל`/`מסובבת`/`מגש` — שמופיעים כמעט בכל כותרת —
// לגרור התאמה בין שתי תקלות שונות לגמרי באותה משפחה.
test("מונח נפוץ שוקל פחות ממונח נדיר", () => {
  const m = buildWeights(FAULTS);
  assert.ok(m.weight("אוברלואד") > m.weight("שאטל"),
    `נדיר ${m.weight("אוברלואד")} מול נפוץ ${m.weight("שאטל")}`);
});

// ⚠️ F1 ולא כיסוי בכיוון אחד: כותרת קצרה שנבלעת בתקלה ארוכה אינה התאמה מלאה.
// ⚠️ **הכיוון המסוכן, וגם הוא התגלה במוטציה.** הגרסה הראשונה של הבדיקה
// בחנה את הכיוון ההפוך ועברה גם כשהחזרתי כיסוי חד-כיווני. המקרה שמפיל:
// שאילתה קצרה שכל מונחיה מופיעים בכותרת ארוכה — `pa` נותן **1.000**, ו-F1
// נותן 0.156. בלי זה, כל תקלה בת מילה אחת הייתה מתאימה לכותרת הארוכה ביותר
// בספרייה.
test("⚠️ שאילתה קצרה שנבלעת בכותרת ארוכה אינה התאמה", () => {
  const m = buildWeights(FAULTS);
  const q = tokens("אוברלואד");
  const long = tokens("דקלוק - אוברלואד במעלית בזמן תנועה של המגש בקומה העליונה");
  const s = similarity(q, long, m.weight);
  assert.ok(s < 0.4, `F1 נתן ${s}; כיסוי חד-כיווני היה נותן 1.0`);
});

test("הסף הוא זה שנמדד בשטח", () => {
  assert.equal(MIN_SCORE, 0.55);
});

// ============================================================
// ⚠️ שקולים — הכרעה לפי מקור המסמך (24/09/2026)
// ============================================================
// 6 זוגות בספריות הם אותה כותרת בפיסוק אחר, ובכל אחד התוכן שונה: כללי מול
// "הדגש לאתר", או שני אתרים. בלי `rank` — מסרבים (ההתנהגות הקודמת נשמרת).
const TIE = [
  { id: "G", title: "מעלית שער לא סגור", emphasis: null },
  { id: "K", title: "מעלית- שער לא סגור", emphasis: "קינג גורג" },
  { id: "X", title: "גלישת מגש", emphasis: null },
];
const rankFor = (mySite) => (f) => (f.emphasis && f.emphasis === mySite ? 0 : f.emphasis ? 2 : 1);

test("שקולים בלי rank — מסרב, כמו קודם", () => {
  assert.equal(matchFault("מעלית - שער לא סגור:", TIE), null);
});

test("⚠️ כללי מול הדגש של אתר אחר — הכללי", () => {
  const r = matchFault("מעלית - שער לא סגור:", TIE, null, { rank: rankFor("גולדברג 5") });
  assert.equal(r?.fault.id, "G");
});

test("⚠️ באתר שהמסמך נכתב בשבילו — ההדגש שלו גובר על הכללי", () => {
  const r = matchFault("מעלית - שער לא סגור:", TIE, null, { rank: rankFor("קינג גורג") });
  assert.equal(r?.fault.id, "K");
});

test("⚠️ שני הדגשים של אתרים זרים — עדיין מסרב", () => {
  const two = [
    { id: "A", title: "מעלית מגש לא ממוקם", emphasis: "אנטיגונוס" },
    { id: "N", title: "מעלית -מגש לא ממוקם", emphasis: "נמל מגשים" },
  ];
  assert.equal(matchFault("מעלית - מגש לא ממוקם", two, null, { rank: rankFor("ויצמן 93") }), null);
  assert.equal(matchFault("מעלית - מגש לא ממוקם", two, null, { rank: rankFor("נמל מגשים") })?.fault.id, "N");
});

test("rank אינו מכשיר מועמד שמתחת לסף", () => {
  const r = matchFault("משהו אחר לגמרי", TIE, null, { rank: rankFor("קינג גורג") });
  assert.equal(r, null);
});

test("⚠️ שתי תקלות שונות בציון קרוב — rank אינו מכריע ביניהן (המקרה האמיתי)", async () => {
  // נמדד על ספריית מצבט Y (גולדברג 5, 24/09/2026): 0.61 מול 0.58, כותרות שונות
  // במילים. בלי ההגבלה rank בחר את הכללי — תקלה אחרת — רק משום שהוא כללי.
  const { readFileSync } = await import("node:fs");
  const MAP = JSON.parse(readFileSync(new URL("../../dashboard/src/components/FixFlowLink/fixflow-sites.json", import.meta.url), "utf8"));
  const lib = MAP.faults["לולק|שאטל מצבט y שמסובבת בשאטל"].map((f) => ({ id: f.i, title: f.t, emphasis: f.e ?? null }));
  const q = "מסובבת שאטל 1 - זמן מקסימלי לתנועה:";
  assert.equal(matchFault(q, lib), null, "בלי rank — מסרב");
  assert.equal(matchFault(q, lib, null, { rank: rankFor("גולדברג 5") }), null, "וגם עם rank");
});
