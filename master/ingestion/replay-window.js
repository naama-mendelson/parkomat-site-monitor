// למה זה קיים: להגן על backfill אמיתי מפני תיקון-סחיפה
// ============================================================
// יישור חותם זמן שנמצא ב*עבר* הוא הימור: הודעה עם חותם ישן יכולה להיות
//
//   (א) שעון שמפגר — האירוע קרה עכשיו, השעון אמר "לפני 235 שניות", או
//   (ב) backfill אמיתי — האירוע קרה מזמן, וההודעה הגיעה באיחור מהתור.
//
// משתי ההודעות עצמן אין שום דרך להבחין: אותו שדה, אותו הפרש מ"עכשיו". אבל
// **הקשר הזמן** כן מבדיל: backfill מגיע בגלים, מיד אחרי שהמנוי ל-HiveMQ חוזר
// ומתחיל לפרוק את מה שהצטבר. בשגרה, לעומת זאת, הודעות מגיעות תוך שניות —
// ולכן חותם ישן בשגרה הוא כמעט תמיד סחיפת שעון.
//
// לכן: בחלון שאחרי חיבור/חיבור-מחדש של המנוי אנחנו **לא** מיישרים חותמים
// מהעבר. עדיף להשאיר סחיפה של דקה בכמה הודעות מאשר לשכתב את זמן ההתרחשות
// האמיתי של גל השלמה שלם — הנתון היחיד שאי אפשר לשחזר.
//
// זה לא פתרון מושלם (ראה ההערה על גל ארוך למטה), אבל הוא מכסה בדיוק את המקרה
// שנצפה בפועל: נפילת שרת, ואחריה פריקת תור.

/**
 * כמה זמן אחרי חיבור המנוי נחשב "חלון פריקה". גל השלמה טיפוסי נפרק בשניות
 * (נמדד: 22 הודעות ב-300ms), ולכן שתי דקות הן מרווח נדיב.
 *
 * ⚠️ גל גדול במיוחד יכול להימשך מעבר לחלון. אז הודעות מסוף הגל ייחשבו
 * "שגרה" ועלולות להיות מיושרות. הגבול הזה הוא פשרה מכוונת, לא הוכחה.
 */
const REPLAY_GRACE_SECONDS = 120;

// מתי המנוי התחבר לאחרונה. null = טרם התחבר בריצה הזו.
let lastBrokerConnectMs = null;

/** נקרא מ-mqtt/subscriber.js בכל אירוע connect (כולל חיבור-מחדש). */
function markBrokerConnected(nowMs = Date.now()) {
  lastBrokerConnectMs = nowMs;
}

/**
 * האם סביר שאנחנו כרגע מקבלים הודעות מתור ולא בזמן אמת.
 * true גם כשטרם היה חיבור — כלומר ברירת המחדל היא הזהירה (לא מיישרים).
 */
function isLikelyReplay(nowMs = Date.now()) {
  if (lastBrokerConnectMs === null) return true;
  return (nowMs - lastBrokerConnectMs) / 1000 < REPLAY_GRACE_SECONDS;
}

/** לבדיקות בלבד. */
function _reset() {
  lastBrokerConnectMs = null;
}

module.exports = { markBrokerConnected, isLikelyReplay, _reset, REPLAY_GRACE_SECONDS };
