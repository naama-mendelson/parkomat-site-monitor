// ingestion/lwt-order.js — האם הודעת נתק (no_comm) עדיין רלוונטית, או שהיא מאוחרת.
//
// ============================================================
// הבעיה: לצוואה אין זמן משלה
// ============================================================
// הודעת no_comm אינה מגיעה מהאתר — הברוקר מפרסם אותה **בשמו** כשהוא מבחין
// שהחיבור מת (LWT של הסוכן מול Mosquitto, או will של הגשר מול HiveMQ). אין
// בה חותם זמן אמיתי, ולכן השרת חותם אותה ב"עכשיו".
//
// וכאן נולד באג הסדר: "עכשיו" הוא תמיד הזמן הכי חדש שקיים. לכן צוואה שהתעכבה
// — ישבה בתור של HiveMQ בזמן שהשרת היה למטה, ונמסרה רק עכשיו — **תמיד** תיראה
// חדשה יותר מכל מצב אמיתי שהאתר דיווח בינתיים. היא עוברת את שומר ה-backfill
// (כי היא לא ישנה, היא "עכשיו"), דורסת את המצב העדכני, ומסמנת כ"אין תקשורת"
// אתר שדיווח לפני שנייה שהוא מוכן.
//
// גרוע מכך: המקטע שנפתח בחותם "עכשיו" גורם לכל הודעה אמיתית שתגיע אחריו
// מהתור (עם חותם ישן יותר) להיראות כ-backfill — ולהידחות. האתר נתקע.
//
// ============================================================
// הכלל: צוואה תקפה רק אחרי שתיקה
// ============================================================
// נתק אמיתי אינו יכול להתגלות מיד. הברוקר מכריז על לקוח כמת רק אחרי
// 1.5 × keepalive, וה-keepalive מוגדר במפורש ל-60 שניות (BridgeConfigWriter),
// כלומר **90 שניות** — זה בדיוק ה"חוק" המתועד בשני קובצי ה-CLAUDE.md.
//
// מכאן נובע מבחן פשוט וחד: אם שמענו מהאתר לפני פחות מ-90 שניות, הצוואה שאנחנו
// מעבדים כרגע *לא יכולה* להיות תיאור של המצב הנוכחי — היא שריד מתור. דוחים.
//
// זה אותו עיקרון בדיוק של "הודעה ישנה לא דורסת מצב עדכני", רק מיושם על הודעה
// שאין לה זמן משלה: במקום להשוות חותמים, משווים מול הפעם האחרונה שהאתר נשמע.
//
// שים לב שזה **לא** watchdog: הוא לא מכריז על נתק, הוא רק מסרב להאמין לצוואה
// שסותרת ידיעה טרייה יותר. אין כאן טיימר ואין סריקה תקופתית.

/**
 * חלון השתיקה המינימלי שהופך צוואה לאמינה. 1.5 × keepalive של 60 שניות —
 * אותו מספר שהברוקרים עצמם משתמשים בו כדי להכריז על לקוח כמת.
 */
const LWT_MIN_SILENCE_SECONDS = 90;

/**
 * האם להחיל הודעת no_comm.
 *
 * @param lastSeenIso  last_seen של האתר (ISO) או null אם מעולם לא נשמע.
 * @param nowMs        "עכשיו" לפי השרת.
 * @returns {{apply:boolean, reason:string|null, silenceSeconds:number|null}}
 */
function shouldApplyNoComm(lastSeenIso, nowMs) {
  // אתר שמעולם לא נשמע — אין ידיעה טרייה שסותרת. מחילים.
  if (!lastSeenIso) {
    return { apply: true, reason: null, silenceSeconds: null };
  }

  const lastSeenMs = Date.parse(lastSeenIso);
  if (!Number.isFinite(lastSeenMs)) {
    return { apply: true, reason: null, silenceSeconds: null };
  }

  const silenceSeconds = Math.round((nowMs - lastSeenMs) / 1000);

  // last_seen בעתיד (שעון סוטה שנכתב לפני שהיישור נכנס) — לא נותנים לזה
  // לחסום נתק אמיתי לנצח. מתייחסים אליו כאל "נשמע ממש עכשיו" ולכן חוסם,
  // אבל רק עד שהזמן ישיג אותו.
  if (silenceSeconds < LWT_MIN_SILENCE_SECONDS) {
    return {
      apply: false,
      reason: `האתר נשמע לפני ${silenceSeconds}s (< ${LWT_MIN_SILENCE_SECONDS}s) — ` +
              `הצוואה מאוחרת ואינה מתארת את המצב הנוכחי`,
      silenceSeconds,
    };
  }

  return { apply: true, reason: null, silenceSeconds };
}

module.exports = { shouldApplyNoComm, LWT_MIN_SILENCE_SECONDS };
