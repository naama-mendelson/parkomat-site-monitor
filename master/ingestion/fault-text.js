// ingestion/fault-text.js — חילוץ תיאור התקלה מהודעת הסוכן.
//
// ============================================================
// למה מודול נפרד ולא שורות בתוך state-handler
// ============================================================
// זהו התפר שבו הסוכן פוגש את השרת — הנקודה היחידה שבה טקסט שנכתב בבקר
// בשטח, שאיש מאיתנו לא ראה, נכנס למסד. שאר השרשרת (FaultTextDecoder,
// timeline, sitePatch) מעבדת נתון שכבר נוקה **כאן**.
//
// ⚠️ בתוך state-handler הוא לא היה ניתן לבדיקה: הקובץ מושך את queries.js
// ודרכו את db.js, שדורש DATABASE_URL. בדיקות השרת רצות בלי מסד בכוונה,
// ולכן לוגיקה טהורה שנקברת בתוך handler היא לוגיקה שלא תיבדק לעולם.
// אותו שיקול בדיוק הוציא את WatchdogPolicy מ-ServiceManager בסוכן.
//
// ⚠️ **המודול הזה לא ידרוש כלום.** ברגע שהוא ידרוש, הכיסוי שלו ימות בשקט.

/**
 * @param {string} newStatus  המצב שההודעה מדווחת עליו
 * @param {object} data       גוף הודעת ה-MQTT
 * @returns {string|null}     התיאור, או null כשאין
 */
function extractFaultText(newStatus, data) {
  // ⚠️ **מתקבל רק על תקלה.** סוכן שישלח טקסט על מצב אחר אינו אמור,
  // ושמירתו הייתה יוצרת שורות 'מוכן' עם תיאור תקלה — מידע שסותר את עצמו.
  if (newStatus !== "error") return null;

  // כל סוג שאינו מחרוזת נדחה בשקט. הנושא הזה פתוח לכל מי שיש לו את פרטי
  // ה-MQTT של האתר, וקליטת **המצב** חשובה מכדי ליפול על תיאור פגום.
  if (typeof data?.faultText !== "string") return null;

  // גבול קשיח: עמודת TEXT אינה מוגבלת, אבל הודעה חריגה מהבקר אינה אמורה
  // להיכנס כמות שהיא. 200 הם פי 2.5 מהתקרה שהסוכן קורא בכלל (80).
  //
  // ⚠️ החיתוך קודם ל-trim בכוונה: כך התקרה חלה על מה שהגיע בפועל, ורווחים
  // בקצה אינם "קונים" תווים נוספים מעבר לה.
  // ============================================================
  // ⚠️ תווים שאינם יכולים להגיע מבקר ישראלי — נחתכים
  // ============================================================
  // נמדד בייצור: אתר 1376 הציג תקלה שכל תיאורה היה `珼` (U+73FC).
  // המקור הוא ב-FaultTextDecoder בסוכן: רגיסטר מעל 0xFF מוחזר כנקודת
  // קוד יוניקוד ישירה — כלל **נכון** לבקרים ששולחים עברית כ-1488..1514,
  // אבל רגיסטר זבל בערך 0x73FC הופך כך לתו סיני.
  //
  // ⚠️ ואותו אתר מפיק עברית תקינה ברוב הזמן, ולכן זו אינה אי-התאמת
  // קידוד אלא קריאה מזדמנת מחוצץ שלא נוקה.
  //
  // ⚠️ **ומדוע לחתוך ולא להציג:** מפעיל שרואה `珼` בשדה תקלה אינו
  // לומד כלום, ולא יכול לדעת אם זו תקלה אמיתית עם שם מוזר או קריאה
  // פגומה. שדה ריק אומר את האמת — התיאור לא נקרא — והמצב עצמו
  // (תקלה) נשמר בכל מקרה.
  const raw = data.faultText.slice(0, 200);

  // עברית, ASCII נדפס, ורווחים. זה כל מה שבקר ישראלי שולח.
  const clean = raw.replace(/[^֐-׿ -~s]/g, "").trim();

  // ⚠️ ריק אחרי הניקוי = לא נשאר כלום קריא. null ולא "" — המסד מבדיל
  // בין 'לא נקרא' (NULL) ל'נקרא והיה ריק' ('').
  // ⚠️ **ריק שהגיע ריק אינו ריק שנוצר מניקוי.** בדיקה קיימת תופסת
  // את זה, ובצדק: NULL אומר "הבקר לא נקרא", ו-'' אומר "נקרא והחזיר
  // כלום". הגרסה הראשונה שלי כאן החזירה null לשניהם ומחקה את ההבחנה.
  if (clean === "" && raw.trim() !== "") return null;   // היה תוכן, וכולו זבל
  return clean;
}

module.exports = { extractFaultText };
