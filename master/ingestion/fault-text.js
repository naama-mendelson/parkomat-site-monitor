// ingestion/fault-text.js — חילוץ תיאור התקלה מהודעת הסוכן.
//
// ============================================================
// למה מודול נפרד ולא שורות בתוך state-handler
// ============================================================
// זהו התפר שבו הסוכן פוגש את השרת — הנקודה היחידה שבה טקסט שנכתב בבקר
// בשטח, שאיש מאיתנו לא ראה, נכנס למסד. שאר השרשרת (FaultTextDecoder,
// timeline, sitePatch) מעבדת נתון שכבר נוקה **כאן**.
//
// ⚠️ בתוך state-handler הוא לא היה ניתן לבדיקה: הקובץ מושך את queries.js
// ודרכו את db.js, שדורש DATABASE_URL. בדיקות השרת רצות בלי מסד בכוונה,
// ולכן לוגיקה טהורה שנקברת בתוך handler היא לוגיקה שלא תיבדק לעולם.
//
// ⚠️ **המודול הזה לא ידרוש כלום.** ברגע שהוא ידרוש, הכיסוי שלו ימות בשקט.

// ============================================================
// ⚠️ התווים המותרים — ולמה הם נכתבים כך ולא ברגקס ישיר
// ============================================================
// עברית (0590–05FF), ASCII נדפס (0020–007E), ורווחים לבנים. זה כל מה
// שבקר ישראלי שולח.
//
// ⚠️ **הגרסה הקודמת נשברה בדיוק כאן.** היא נכתבה דרך כלי עריכה שבלע את
// הלוכסן, ו-\s הפך ל-s ספרותי. התוצאה: ירידות שורה וטאבים נמחקו,
// ו-"שורה א\nשורה ב" הפך ל-"שורה אשורה ב" — מילים דבוקות בלי מפריד.
// נמדד, לא שוער.
//
// הבנייה מקודי תווים מפורשים אינה ניתנת לשיבוש כזה: אין כאן לוכסן
// שמישהו יכול לאבד.
const HEBREW_FROM = 0x0590;
const HEBREW_TO   = 0x05ff;
const ASCII_FROM  = 0x0020;   // רווח
const ASCII_TO    = 0x007e;   // ~

function isAllowed(ch) {
  const c = ch.codePointAt(0);
  if (c >= HEBREW_FROM && c <= HEBREW_TO) return true;
  if (c >= ASCII_FROM && c <= ASCII_TO) return true;
  // ⚠️ ירידת שורה, טאב, CR — הם **מפרידים**, ומחיקתם מדביקה מילים.
  return ch === "\n" || ch === "\r" || ch === "\t";
}

/**
 * @param {string} newStatus  המצב שההודעה מדווחת עליו
 * @param {object} data       גוף הודעת ה-MQTT
 * @returns {string|null}     התיאור, או null כשאין
 */
function extractFaultText(newStatus, data) {
  // ⚠️ **מתקבל רק על תקלה.** סוכן שישלח טקסט על מצב אחר אינו אמור,
  // ושמירתו הייתה יוצרת שורות 'מוכן' עם תיאור תקלה — מידע שסותר את עצמו.
  if (newStatus !== "error") return null;

  // כל סוג שאינו מחרוזת נדחה בשקט. הנושא הזה פתוח לכל מי שיש לו את פרטי
  // ה-MQTT של האתר, וקליטת **המצב** חשובה מכדי ליפול על תיאור פגום.
  if (typeof data?.faultText !== "string") return null;

  // גבול קשיח: הודעה חריגה מהבקר אינה אמורה להיכנס כמות שהיא. 200 הם
  // פי 2.5 מהתקרה שהסוכן קורא בכלל (80).
  //
  // ⚠️ החיתוך קודם ל-trim בכוונה: כך התקרה חלה על מה שהגיע בפועל, ורווחים
  // בקצה אינם "קונים" תווים נוספים מעבר לה.
  const raw = data.faultText.slice(0, 200);

  // ============================================================
  // ⚠️ תווים שאינם יכולים להגיע מבקר ישראלי — נחתכים
  // ============================================================
  // נמדד בייצור: אתר 1376 הציג תקלה שכל תיאורה היה `珼` (U+73FC), במקום
  // "מעלית לא בקומה בכניסה לאוטומט:". המקור הוא תחרות תזמון בסוכן —
  // תיאור התקלה נקרא מכתובת 2 וה-MODE מ-290, בשתי קריאות נפרדות, והבקר
  // טרם כתב את הטקסט.
  //
  // ⚠️ **ומדוע לחתוך ולא להציג:** מפעיל שרואה `珼` אינו לומד כלום, ואינו
  // יכול לדעת אם זו תקלה אמיתית עם שם מוזר או קריאה פגומה. שדה ריק אומר
  // את האמת — התיאור לא נקרא — והמצב עצמו (תקלה) נשמר בכל מקרה.
  const clean = [...raw].filter(isAllowed).join("").trim();

  // ============================================================
  // ⚠️ טקסט שכולו סימני שאלה הוא זבל, גם אם ASCII מתיר אותו
  // ============================================================
  // הסוכן המתוקן ממיר רגיסטר לא-מזוהה ל-'?'. '?' הוא ASCII נדפס ולכן
  // עובר את הסינון למעלה — ואז המפעיל רואה "???" ואנחנו לא רושמים כלום.
  // זו בדיוק התוצאה שהמודול הזה קיים כדי למנוע.
  //
  // ⚠️ ורק כשזה **כל** הטקסט: "מעלית תקועה?" הוא תיאור לגיטימי.
  const meaningful = clean.replace(/[?\s]/g, "");
  if (clean !== "" && meaningful === "") return null;

  // ⚠️ **ריק שהגיע ריק אינו ריק שנוצר מניקוי.** NULL אומר "הבקר לא נקרא",
  // ו-'' אומר "נקרא והחזיר כלום". בדיקה קיימת תופסת את ההבחנה הזו.
  if (clean === "" && raw.trim() !== "") return null;   // היה תוכן, וכולו זבל
  return clean;
}

module.exports = { extractFaultText };
