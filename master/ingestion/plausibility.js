// ingestion/plausibility.js — האם חותם הזמן שהאתר שלח בכלל אפשרי, ומה עושים איתו.
//
// ============================================================
// שתי דרגות, לא מדיניות אחת
// ============================================================
// סחיפת שעון קטנה וסחיפה אבסורדית הן שתי תקלות שונות, ומגיע להן טיפול שונה:
//
//   • סחיפה קטנה (עד FUTURE_CLAMP_MAX) — **מיישרים ומקבלים**. אתר עם שעון
//     שמקדים ב-34 שניות הוא אתר עובד לגמרי; דחייה שלו הייתה מוחקת את כל
//     הדיווח שלו בגלל תקלה שאינה שלו. (נמדד בשטח: אתר 1343 ב-34s+, 2439
//     ב-70s+, 3513 ב-20s-.)
//
//   • סחיפה אבסורדית (רחוק בעתיד / לפני רישום האתר / אפוק-אפס) — **דוחים
//     ורושמים**. חותם כזה אינו סחיפה אלא שעון שבור או הודעה זרה, ואין ערך
//     בניחוש מתי הוא "באמת" קרה.
//
// ============================================================
// למה חותם עתידי הוא נעילה עצמית, ולא אי-דיוק
// ============================================================
//   1. `last_seen` נדחף לעתיד. הוא מתקדם *קדימה בלבד*, ולכן כל דיווח אמיתי
//      מכאן והלאה כבר לא "חדש יותר" — האתר נראה כאילו השתתק.
//   2. applyStateChange פותח מקטע עם started_at עתידי, וכל הודעה אמיתית
//      אחריו נראית מוקדמת ממנו — שומר ה-backfill דוחה אותה. האתר נתקע.
//   3. cycle_last_ts נקבע לעתיד, וכל עדכון מונה מסווג כ-backfill. המונה קופא.
//
// ============================================================
// היישור והקשר שלו ל-dedup — הנקודה העדינה כאן
// ============================================================
// מפתח ה-dedup בשרת בנוי על חותם הזמן. יישור ל"עכשיו" הופך את החותם לתלוי
// ב*רגע הקליטה*, ולכן מסירה חוזרת של QoS-1 (או ניסיון חוזר של הסוכן) הייתה
// מקבלת חותם אחר — ונכנסת כפעולה **שנייה**.
//
// לכן היישור לבדו אינו מספיק: `operations` שומרת עכשיו **שני** זמנים —
//   occurred_at  = הזמן המיושר. זהו זמן ה"אמת" של השרת, וממנו נגזרים סדר,
//                  זמינות, דליים וסטטיסטיקה.
//   reported_at  = מה שהסוכן אמר, byte-for-byte. **הוא מפתח ה-dedup**, והוא
//                  קבוע לחלוטין על פני מסירות חוזרות.
// כך מתקיימים שני התנאים יחד: אפס אובדן (מיישרים ומקבלים) ואפס כפילויות
// (מזהים לפי מה שלא משתנה).

/** מעבר לזה בעתיד — דחייה. מתחת לזה — יישור. */
const FUTURE_CLAMP_MAX_SECONDS = 300;          // 5 דקות

// ============================================================
// ורצפה גם בכיוון העתיד — התיקון שהיה מפצל מעבר MODE אחד לשתיים
// ============================================================
// בכיוון העבר יש רצפה (PAST_CLAMP_MIN_SECONDS, ראה למטה) כדי לא להרוס חותמים
// נכונים. בכיוון העתיד לא הייתה רצפה בכלל, וזה נראה בטוח — "שום אירוע אמיתי
// אינו קורה בעתיד" — עד שהופעל על תנועה אמיתית.
//
// מה שקרה בפועל: מעבר MODE אחד מייצר שתי הודעות עם **אותו חותם בדיוק**
// (OperationDetector.Process לוקח now פעם אחת ומחתים בו את שתיהן). השרת
// מעבד אותן בזו אחר זו, ולכן "עכשיו" שלו שונה ביניהן בשנייה:
//
//     הסוכן שולח state ו-operation, שניהם בחותם T+1
//     state     מעובד כשהשרת על T    → סטייה +1 לעתיד → יושר ל-T
//     operation מעובד כשהשרת על T+1  → סטייה 0        → נשמר כ-T+1
//
// והתוצאה בלוג: "המצב השתנה ל: מוכן" בשנייה T, ו"הפעולה הסתיימה" בשנייה T+1 —
// כלומר האתר חזר להיות מוכן בזמן שהפעולה עוד פתוחה. סדר שלא יכול לקרות.
// נמצא ב-19 זוגות אמיתיים (אתרים 2438, 1284, 1376, 3513 ועוד).
//
// סטייה של שנייה-שתיים לעתיד אינה סחיפת שעון אלא רעש עיגול והשהיית מסלול,
// והסכנה שהיישור בא למנוע (נעילה עצמית — ראה למטה) מתעוררת רק בסטיות
// משמעותיות: 5 שניות נפתרות מעצמן בהודעה הבאה. הרצפה זהה לסף האזהרה, ולכן
// הכלל פשוט לזכירה: **מה שלא מדווח כסטייה — לא נוגעים בו.**
const FUTURE_CLAMP_MIN_SECONDS = 5;

// ============================================================
// והכיוון השני: שעון שמפגר
// ============================================================
// שני הכיוונים אינם סימטריים מבחינת סיכון, ולכן יש להם שני קבועים נפרדים —
// כדי שאפשר יהיה לכייל את המסוכן מביניהם בלי לגעת בבטוח.
//
//   • **עתיד = חד-משמעי.** שום אירוע אמיתי אינו קורה בעתיד. חותם עתידי הוא
//     תמיד תקלת שעון, ולכן יישור שלו בטוח לחלוטין.
//
//   • **עבר = דו-משמעי.** חותם ישן יכול להיות שעון מפגר *או* backfill אמיתי
//     (אירוע שקרה בזמן נפילה והגיע באיחור). מההודעה עצמה אי אפשר להבחין.
//
// לכן ליישור-לאחור יש שתי הגנות:
//   1. תקרה: מעל PAST_CLAMP_MAX_SECONDS לא מיישרים בכלל. שם חי ה-backfill
//      האמיתי (נמדד: גל השלמה של 14.5 שעות), והוא נשאר כפי שהוא.
//   2. חלון פריקה: גם *מתחת* לתקרה לא מיישרים אם אנחנו כרגע פורקים תור
//      (allowPastClamp=false — ראה replay-window.js).
//
// מה שנשאר חשוף במכוון: backfill קצר (עד PAST_CLAMP_MAX_SECONDS) שמגיע בשגרה
// ולא בחלון פריקה — הוא ייושר, והשגיאה חסומה בגודל התקרה. הפשרה הזו מכוונת:
// שעון מפגר פוגע ב**כל** הודעה מהאתר, תמיד; backfill קצר הוא אירוע נדיר.
// מתקנים את הכרוני, וסופגים שגיאה חסומה בנדיר.
//
// 300 שניות ולא פחות, כי אתר 2439 נמדד עם פיגור של עד 235 שניות — תקרה נמוכה
// יותר לא הייתה מתקנת אותו בכלל.
const PAST_CLAMP_MAX_SECONDS = 300;            // 5 דקות

// ============================================================
// ולמה יש גם *רצפה* — התיקון שהיה מקלקל במקום לתקן
// ============================================================
// הגרסה הראשונה יישרה **כל** חותם מהעבר עד התקרה, וזה נראה הגיוני עד שהופעל
// על תנועה אמיתית. מה שקרה בפועל, בשורת לוג אחת:
//
//     אתר 3513: שעון מפגר ב-1s — החותם יושר לזמן השרת
//
// הפיגור הזה איננו סחיפת שעון. הוא **השהיית המסלול**: האירוע קרה, הסוכן דגם
// אותו (עד שנייה), פרסם, וההודעה עברה Mosquitto → HiveMQ → השרת. פיגור של
// שנייה-שתיים הוא הזמן הנכון של האירוע, והחותם המקורי הוא המדויק מבין השניים.
// יישור שלו מחליף זמן *נכון* בזמן ההגעה — כלומר מוריד את הדיוק, בכל הודעה,
// בכל אתר תקין. הפוך בדיוק מהמטרה.
//
// לכן יש רצפה: מתחתיה מניחים השהיית מסלול ולא נוגעים. הערכים שנמדדו באתרים
// תקינים היו 1-6 שניות, ולכן 30 שניות הן פי כמה מהרעש הטבעי ועדיין רחוק מתחת
// לפיגור של 2439 (62 שניות במינימום).
//
// התוצאה: היישור-לאחור פועל רק בחלון [30s, 300s] — צר, ובדיוק שם שבו פיגור
// אינו מוסבר עוד כהשהיית רשת אבל גם אינו נראה כמו backfill אמיתי.
const PAST_CLAMP_MIN_SECONDS = 30;

/** סחיפה שמעבר לה מתריעים בלוג, גם כשהיא נסבלת ומיושרת. */
const SKEW_WARN_SECONDS = 5;

/**
 * מרווח חסד לפני זמן הרישום. הרישום והדיווח הראשון קורים בשניות זה מזה,
 * ושעוני השרת והאתר אינם זהים — בלי המרווח הדיווח הראשון של אתר חדש נדחה.
 */
const REGISTRATION_GRACE_SECONDS = 120;

// גבולות שפיות מוחלטים. חותם מחוץ להם אינו "סחיפה" — הוא ערך לא-מאותחל
// (אפוק-אפס), חותם במילישניות שנשלח בטעות, או זיכרון זבל.
const MIN_TIMESTAMP = 1577836800;   // 2020-01-01T00:00:00Z
const MAX_TIMESTAMP = 4102444800;   // 2100-01-01T00:00:00Z

/**
 * מסווג חותם זמן של הודעה מהאתר. פונקציה טהורה — בלי DB ובלי שעון.
 *
 * @param timestampSec   החותם מההודעה, ב-unix **שניות** (חוזה הסוכן).
 * @param nowMs          "עכשיו" לפי השרת, במילישניות.
 * @param registeredAtMs זמן רישום האתר במילישניות, או null.
 * @param opts.allowPastClamp  האם מותר ליישר חותם מהעבר. false בחלון פריקת
 *                             תור, שבו חותם ישן הוא כמעט תמיד backfill אמיתי.
 *                             ברירת המחדל false — הזהירה.
 * @returns {{action:"accept"|"clamp"|"reject", effectiveSec:number|null,
 *            reason:string|null, skewSeconds:number, warn:boolean,
 *            classification:"ok"|"drift_future"|"drift_past"|"backfill"}}
 */
function classifyTimestamp(timestampSec, nowMs, registeredAtMs = null, opts = {}) {
  const allowPastClamp = opts.allowPastClamp === true;
  const nowSec = Math.floor(nowMs / 1000);

  // --- דרגה 1: בכלל מספר? בכלל בטווח אנושי? ---
  if (!Number.isFinite(timestampSec)) {
    return reject(`חותם זמן אינו מספר (${timestampSec})`, 0);
  }
  if (timestampSec < MIN_TIMESTAMP) {
    // כולל אפוק-אפס (0) ואת מקרה "שעון שלא אותחל".
    return reject(`חותם זמן לפני 2020 (${timestampSec}) — שעון לא מאותחל`, timestampSec - nowSec);
  }
  if (timestampSec >= MAX_TIMESTAMP) {
    // הביטוי הרגיל של חותם שנשלח במילישניות במקום בשניות.
    return reject(`חותם זמן אחרי 2100 (${timestampSec}) — כנראה מילישניות`, timestampSec - nowSec);
  }

  const skewSeconds = timestampSec - nowSec;   // חיובי = בעתיד

  // --- דרגה 2: רחוק מדי בעתיד ---
  if (skewSeconds > FUTURE_CLAMP_MAX_SECONDS) {
    return reject(
      `חותם זמן ${skewSeconds}s בעתיד (מיישרים עד ${FUTURE_CLAMP_MAX_SECONDS}s)`, skewSeconds);
  }

  // --- דרגה 2: לפני שהאתר בכלל נרשם ---
  if (registeredAtMs !== null && Number.isFinite(registeredAtMs)) {
    const beforeRegistration = Math.floor(registeredAtMs / 1000) - timestampSec;
    if (beforeRegistration > REGISTRATION_GRACE_SECONDS) {
      return reject(`חותם זמן ${beforeRegistration}s לפני רישום האתר`, skewSeconds);
    }
  }

  const warn = Math.abs(skewSeconds) >= SKEW_WARN_SECONDS;

  // --- עתיד: מיישרים לשנייה השלמה הנוכחית, אך רק מעל הרצפה ---
  // מעגלים לשנייה שלמה כי החוזה הוא unix-שניות; חותם ברזולוציית מילישניות
  // היה נראה "חדש יותר" מכל resync של הסוכן ומחזיר את בעיית ה-backfill.
  if (skewSeconds > 0) {
    // מתחת לרצפה זה רעש, לא סחיפה. יישור כאן היה מפצל שתי הודעות של אותו
    // מעבר MODE לשתי שניות שונות — ראה ההסבר ליד FUTURE_CLAMP_MIN_SECONDS.
    if (skewSeconds <= FUTURE_CLAMP_MIN_SECONDS) {
      return {
        action: "accept", effectiveSec: timestampSec, reason: null,
        skewSeconds, warn, classification: "ok",
      };
    }
    return {
      action: "clamp", effectiveSec: nowSec, reason: null,
      skewSeconds, warn, classification: "drift_future",
    };
  }

  const behindSeconds = -skewSeconds;

  // --- עבר עמוק: זה איננו סחיפה, זה backfill. לא נוגעים. ---
  if (behindSeconds > PAST_CLAMP_MAX_SECONDS) {
    return {
      action: "accept", effectiveSec: timestampSec,
      reason: `חותם ${behindSeconds}s בעבר — מעל תקרת היישור, מטופל כ-backfill`,
      skewSeconds, warn, classification: "backfill",
    };
  }

  // --- פיגור בחלון היישור: יותר מהשהיית מסלול, פחות מ-backfill ---
  if (behindSeconds > PAST_CLAMP_MIN_SECONDS) {
    // בחלון פריקת תור מעדיפים לשמר: כאן חותם ישן הוא כמעט תמיד אירוע אמיתי
    // שמגיע באיחור, וליישר אותו פירושו למחוק את זמן ההתרחשות שלו לתמיד.
    if (!allowPastClamp) {
      return {
        action: "accept", effectiveSec: timestampSec,
        reason: `חותם ${behindSeconds}s בעבר בתוך חלון פריקה — נשמר כפי שהוא`,
        skewSeconds, warn, classification: "backfill",
      };
    }
    // בשגרה, פיגור בגודל הזה אינו מוסבר כהשהיית רשת — זה שעון מפגר.
    return {
      action: "clamp", effectiveSec: nowSec, reason: null,
      skewSeconds, warn, classification: "drift_past",
    };
  }

  // --- פיגור רדוד, או בדיוק עכשיו: זו השהיית המסלול. החותם המקורי מדויק יותר ---
  return {
    action: "accept", effectiveSec: timestampSec, reason: null,
    skewSeconds, warn, classification: "ok",
  };
}

const reject = (reason, skewSeconds) =>
  ({ action: "reject", effectiveSec: null, reason, skewSeconds, warn: true,
     classification: "reject" });

module.exports = {
  classifyTimestamp,
  FUTURE_CLAMP_MAX_SECONDS,
  FUTURE_CLAMP_MIN_SECONDS,
  PAST_CLAMP_MAX_SECONDS,
  PAST_CLAMP_MIN_SECONDS,
  SKEW_WARN_SECONDS,
  REGISTRATION_GRACE_SECONDS,
  MIN_TIMESTAMP,
  MAX_TIMESTAMP,
};
