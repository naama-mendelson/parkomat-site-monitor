// שערי ה-parity קוראים את אותו נתון פעמיים — פעם דרך זרוע השרת ופעם
// דרך הזרוע הישירה — ומשווים. שתי הקריאות אינן בו-זמנית, ולכן כל כתיבה
// שנכנסת ביניהן נראית כמו **הבדל בין הזרועות**.
//
// ⚠️ הגנת ה-lag הקיימת סוגרת את קצה הטווח 15 שניות אחורה, וזה מכסה
// פעולה שנוצרת עכשיו ונושאת חותם של עכשיו. **היא אינה מכסה מסירה חוזרת:**
// כשהשרת עולה, HiveMQ מוסר את כל מה שהצטבר — עם החותמים **המקוריים**.
// כלומר שורות עם occurred_at מלפני שעות נכתבות ברגע זה, וטווח עבר משתנה
// מתחת לשתי הזרועות. שום חלון לא יעזור שם.
//
// נמדד: 11 הבדלים מתוך 860, כולם על אתר אחד שפעל באותו רגע, וכולם באותו
// כיוון — הזרוע שקראה מאוחר יותר ראתה פעולה אחת יותר.
//
// ============================================================
// ⚠️ למה "לא ידוע" ולא "עבר"
// ============================================================
// הפיתוי הוא להתעלם מהבדלים כשהנתונים זזו. זה הופך את השער לחסר ערך
// בדיוק כשהמערכת עמוסה — כלומר כשהכי חשוב שיעבוד.
//
// לכן שלוש תוצאות ולא שתיים: **עבר** / **נפל** / **לא ניתן להשוות**.
// השלישית יוצאת בקוד 2, ו-gates.js מדווח עליה כ"לא רץ" — אותה הפרדה
// שכבר קיימת שם עבור שער שחסרים לו אישורים. אין ידיעה, וזה נאמר.

/**
 * צילום מצב של הטבלאות שהשערים משווים.
 *
 * ⚠️ MAX(id) ולא COUNT(*): מחיקה והוספה באותו רגע היו משאירות ספירה זהה,
 * ו-id עולה מונוטונית ואינו חוזר. זול הרבה יותר גם — אינדקס במקום סריקה.
 */
async function snapshot(db) {
  const [ops, hist] = await Promise.all([
    db.prepare("SELECT COALESCE(MAX(id), 0)::int AS m FROM operations").get(),
    db.prepare("SELECT COALESCE(MAX(id), 0)::int AS m FROM status_history").get(),
  ]);
  return `${ops.m}/${hist.m}`;
}

/**
 * מריץ השוואה, ומוודא שהנתונים לא זזו תוך כדי.
 *
 * @param db        מודול המסד
 * @param run       הפונקציה שמריצה את ההשוואה בפועל
 * @param attempts  כמה ניסיונות לפני שמוותרים
 * @returns {{stable: boolean, marker: string}}
 *
 * ⚠️ הניסיון החוזר מריץ את ההשוואה **כולה** מחדש ולא רק בודק שוב: השוואה
 * שנעשתה על נתונים שזזו אינה ניתנת לתיקון בדיעבד, רק לחזרה.
 */
async function runStable(db, run, attempts = 3) {
  let marker = "";
  for (let i = 0; i < attempts; i++) {
    const before = await snapshot(db);
    await run();
    const after = await snapshot(db);
    marker = `${before} → ${after}`;

    if (before === after) return { stable: true, marker };

    if (i < attempts - 1) {
      console.log(`   ⏳ נתונים נכתבו תוך כדי ההשוואה (${marker}) — מריץ שוב`);
      // שהות קצרה: מסירה חוזרת מגיעה בפרצים, ולא ברצף אחיד.
      await new Promise((r) => setTimeout(r, 2500));
    }
  }
  return { stable: false, marker };
}

module.exports = { snapshot, runStable };
