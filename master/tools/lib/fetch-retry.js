// tools/lib/fetch-retry.js — fetch שחוזר על **כשל רשת בלבד**.
//
// ============================================================
// למה זה קיים
// ============================================================
// שערי ה-PostgREST מדפדפים על אלפי שורות, כלומר עשרות בקשות רצופות. נמדד:
// כשכל השערים רצים יחד, `parity-insights` נפל על `fetch failed` — ולבדו,
// מיד אחרי, עבר עם 80 השוואות ו-0 הבדלים. כלומר תקלת רשת חולפת, לא רגרסיה.
//
// ⚠️ וזה בדיוק הכשל שהופך שער לרעש. `gates.js` כבר מתעד את הכלל: שער שנופל
// כי הרשת קרטעה הוא שער שאנשים לומדים להתעלם ממנו — ואז גם נפילה אמיתית
// נקראת "כנראה שוב הרשת".
//
// ============================================================
// ⚠️ מה **לא** חוזר, וזה העיקר
// ============================================================
// חוזרים רק על שגיאת רשת — `fetch` שזרק, כלומר הבקשה לא הגיעה או נותקה
// באמצע. תשובת HTTP, גם 401 וגם 500, מוחזרת כמות שהיא ואינה מנוסה שוב:
//
//   • 401 פירושו שההתחברות נכשלה — חזרה עליו רק תאריך את הכשל בשקט.
//   • 500 מהמסד הוא ממצא, ובדיוק סוג הממצא שהשער נועד לתפוס.
//
// חזרה על סטטוסים הייתה הופכת את השער ממדידה לניחוש.
const ATTEMPTS = 3;
const BACKOFF_MS = [300, 900];

/** כמו fetch, אך עם חזרה על ניתוקים חולפים. חתימה זהה. */
async function fetchRetry(url, options) {
  let last;
  for (let i = 0; i < ATTEMPTS; i++) {
    try {
      return await fetch(url, options);
    } catch (err) {
      last = err;
      // ⚠️ AbortError אינו תקלה חולפת אלא ביטול מכוון — חזרה עליו מתעלמת
      // מהבקשה של מי שביטל.
      if (err.name === "AbortError") throw err;
      if (i < ATTEMPTS - 1) {
        console.error(`   רשת נכשלה (${err.message}) — ניסיון ${i + 2}/${ATTEMPTS}`);
        await new Promise((r) => setTimeout(r, BACKOFF_MS[i]));
      }
    }
  }
  throw last;
}

module.exports = { fetchRetry };
