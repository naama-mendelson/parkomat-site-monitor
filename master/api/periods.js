// api/periods.js — הגדרת התקופות (שבוע / חודש / שנה).
//
// ============================================================
// למה זה מודול נפרד, ולא הועתק פעמיים
// ============================================================
// גם ה-API של הדשבורד וגם עוזר ה-AI צריכים לתרגם "חודש" לטווח תאריכים. אם כל
// אחד היה מחזיק עותק משלו, הם היו נפרדים ביום שבו מישהו יתקן אחד מהם — והבוט
// היה מדווח מספרים ש**אינם תואמים למסך שהמשתמש מסתכל בו באותו רגע**. משתמש
// שרואה 24 פעולות בדשבורד ושומע מהבוט 31 לא יאמין לאף אחד מהם, ובצדק.
//
// מקור אמת אחד. הקוד הועבר לכאן כמות שהוא — בלי שינוי התנהגות.
// ============================================================

// גבולות התקופה הנבחרת + התקופה הקודמת המקבילה.
// הגבולות קלנדריים ומחושבים בשעון המקומי (השרת רץ בישראל), ומומרים ל-ISO לשאילתות.
//
// ============================================================
// ⚠️ `now` הוא פרמטר — אחרת אי אפשר לבדוק את זה באמת
// ============================================================
// הפונקציה קראה `new Date()` בעצמה, ולכן כל בדיקה רצה **על התאריך של
// היום בלבד**. וזה נכשל בפועל: ב-30/08/2026 "חצות לפני 29 יום" הוא
// במקרה ה-1 בחודש, כלומר ההגדרה הנכונה וההגדרה השגויה מתלכדות —
// ובדיקה שרצה רק על היום הזה **אינה יכולה להבחין ביניהן**. בדיקת מוטציה
// הוכיחה את זה: החזרתי את הבאג הישן והבדיקה עברה.
//
// ברירת המחדל שומרת על כל הקוראים הקיימים כמות שהם; רק הבדיקות מזריקות.
function resolvePeriod(period, now = new Date()) {
  const iso = (d) => d.toISOString();

  // ============================================================
  // "חודש" = 30 הימים האחרונים, ולא "מה-1 בחודש"
  // ============================================================
  // קודם החלון התחיל ב-1 בחודש הנוכחי, וזו הייתה תקלת תצוגה אמיתית: ב-3
  // בחודש המסך הראה **שלושה ימים** תחת הכותרת "חודש". בתחילת כל חודש כל
  // המדדים קרסו לכמעט-אפס נתונים, ואז תפחו לאורכו — בלי שקרה שום דבר בשטח.
  //
  // חלון מתגלגל של 30 יום נותן תמיד את אותה כמות זמן, ולכן הוא גם בר-השוואה
  // מול 30 הימים שלפניו. זו בדיוק הסיבה ש'שבוע' כבר מוגדר כ-7 ימים מתגלגלים
  // ולא כ"מיום ראשון"; החודש פשוט לא יושר אליו.
  //
  // ⚠️ 30 קבוע ולא "חודש קלנדרי אחורה". `new Date(y, m - 1, d)` נראה נכון
  // יותר, אבל אורך החלון שלו משתנה לפי החודש — ונמדד: 31 בינואר → 31 ימים,
  // 31 במאי → 30, **31 במרץ → 28** (הבקשה היא 31 בפברואר, ו-JS מגלגל אותה
  // ל-3 במרץ). כלומר החלון היה מתכווץ ומתרחב בלי סיבה, ובדיוק כמו קודם
  // ההשוואה בין תקופות הייתה בין אורכים שונים. 30 קבוע — אין מקרי קצה.
  //
  // מיושר לחצות מקומית, מאותו טעם כמו בשבוע: חלון שמתחיל בשעה שרירותית
  // יוצר ימים חלקיים בשני הקצוות ומעוות את הדליים היומיים.
  if (period === "month") {
    const from = new Date(now.getFullYear(), now.getMonth(), now.getDate() - 29);
    const prevFrom = new Date(now.getFullYear(), now.getMonth(), now.getDate() - 59);
    return {
      period: "month",
      label: "30 הימים האחרונים",
      comparisonLabel: "לעומת 30 הימים הקודמים",
      granularity: "day",
      range: { from: iso(from), to: iso(now) },
      prev: { from: iso(prevFrom), to: iso(from) },   // 30 הימים הקלנדריים שלפני כן
    };
  }

  if (period === "year") {
    const from = new Date(now.getFullYear(), 0, 1);                    // 1 בינואר
    const prevFrom = new Date(now.getFullYear() - 1, 0, 1);
    return {
      period: "year",
      label: String(now.getFullYear()),
      comparisonLabel: `לעומת ${now.getFullYear() - 1}`,
      granularity: "month",
      range: { from: iso(from), to: iso(now) },
      prev: { from: iso(prevFrom), to: iso(from) },   // השנה הקודמת במלואה
    };
  }

  // ברירת מחדל: שבוע — 7 ימים קלנדריים כולל היום, מיושר לחצות.
  // חשוב: חלון שמתחיל בשעה שרירותית (now פחות 168 שעות) יוצר ימים חלקיים
  // בשני הקצוות, והדלי של *היום* נופל מחוץ לסדרה — כך אבדו פעולות ותקלות של היום.
  const from = new Date(now.getFullYear(), now.getMonth(), now.getDate() - 6);
  const prevFrom = new Date(now.getFullYear(), now.getMonth(), now.getDate() - 13);
  return {
    period: "week",
    label: "7 הימים האחרונים",
    comparisonLabel: "לעומת השבוע הקודם",
    granularity: "day",
    range: { from: iso(from), to: iso(now) },
    prev: { from: iso(prevFrom), to: iso(from) },   // 7 הימים הקלנדריים שלפני כן
  };
}

module.exports = { resolvePeriod };
