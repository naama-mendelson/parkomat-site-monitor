// auth/provider.js — שכבת ההפשטה מעל ספק האימות.
//
// ============================================================
// אותה תבנית בדיוק כמו ai/provider.js, ומאותה סיבה
// ============================================================
// שם ההפשטה קיימת כי סביר שנחליף את Groq. כאן היא קיימת כי אנחנו רוצים
// *לשמור את היכולת* לעזוב את Supabase Auth — וההבדל בין "אפשר יום אחד" ל-
// "אפשר" הוא בדיוק קובץ אחד שנכתב מראש ונבדק.
//
// כל הקוד שמעל הקובץ הזה לא יודע ש-Supabase קיים.
//
//     verifyToken(token) -> { userId, email, role } | null
//
// ============================================================
// ה-seam הוא אימות, לא התחברות — וזה לא שרירותי
// ============================================================
// במצב Supabase ההתחברות קורית **בדפדפן** מול GoTrue, והשרת לעולם לא רואה
// סיסמה. במצב עצמי היא חייבת להיות נקודת קצה בשרת. כלומר התחברות אינה
// סימטרית בין המצבים, ואי אפשר להסתיר אותה מאחורי ממשק אחד בלי לשקר.
//
// מה שכן סימטרי — ונדרש בשרת בשני המצבים — הוא **אימות אסימון**: עבור נתיב
// ה-AI וכל כתיבה שתישאר בשרת. שם עובר ה-seam. זרימות ההתחברות עצמן (טופס,
// איפוס סיסמה, אישור אימייל) הן נקודת השוני שמקבלים אותה במעבר, והיא
// מתועדת ככזו ולא מוסתרת.
//
// ============================================================
// מה שהקובץ הזה **אינו** עושה עדיין
// ============================================================
// שום נתיב חי אינו קורא לו. אין היום משתמשים במערכת כלל — התפקיד בדשבורד
// הוא useState בדפדפן — ולכן אכיפה עכשיו הייתה חוסמת מערכת שאין לה למי
// לתת אסימונים. ההפשטה מונחת לפני האכיפה בכוונה: הנחתה עולה מעט עכשיו,
// והוספתה בדיעבד הייתה נוגעת בכל נתיב.

const supabase = require("./providers/supabase");
const selfhosted = require("./providers/selfhosted");

const PROVIDERS = { supabase, selfhosted };

const active = PROVIDERS[process.env.AUTH_PROVIDER || "supabase"];

if (!active) {
  throw new Error(
    `auth: ספק לא מוכר "${process.env.AUTH_PROVIDER}". קיימים: ${Object.keys(PROVIDERS).join(", ")}`
  );
}

module.exports = {
  // async: ספק Supabase מאמת ES256 מול מפתח ציבורי שנמשך מ-JWKS.
  verifyToken: (token) => active.verifyToken(token),
  isConfigured: () => active.isConfigured(),
  info: () => ({ provider: active.name, configured: active.isConfigured() }),

  // נחשף לבדיקות החוזה: אותם מקרים רצים מול **שני** הספקים, כדי שהמסלול
  // הרדום לא ירקב. ראה tests/auth-provider.test.js.
  _providers: PROVIDERS,
};
