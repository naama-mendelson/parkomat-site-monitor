// db/single-instance.js — מוודא ששרת אחד בלבד רץ מול מסד נתונים אחד.
//
// ============================================================
// למה זו אכיפה ולא הערה בתיעוד
// ============================================================
// `mqtt/subscriber.js` משתמש ב-clientId **קבוע** עם `clean:false` — וזה מכוון,
// זה מה שמאפשר ל-HiveMQ לשמור את התור בזמן שהשרת למטה. אבל MQTT דורש
// clientId ייחודי, ולכן שני תהליכים מנתקים זה את זה **בלולאה אינסופית** ואף
// אחד מהם לא מעבד כלום. הלוג מראה `connected → connection closed → reconnecting`
// בלי סוף.
//
// ⚠️ והתסמין מטעה: זה נראה בדיוק כמו "השרת החדש לא עובד", כשהבעיה היא שהישן
// עדיין חי. זה קרה בפרודקשן, וזה קרה שוב תוך כדי פיתוח — פעמיים.
//
// ⚠️ ומקרה גרוע יותר: שני תהליכים עם `MASTER_CLIENT_ID` **שונה** לא מתנגשים
// כלל. שניהם קולטים, שניהם כותבים, והנתונים נהרסים בשקט — בלי שום לולאה
// בלוג שתסגיר את זה. נעילה על המסד תופסת גם את המקרה הזה, כי היא לא תלויה
// ב-MQTT בכלל.
//
// ============================================================
// ⚠️ למה נעילה במסד ולא קובץ נעילה או תפיסת פורט
// ============================================================
// קובץ נעילה או `listen` על פורט תופסים **רק כפילות על אותו מחשב**. הסכנה
// האמיתית כאן חוצה מחשבים: השרת במשרד (Docker) והרצה ידנית על העמדה מדברים
// אל **אותו** מסד ואל אותו HiveMQ, ואף אחד מהם לא רואה את השני.
//
// `pg_try_advisory_lock` נתפס במסד עצמו, כלומר בדיוק במקום שבו שניהם נפגשים.
// בונוס: הנעילה משוחררת **אוטומטית כשה-session נסגר** — כולל קריסה, כולל
// `kill -9`. אין נעילה תקועה שצריך לנקות ביד, וזה בדיוק מה שהופך קובץ נעילה
// למטרד אחרי כל קריסה.
//
// ============================================================
// ⚠️ חיבור session (5432) ולא ה-pool (6543) — וזה לא פרט
// ============================================================
// `pg_try_advisory_lock` ברמת session נשמר כל עוד ה-session חי. מול ה-
// transaction pooler כל שאילתה עלולה לנחות על backend אחר, ולכן הנעילה הייתה
// נתפסת ומשוחררת מיד — כלומר "עוברת" תמיד ולא מגינה על כלום. אותו נימוק
// בדיוק שבגללו הסכמה רצה על 5432 (ראה db.js).
const { Client } = require("pg");
const db = require("./db");

// מזהה שרירותי אך קבוע. שני מספרים של 32 ביט, כפי ש-Postgres מצפה בגרסה
// הדו-ארגומנטית — קריא יותר במקום מספר 64 ביט אחד.
const LOCK_KEY_1 = 0x7061726b;   // "park"
const LOCK_KEY_2 = 0x6d617374;   // "mast"

let holder = null;

/**
 * הכתובת שהנעילה נתפסת עליה — חיבור session (5432) ולא ה-transaction pooler.
 * מיוצאת כדי שהשער יוכל לאמת את זה **מבנית**, ולא לנחש מהתנהגות הניתוב.
 */
const sessionUrlFor = (connectionString) => connectionString.replace(":6543/", ":5432/");

/**
 * תופס את הנעילה, או זורק אם שרת אחר מחזיק בה.
 * מחזיר פונקציית שחרור (לכיבוי מסודר; קריסה משחררת מעצמה).
 *
 * `keys` — **לשער הבדיקה בלבד.** השער חייב לתפוס נעילה, לוודא ששנייה
 * נדחית, ולשחרר; עם המפתח האמיתי הוא היה מתנגש בשרת החי ונופל בכל פעם
 * שהמערכת עובדת כשורה — כלומר שער שאי אפשר להריץ בדיוק כשהכול תקין.
 * בקוד הייצור אף אחד אינו מעביר את הארגומנט הזה.
 */
// ============================================================
// ⚠️ פינג על **חיבור הנעילה עצמו** — בלעדיו ההגנה מתה אחרי 60 שניות
// ============================================================
// זהו התיקון לבאג שנמדד בפועל: השער שמתחתיו מכריז על מחזיק כ"מת" אחרי
// 60 שניות בסרק, וההנחה שהצדיקה זאת הייתה ש"שרת חי מריץ keep-alive כל 20
// שניות ולכן ה-session שלו לעולם אינו מתיישן".
//
// ⚠️ **ההנחה אינה נכונה לחיבור הזה.** ה-keepalive שב-master.js מחמם את
// חיבורי ה-**pool** (6543). הנעילה יושבת על חיבור **session** נפרד (5432)
// שנפתח פעם אחת, תופס את הנעילה, ואז — לפי התכנון — אינו מריץ עוד שאילתה
// לעולם. `state_change` שלו קופא ברגע העלייה.
//
// התוצאה שנמדדה: דקה אחרי שהשרת עלה, כל תהליך שני רואה את הנעילה שלו
// כתקועה, מריץ `pg_terminate_backend` על ה-session החי, ועולה לצידו. שני
// מאסטרים על אותו clientId — בדיוק מה שהקובץ הזה קיים כדי למנוע, והוא
// עצמו הכלי שמאפשר את זה. נצפה בייצור, לא בתיאוריה.
//
// 20 שניות מול סף של 60 — שלוש החמצות רצופות לפני שמישהו נחשב מת, אותו
// יחס שההערה למטה מתארת.
//
// ⚠️ `unref()` הוא חובה: בלעדיו הטיימר לבדו מחזיק את התהליך חי לנצח,
// והשרת לא יסתיים לעולם ב-Ctrl+C או ב-SIGTERM של Docker.
const LOCK_PING_MS = 20_000;

function startLockPing(client) {
  const id = setInterval(() => {
    // כישלון פינג אינו מפיל דבר: אם החיבור מת, הנעילה ממילא השתחררה,
    // וזו התנהגות נכונה. מה שאסור הוא לזרוק מתוך טיימר.
    client.query("SELECT 1").catch(() => {});
  }, LOCK_PING_MS);
  id.unref?.();
  return () => clearInterval(id);
}

async function acquireSingleInstanceLock(connectionString, keys = [LOCK_KEY_1, LOCK_KEY_2]) {
  const [k1, k2] = keys;
  const sessionUrl = sessionUrlFor(connectionString);

  // ============================================================
  // ⚠️ החיבור עצמו חייב לחזור על עצמו — נמדד, ולא בתיאוריה
  // ============================================================
  // ה-session pooler של Supabase (5432) מנתק חיבורים ביוזמתו: בבדיקה חוזרת
  // ניסיון 1 נפל ב-ECONNRESET וניסיון 2 עבר. בלי חזרה, השרת היה מסרב לעלות
  // בשגיאת רשת מקרית — כלומר **מנגנון ההגנה היה הופך לסיבת ההשבתה**, וזה
  // גרוע יותר מהבעיה שהוא מונע.
  //
  // ⚠️ **החיבור *וגם* שאילתת הנעילה בתוך הניסיון החוזר.** גרסה קודמת עטפה רק
  // את ה-connect, ואז ניתוק חולף בזמן השאילתה עצמה — התרחיש הנפוץ **יותר**,
  // כי היא באה מיד אחרי — הפיל את העלייה בכל זאת.
  //
  // ⚠️ וההבחנה שמחזיקה את זה: חוזרים על **שגיאה שנזרקה**, לא על תוצאה.
  // `pg_try_advisory_lock` שמחזיר false אינו תקלה חולפת אלא התשובה הנכונה,
  // ולכן הוא נבדק מחוץ ללולאה — אחרת "שרת אחר רץ" היה הופך לחמישה ניסיונות
  // מיותרים ואז אותה שגיאה בדיוק.
  const { client, got } = await db.retryTransient(async () => {
    const c = new Client({
      connectionString: sessionUrl,
      ssl: { rejectUnauthorized: false },
      // ⚠️ **אל תסתמכו על השם הזה לזיהוי — הוא אינו שורד את ה-pooler.** נמדד:
      // ב-pg_stat_activity ה-application_name של החיבור הזה הוא "Supavisor",
      // לא מה שנכתב כאן. לכן איתור המחזיק למטה עובר דרך pg_locks על מפתח
      // הנעילה, ולא דרך השם. הוא נשאר כי הוא כן מופיע בלוגים מקומיים.
      application_name: "parkomat-master-instance-lock",
    });

    // ⚠️ **המאזין נרשם מיד אחרי connect ולא בסוף הפונקציה** — וזה היה באג
    // אמיתי כאן. `Client` הוא EventEmitter: ניתוק בלי מאזין ל-'error' מפיל
    // את **כל התהליך** על unhandled error. כשהמאזין נרשם רק אחרי שאילתת
    // הנעילה, כל ניתוק בזמנה הרג את השרת — כלומר מנגנון ההגנה היה הופך
    // לסיבת הקריסה, בדיוק מה שהוא נועד למנוע. וזה לא תיאורטי: נמדד שה-
    // pooler מנתק מיוזמתו בערך בכל בקשה שנייה.
    c.on("error", (err) => {
      console.error("[single-instance] חיבור הנעילה נותק:", err.message);
    });

    // כל ניסיון בונה Client חדש: אחרי ניתוק pg מסמן את הקודם כלא-שמיש.
    await c.connect();
    try {
      const r = await c.query("SELECT pg_try_advisory_lock($1, $2) AS got", [k1, k2]);
      return { client: c, got: r.rows[0].got };
    } catch (err) {
      // ⚠️ סוגרים לפני שזורקים, אחרת כל ניסיון חוזר משאיר חיבור פתוח מאחוריו.
      await c.end().catch(() => {});
      throw err;
    }
  }, "נעילת המופע היחיד");

  // ⚠️ `got === false` **אינו** תקלה חולפת אלא התשובה הנכונה — ולכן הוא נבדק
  // כאן, מחוץ ל-retryTransient. חזרה עליו הייתה הופכת "שרת אחר רץ" להמתנה
  // עיוורת של חמישה ניסיונות ואז אותה שגיאה.
  if (!got) {
    // ⚠️ שולפים מי מחזיק **לפני** שסוגרים, ומוותרים בשקט אם אי אפשר: הודעת
    // הכשל חשובה יותר משלמות האבחון, ובלי זה ההודעה הייתה "משהו תפוס".
    let who = "";
    // ⚠️ שם ייחודי ולא `holder` — כדי לא להסתיר את משתנה המודול שמחזיק
    // את החיבור החי. הצללה שם הייתה משאירה את הנעילה בלי מי שישחרר אותה.
    let stale = null;
    try {
      const { rows: w } = await client.query(`
        SELECT l.pid, a.client_addr::text AS addr, a.backend_start,
               EXTRACT(EPOCH FROM (now() - a.state_change))::int AS idle_seconds
          FROM pg_locks l
          JOIN pg_stat_activity a ON a.pid = l.pid
         WHERE l.locktype = 'advisory'
           AND l.classid = $1 AND l.objid = $2 AND l.granted
         LIMIT 1`, [k1, k2]);
      stale = w[0] || null;
      if (stale) {
        who = `\n   המחזיק: ${stale.addr || "מקומי"} מאז ${stale.backend_start.toISOString()}`;
      }
    } catch { /* אבחון בלבד */ }

    // ============================================================
    // ⚠️ מחזיק **בסרק** אינו שרת — הוא שרת שמת ולא נוקה
    // ============================================================
    // נעילת advisory משוחררת כשה-session נגמר. מול ה-pooler של Supabase
    // `kill` של התהליך **אינו** מסיים את ה-session מיד — הוא נשאר פתוח
    // בצד Postgres, והנעילה איתו.
    //
    // ⚠️ נמדד שוב ושוב היום: 11.5 דקות, ואחר כך 32 דקות, שבהן השרת סירב
    // לעלות עם ההודעה "שרת אחר כבר רץ" **בזמן שלא רץ שום שרת**. וזה בדיוק
    // מה שיקרה בכל `docker compose restart`.
    //
    // ⚠️ **וההבחנה בטוחה, לא ניחוש:** שרת חי מריץ keep-alive של 4 שאילתות
    // כל 20 שניות (master.js), ולכן `state_change` שלו לעולם אינו מתיישן
    // מעבר לזה. סרק של דקה שלמה פירושו שאין מי שיריץ אותן.
    //
    // ⚠️ והסף הוא 60ש' ולא 25ש': שלוש החמצות רצופות של ה-keep-alive, ולא
    // אחת. עומס חולף או ניתוק חולף לא יוציאו שרת חי מהמשחק.
    const STALE_AFTER_SECONDS = 60;
    if (stale && stale.idle_seconds >= STALE_AFTER_SECONDS) {
      console.warn(
        `[single-instance] נעילה בסרק ${stale.idle_seconds}ש' (pid ${stale.pid}) — ` +
        "שרת קודם שנהרג ולא נוקה. משחרר וממשיך."
      );
      try {
        await client.query("SELECT pg_terminate_backend($1)", [stale.pid]);
      } catch (err) {
        console.error("[single-instance] שחרור הנעילה התקועה נכשל:", err.message);
      }

      // ⚠️ ניסיון **אחד** נוסף, ולא לולאה: אם גם הוא נכשל, יש מחזיק אמיתי
      // (או שאין הרשאה לשחרר) — ואז ההודעה למטה היא התשובה הנכונה.
      const retry = await client.query(
        "SELECT pg_try_advisory_lock($1, $2) AS got", [k1, k2]
      ).catch(() => ({ rows: [{ got: false }] }));

      if (retry.rows[0].got) {
        client.on("error", (err) => {
          console.error("[single-instance] חיבור הנעילה נותק:", err.message);
        });
        holder = client;
        const stopPing = startLockPing(client);
        return async () => {
          holder = null;
          stopPing();
          await client.end().catch(() => {});
        };
      }
    }

    await client.end().catch(() => {});
    throw new Error(
      `שרת master אחר כבר רץ מול מסד הנתונים הזה.${who}\n` +
      "   שני תהליכים מנתקים זה את זה ב-MQTT בלולאה, ואף אחד לא קולט הודעות.\n" +
      "   כבי את הקודם, או השתמשי במסד אחר (DATABASE_URL)."
    );
  }

  // ⚠️ החיבור נשאר פתוח בכוונה — הנעילה חיה כל עוד ה-session חי. סגירתו
  // משחררת אותה, ולכן אין כאן `client.end()` בשום מסלול הצלחה.
  //
  // ⚠️ ואם החיבור הזה ינותק אחר כך, הנעילה נופלת איתו והשרת ממשיך לרוץ בלי
  // הגנה עד להפעלה הבאה. מקובל: זה בדיוק המצב שהיה כאן תמיד, והחלופה —
  // להפיל שרת שקולט הודעות כי חיבור צדדי נותק — גרועה יותר.
  //
  // ⚠️ **הפינג כאן ולא רק במסלול השחרור.** זהו המסלול הרגיל — נעילה שנתפסה
  // בניסיון הראשון — כלומר מה שקורה בכל עלייה תקינה בייצור. גרסה ראשונה של
  // התיקון הוסיפה את הפינג רק למסלול השני, ואז ההגנה נשארה מתה בדיוק במקרה
  // הנפוץ. ראה startLockPing למעלה.
  holder = client;
  const stopPing = startLockPing(client);
  return async () => {
    holder = null;
    stopPing();
    await client.end().catch(() => {});
  };
}

module.exports = { acquireSingleInstanceLock, sessionUrlFor, LOCK_KEY_1, LOCK_KEY_2, _holder: () => holder };
